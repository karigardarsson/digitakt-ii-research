// 32 native samples of eight band-limited harmonics with coefficient ramps.
// Selache C ABI: R4 voice, R8 gains[8] plus pitch step, R12 stereo-side out.
.SECTION/PM seg_pmco;
.NOCOMPRESS;
.GLOBAL fold_emit.;
fold_emit.:
    MODIFY(I7,-15) (NW);
    DM(-3,I6) = R8;
    DM(-4,I6) = R9;
    DM(-5,I6) = R10;
    DM(-6,I6) = R11;
    DM(-7,I6) = R12;
    DM(-8,I6) = R13;
    DM(-9,I6) = R14;
    DM(-10,I6) = R15;
    DM(-11,I6) = R4;
    I4 = R12;
    I0 = R4;
    R14 = DM(0,I0);
    R15 = DM(1,I0);
    I5 = R8;
    R0 = DM(8,I5);
    DM(-12,I6) = R0;
    LCNTR = 32, DO _fold_emit_sample UNTIL LCE;
        // Reduce sine and cosine arguments to a quarter cycle.
        R13 = 0x3f800000;
        R9 = 0x3e800000;
        R10 = 0x3f000000;
        F0 = F14 + F9;
        COMP(F0,F13);
        IF GE F0 = F0 - F13;
        F0 = F0 - F10;
        F0 = ABS F0;
        F0 = F9 - F0;
        F1 = F14 - F10;
        F1 = ABS F1;
        F1 = F1 - F9;
        F2 = F0 * F0;
        F3 = F1 * F1;
        R5 = 0x42283c1a;
        R6 = 0xc2996966;
        R7 = 0x42a335e3;
        R8 = 0xc2255de7;
        R9 = 0x40c90fdb;
        F10 = F5 * F2;
        F11 = F5 * F3;
        F10 = F10 + F6;
        F11 = F11 + F6;
        F10 = F10 * F2;
        F11 = F11 * F3;
        F10 = F10 + F7;
        F11 = F11 + F7;
        F10 = F10 * F2;
        F11 = F11 * F3;
        F10 = F10 + F8;
        F11 = F11 + F8;
        F10 = F10 * F2;
        F11 = F11 * F3;
        F10 = F10 + F9;
        F11 = F11 + F9;
        F0 = F0 * F10;
        F1 = F1 * F11;
        R2 = R0;
        R3 = R1;
        R4 = 0;

        R12 = DM(-11,I6);
        R5 = 312;
        R6 = 344;
        R7 = 504;
        R8 = 536;
        R5 = R12 + R5;
        R6 = R12 + R6;
        R7 = R12 + R7;
        R8 = R12 + R8;
        I0 = R5;
        I1 = R6;
        I2 = R7;
        I3 = R8;
        R12 = DM(-3,I6);
        I5 = R12;
        LCNTR = 8, DO _fold_emit_partial UNTIL LCE;
            R5 = DM(I0,M5);
            R6 = DM(I1,M5);
            F7 = F5 * F2;
            F8 = F6 * F3;
            F7 = F7 + F8;
            R8 = DM(I5,M6);
            F7 = F7 * F8;
            F4 = F4 + F7;
            R7 = DM(I2,M6);
            F5 = F5 + F7;
            DM(I0,M6) = R5;
            R7 = DM(I3,M6);
            F6 = F6 + F7;
            DM(I1,M6) = R6;
            F7 = F2 * F1;
            F8 = F3 * F0;
            F7 = F7 + F8;
            F5 = F3 * F1;
            F6 = F2 * F0;
            F3 = F5 - F6;
_fold_emit_partial:
            R2 = R7;
        R12 = 0x3f266666;
        F4 = F4 * F12;
        DM(I4,M6) = R4;
        F14 = F14 + F15;
        COMP(F14,F13);
        IF GE F14 = F14 - F13;
        R12 = DM(-12,I6);
_fold_emit_sample:
        F15 = F15 + F12;
    R4 = DM(-11,I6);
    I0 = R4;
    DM(0,I0) = R14;
    DM(1,I0) = R15;
    R8 = DM(-3,I6);
    R9 = DM(-4,I6);
    R10 = DM(-5,I6);
    R11 = DM(-6,I6);
    R12 = DM(-7,I6);
    R13 = DM(-8,I6);
    R14 = DM(-9,I6);
    R15 = DM(-10,I6);
    MODIFY(I7,15) (NW);
    I12 = DM(M7,I6);
    JUMP (M14,I12) (DB);
    .COMPRESS;
    RFRAME;
    NOP;
