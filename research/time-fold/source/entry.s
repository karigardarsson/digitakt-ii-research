// Uses the existing DigiKit inline voice ABI and the retained SY FANG linear
// stack adapter pattern. Native renderer processes even then odd.
.SECTION/PM seg_pmco;
.NOCOMPRESS;
.GLOBAL _fold_entry;
.EXTERN _di_frame_hw;
.EXTERN _di_trig;
.EXTERN _di_return_out;
.EXTERN fold_track.;
_fold_entry:
    R8 = R0;
    R9 = R2;
    R10 = R4;
    R0 = 1;
    R0 = R8 AND R0;
    IF NE JUMP _fold_odd;
    I5 = _fold_frame;
    R0 = R9 + 1;
    CALL _di_frame_hw;
    DM(I5,M6) = R0;
    R11 = LSHIFT R9 BY 5;
    R1 = LSHIFT R9 BY 4;
    R11 = R11 + R1;
    R1 = 0x6d;
    R11 = R11 + R1;
    R0 = R11;
    CALL _di_frame_hw;
    DM(I5,M6) = R0;
    R0 = R11 + 1;
    CALL _di_frame_hw;
    DM(I5,M6) = R0;
    R1 = 2;
    R0 = R11 + R1;
    CALL _di_frame_hw;
    DM(I5,M6) = R0;
    R1 = 6;
    R0 = R11 + R1;
    CALL _di_frame_hw;
    DM(I5,M6) = R0;
    R1 = 7;
    R0 = R11 + R1;
    CALL _di_frame_hw;
    DM(I5,M6) = R0;
    R1 = 8;
    R0 = R11 + R1;
    CALL _di_frame_hw;
    DM(I5,M6) = R0;
    R1 = 0x1b8;
    R1 = R10 + R1;
    I4 = R1;
    R0 = DM(I4,M5);
    R1 = 255;
    R0 = R0 AND R1;
    DM(I5,M6) = R0;
    R0 = R8;
    CALL _di_trig;
    DM(I5,M6) = R0;
    R0 = 0x15;
    CALL _di_frame_hw;
    R1 = -R9;
    R0 = LSHIFT R0 BY R1;
    R1 = 1;
    R0 = R0 AND R1;
    DM(I5,M6) = R0;

    I3 = _fold_save;
    R0 = I6;
    DM(I3,M6) = R0;
    R0 = I7;
    DM(I3,M6) = R0;
    R0 = L6;
    DM(I3,M6) = R0;
    R0 = L7;
    DM(I3,M6) = R0;
    L6 = 0;
    L7 = 0;
    R0 = _fold_stack;
    R1 = 4092;
    R0 = R0 + R1;
    I7 = R0;
    R4 = R9;
    R8 = _fold_frame;
    R12 = I2;
    R2 = I6;
    CJUMP fold_track. (DB);
    DM(I7,M7) = R2;
    DM(I7,M7) = _fold_back - 1;
_fold_back:
    I3 = _fold_save;
    R0 = DM(I3,M6);
    I6 = R0;
    R0 = DM(I3,M6);
    I7 = R0;
    R0 = DM(I3,M6);
    L6 = R0;
    R0 = DM(I3,M6);
    L7 = R0;
    JUMP _di_return_out;
_fold_odd:
    R0 = I2;
    R1 = -128;
    R0 = R0 + R1;
    I3 = R0;
    LCNTR = 32, DO _fold_copy UNTIL LCE;
    R0 = DM(I3,M6);
_fold_copy:
    DM(I2,M6) = R0;
    JUMP _di_return_out;

.SECTION/DM seg_dmda;
.PKDATA _fold_frame,40;
.PKDATA _fold_save,16;
.PKBSS _fold_stack,4096;
.PKDATA fold_voices.,9472;
