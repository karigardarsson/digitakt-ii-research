// PLAITS for the Digitakt II: Plaits' VirtualAnalogEngine (VA_VARIANT 2) in C99, from the dt2-machine-lab
// translation (MIT, the notice above). Changes from that translation, none of which changes a result on the host:
//   - the pitch reference is 48,000 Hz (Plaits uses kCorrectedSampleRate = 47872.34 Hz, the rate of its STM32 codec
//     clock; on the Digitakt that would play 4.6 cents sharp). a0 = (440 / 8) / 48000 as in plaits/dsp/dsp.h;
//   - int-to-float conversions go through dsp_util.h `itof_nonneg` (equal to the cast for 0 <= i < 2^23; Selache
//     compresses a register-to-register FLOAT into a form the stock DSP code never uses, which the encoding gate
//     refuses);
//   - the shared helpers moved to dsp_util.h; the pitch tables are file-local.
// The host test tests/plaits/test_va_host.py compares it bit for bit with upstream Plaits built at 48,000 Hz.
#include "va.h"
