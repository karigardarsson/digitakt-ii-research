"""Generate lib/noise_sm.s: NOISE's sample loops (engines/noise.c: clocked_render's loop and noise_render's filter
loop) as SISD kernels, bit-identical to selcc's code of the C (-DPL_NOISE_C).

    python3 modules/machines/plaits/src/dsp/lib/gen_noise_kernel.py

Every float operation is the C's, with the same operands in the same order (commutative swaps only); rng_float (the
shift sum of rng_word is the product by 1664525 mod 2^32, as in lib/drums_sm.s), tan_accurate, svf_set_g_q, svf_step,
pl_rsqrt, minf, maxf, absf, the blep helpers and selcc's division are written out; comparisons are selcc's. Two
exact shortcuts: lp_hp_filter_ and bp_filter_[0] get the same arguments every sample (tan_accurate(g_f0), g_q), so
their g_, r_ and h_ are computed once; and r_ = 1 / g_q is the same for all three filters. A pure function of the
same words gives the same words. tests/plaits/test_noise_kernel.py checks the kernels against the C on the concrete
core.
"""

from __future__ import annotations

from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE / "noise_sm.s"

ONE, HALF, MHALF, TWO, QUARTER, FOUR = (
    "0x3F800000",
    "0x3F000000",
    "0xBF000000",
    "0x40000000",
    "0x3E800000",
    "0x40800000",
)
F40, F1_5, MAGIC = "0x42200000", "0x3FC00000", "0x5F3759DF"
TAN = {
    "pi": "0x40490FDB",
    "a": "0x41255DA9",
    "b": "0x42234865",
    "c": "0x4321348F",
    "d": "0x42ACEC90",
    "e": "0x452EFE23",
}

HEADER = """\
// machines/plaits: NOISE's sample loops (engines/noise.c), hand-written SISD kernels.
// Generated by lib/gen_noise_kernel.py; do not edit by hand.
//
// clocked_kernel(ClockedNoise *c, unsigned int *rng, float *k, float *out, int size): clocked_render's loop.
//   c = (phase_, sample_, next_sample_, frequency_); k[0] = the frequency interpolator's increment, k[1] = 2^23 (the
//   bits 0x4B000000), k[2] = 65536.0f, k[3] = 4294967296.0f, k[4] = 2.0f; k[5] is written (selcc's reciprocal of
//   2^32 after its two Newton steps). Writes `size` samples to out, the state back and *rng.
// noise_filter_kernel(Noise *s, const float *k, float *out, float *aux, const float *temp, int size): noise_render's
//   filter loop; k[0..3] = the increments of previous_f0_, previous_f1_, previous_q_, previous_mode_. aux holds the
//   first clocked noise on entry, temp the second; out and aux receive the filters' outputs.
// Both bit-identical to selcc's code of the C (-DPL_NOISE_C): the same operations with the same operands in the same
// order (tests/plaits/test_noise_kernel.py).
//
// State on return: R0-R8, R12, I4 and the flags change; every other register is as on entry (R9-R11, R13-R15 saved
// above I7; I0, I1, I2, I3, M6, L0-L4 pushed through R0, M6 = 1 and L0-L4 = 0 set here). No SIMD.
//
// ABI: as the other kernels (lib/wavetable_sm.s): relies on M5 = 0 and M7 = -1, sets M6 = 1 itself; DAG registers
// are pushed through R0 and restored by loads through I7. Assembled under .COMPRESS.

.SECTION/PM seg_pmco;
.GLOBAL clocked_kernel.;
.GLOBAL noise_filter_kernel.;
.COMPRESS;
"""


class Asm:
    def __init__(self) -> None:
        self.lines: list[str] = []

    def __call__(self, text: str, comment: str = "") -> None:
        line = f"    {text};"
        if comment:
            line = f"{line:<56}// {comment}"
        self.lines.append(line)

    def label(self, name: str) -> None:
        self.lines.append(f"{name}:")

    def div(
        self, res: str, n: str, d: str, y: str, t: str, w: str, comment: str = ""
    ) -> None:
        """res = n / d as selcc divides; w holds 2.0 on entry. res may be w."""
        self(f"{y} = RECIPS {d}")
        self(f"{t} = {d} * {y}", comment or "selcc division")
        self(f"{t} = {w} - {t}")
        self(f"{y} = {y} * {t}")
        self(f"{t} = {d} * {y}")
        self(f"{t} = {w} - {t}")
        self(f"{y} = {y} * {t}")
        self(f"{w} = {n} * {y}")
        self(f"{t} = {d} * {w}")
        self(f"{t} = {n} - {t}")
        self(f"{t} = {t} * {y}")
        self(f"{res} = {w} + {t}")

    def slot(self, reg: str, k: int, comment: str = "") -> None:
        self(f"{reg} = DM({k}, I7)", comment)

    def put(self, k: int, reg: str, comment: str = "") -> None:
        self(f"DM({k}, I7) = {reg}", comment)


DAGS = ["I0", "I1", "I2", "I3", "M6", "L0", "L1", "L2", "L3", "L4"]
SAVES = ["R9", "R10", "R11", "R13", "R14", "R15"]


def prologue(a: Asm, name: str, frame: int) -> None:
    a.label(name)
    for r in DAGS:
        a(f"R0 = {r}")
        a("DM(I7, M7) = R0")
    a("M6 = 1")
    for r in DAGS[5:]:
        a(f"{r} = 0")
    a(f"I7=MODIFY (I7,-{frame})(NW)")
    for i, r in enumerate(SAVES):
        a.put(i + 1, r)


def epilogue(a: Asm, frame: int) -> None:
    for i, r in enumerate(SAVES):
        a.slot(r, i + 1)
    a(f"I7=MODIFY (I7,{frame})(NW)")
    for i, r in enumerate(reversed(DAGS)):
        a(f"{r} = DM({i + 1}, I7)")
    a("I12 = DM(M7, I6)")
    a("JUMP (M14, I12) (DB)")
    a("RFRAME")
    a("NOP")


# ---- clocked_kernel -------------------------------------------------------------------------------------------------
KC = {"INC": 0, "BIG": 1, "C65536": 2, "D32": 3, "TWO": 4, "Y32": 5}
C_CNT = 7
C_FRAME = 7


def rng_float(a: Asm, dst: str) -> None:
    """dst = rng_float(&rng) with the word in R13 (lib/gen_drum_kernels.py rng_float, I4 = k). Uses R4-R8."""
    k = KC
    a("R4 = 1664525")
    a("R5 = 1013904223")
    a(f"R13 = R13 * R4 (SSI), R6 = DM({k['BIG']}, I4)", "rng_word")
    a("R13 = R13 + R5")
    a("R7 = FEXT R13 BY 16:16", "w >> 16")
    a("R8 = FEXT R13 BY 0:16", "w & 0xFFFF")
    a("R7 = R7 OR R6", "itof_nonneg")
    a("R8 = R8 OR R6")
    a(f"F7 = F7 - F6, R5 = DM({k['C65536']}, I4)")
    a("F8 = F8 - F6")
    a(f"F7 = F7 * F5, R5 = DM({k['Y32']}, I4)", "hi * 65536.0f")
    a(f"F7 = F7 + F8, R6 = DM({k['D32']}, I4)", "+ lo")
    a("F8 = F7 * F5", "/ 4294967296.0f: q")
    a("F4 = F6 * F8")
    a("F4 = F7 - F4")
    a("F4 = F4 * F5")
    a(f"{dst} = F8 + F4")


def clocked_kernel() -> str:
    a = Asm()
    prologue(a, "clocked_kernel.", C_FRAME)
    a("I1 = R4", "c")
    a("I2 = R8", "rng")
    a("I4 = R12", "k")
    a("R0 = DM(1, I6)", "out")
    a("I0 = R0")
    a("R0 = DM(2, I6)", "size")
    a.put(C_CNT, "R0")
    # k[Y32] = selcc's reciprocal of 2^32 after its two Newton steps
    a(f"R8 = DM({KC['D32']}, I4)")
    a(f"R4 = DM({KC['TWO']}, I4)")
    a("F9 = RECIPS F8")
    a("F10 = F8 * F9")
    a("F10 = F4 - F10")
    a("F9 = F9 * F10")
    a("F10 = F8 * F9")
    a("F10 = F4 - F10")
    a("F9 = F9 * F10")
    a(f"DM({KC['Y32']}, I4) = R9")
    a(f"R9 = DM({KC['INC']}, I4)", "the increment")
    a("R13 = DM(I2, M5)", "rng")
    a("R15 = DM(0, I1)", "phase_")
    a("R14 = DM(1, I1)", "sample_")
    a("R11 = DM(2, I1)", "next_sample_")
    a("R10 = DM(3, I1)", "frequency_ (the interpolator's value)")
    a("R1 = 0")
    a("COMP(R0, R1)")
    a("IF LE JUMP _ck_done")
    a.label("_ck_loop")
    a("R12 = PASS R11", "this_sample = next_sample")
    a("R11 = 0", "next_sample = 0.0f")
    a("F10 = F10 + F9", "freq = fm.Next()")
    rng_float(a, "F3")
    a(f"R0 = {TWO}")
    a("F3 = F3 * F0", "raw_sample = rng_float(rng) * 2.0f - 1.0f")
    a(f"R0 = {ONE}")
    a("F3 = F3 - F0")
    a(f"R0 = {QUARTER}")
    a("F1 = F10 - F0", "raw_amount = 4.0f * (freq - 0.25f)")
    a(f"R0 = {FOUR}")
    a("F1 = F0 * F1")
    a("R0 = 0")
    a("COMP(F1, F0)", "CONSTRAIN(raw_amount, 0.0f, 1.0f)")
    a("IF LT R1 = R0 OR R0")
    a(f"R0 = {ONE}")
    a("COMP(F1, F0)")
    a("IF GT R1 = R0 OR R0")
    a("F15 = F15 + F10", "phase_ += freq")
    a("COMP(F15, F0)", "phase_ >= 1.0f")
    a("IF LT JUMP _ck_nr")
    a("F15 = F15 - F0", "phase_ -= 1.0f")
    a(f"R4 = {TWO}")
    a.div("F2", "F15", "F10", "F5", "F6", "F4", "t = phase_ / freq")
    a("F0 = F3 - F14", "discontinuity = new_sample - sample")
    a(f"R4 = {HALF}")
    a("F4 = F4 * F2", "ThisBlepSample(t)")
    a("F4 = F4 * F2")
    a("F4 = F0 * F4")
    a("F12 = F12 + F4", "this_sample += discontinuity * ..")
    a(f"R5 = {ONE}")
    a("F5 = F5 - F2", "NextBlepSample(t)")
    a(f"R4 = {MHALF}")
    a("F4 = F4 * F5")
    a("F4 = F4 * F5")
    a("F4 = F0 * F4")
    a("F11 = F11 + F4", "next_sample += discontinuity * ..")
    a("R14 = PASS R3", "sample = new_sample")
    a.label("_ck_nr")
    a("F11 = F11 + F14", "next_sample += sample")
    a("F0 = F3 - F12", "out[i] = this_sample + raw_amount * (raw_sample - this_sample)")
    a("F0 = F1 * F0")
    a("F0 = F12 + F0")
    a("DM(I0, M6) = R0")
    a.slot("R0", C_CNT)
    a("R1 = 1")
    a("R0 = R0 - R1")
    a.put(C_CNT, "R0")
    a("IF NE JUMP _ck_loop")
    a.label("_ck_done")
    a("DM(0, I1) = R15")
    a("DM(1, I1) = R14")
    a("DM(2, I1) = R11")
    a("DM(3, I1) = R10")
    a("DM(I2, M5) = R13")
    epilogue(a, C_FRAME)
    return "\n".join(a.lines) + "\n"


# ---- noise_filter_kernel --------------------------------------------------------------------------------------------
(
    N_K0,
    N_K1,
    N_K2,
    N_K3,
    N_CNT,
    N_G0,
    N_R,
    N_H0,
    N_G1,
    N_H1,
    N_IN1,
    N_IN2,
    N_HPG,
    N_BPG,
    N_LPG,
) = range(7, 22)
N_FRAME = 21
# Noise words: lp_hp_filter_ 8..12, bp_filter_[0] 13..17, bp_filter_[1] 18..22, previous_f0_ 23, previous_f1_ 24,
# previous_q_ 25, previous_mode_ 26.


def tan_accurate(a: Asm, dst: str, f: str) -> None:
    """dst = tan_accurate(f) (lib/drums.h); uses R4-R6 (f kept unless it is one of them; dst may be R4..R6)."""
    a(f"F4 = {f} * {f}", "tan_accurate: f2")
    a(f"R5 = {TAN['e']}")
    a("F5 = F4 * F5")
    a(f"R6 = {TAN['d']}")
    a("F5 = F6 + F5")
    a("F5 = F4 * F5")
    a(f"R6 = {TAN['c']}")
    a("F5 = F6 + F5")
    a("F5 = F4 * F5")
    a(f"R6 = {TAN['b']}")
    a("F5 = F6 + F5")
    a("F5 = F4 * F5")
    a(f"R6 = {TAN['a']}")
    a("F5 = F6 + F5")
    a("F5 = F4 * F5")
    a(f"R6 = {TAN['pi']}")
    a("F5 = F6 + F5")
    a(f"{dst} = {f} * F5")


def svf_step(a: Asm, base: int, g: str, r: str, h: str, x: str) -> None:
    """One svf_step of the filter at Noise word `base` (state_1_ at base + 3, state_2_ at base + 4) on input x:
    F0 = lp, F1 = bp, F2 = hp. g, r, h, x are registers outside R0-R3; uses R0-R3."""
    a(f"R0 = DM({base + 3}, I1)", "svf_step: state_1_")
    a(f"R1 = DM({base + 4}, I1)", "state_2_")
    a(f"F2 = {r} * F0", "h = (in - r_ s1 - g_ s1 - s2) * h_")
    a(f"F2 = {x} - F2")
    a(f"F3 = {g} * F0")
    a("F2 = F2 - F3")
    a("F2 = F2 - F1")
    a(f"F2 = F2 * {h}")
    a(f"F3 = {g} * F2", "b = g_ h + s1")
    a("F3 = F3 + F0")
    a(f"F0 = {g} * F2", "s1 = g_ h + b")
    a("F0 = F0 + F3")
    a(f"DM({base + 3}, I1) = R0")
    a(f"F0 = {g} * F3", "l = g_ b + s2")
    a("F0 = F0 + F1")
    a(f"F1 = {g} * F3", "s2 = g_ b + l")
    a("F1 = F1 + F0")
    a(f"DM({base + 4}, I1) = R1")
    a("R1 = PASS R3", "(bp)")


def noise_filter_kernel() -> str:
    a = Asm()
    prologue(a, "noise_filter_kernel.", N_FRAME)
    a("I1 = R4", "s")
    a("I4 = R8", "k")
    a("I0 = R12", "out")
    a("R0 = DM(1, I6)", "aux")
    a("I2 = R0")
    a("R0 = DM(2, I6)", "temp")
    a("I3 = R0")
    for j, sl in enumerate((N_K0, N_K1, N_K2, N_K3)):
        a(f"R0 = DM({j}, I4)")
        a.put(sl, "R0")
    a("R0 = DM(3, I6)", "size")
    a.put(N_CNT, "R0")
    a("R1 = 0")
    a("COMP(R0, R1)")
    a("IF LE JUMP _nf_done")
    a.label("_nf_loop")
    # the interpolators
    a("R13 = DM(23, I1)")
    a.slot("R0", N_K0)
    a("F13 = F13 + F0", "g_f0 = f0_modulation.Next()")
    a("DM(23, I1) = R13")
    a("R14 = DM(24, I1)")
    a.slot("R0", N_K1)
    a("F14 = F14 + F0", "g_f1")
    a("DM(24, I1) = R14")
    a("R15 = DM(25, I1)")
    a.slot("R0", N_K2)
    a("F15 = F15 + F0", "g_q")
    a("DM(25, I1) = R15")
    # gain = pl_rsqrt((0.5f + g_q) * 40.0f * g_f0)
    a(f"R0 = {HALF}")
    a("F1 = F0 + F15", "(0.5f + g_q) * 40.0f * g_f0")
    a(f"R2 = {F40}")
    a("F1 = F1 * F2")
    a("F1 = F1 * F13")
    a("F3 = F0 * F1", "pl_rsqrt: h = 0.5f * x")
    a("R2 = 0")
    a("COMP(F1, F2)", "x > 0.0f")
    a("IF GT JUMP _nf_rs")
    a("R12 = 0", "gain = 0.0f")
    a("JUMP _nf_rd")
    a.label("_nf_rs")
    a("R2 = -1")
    a("R1 = ASHIFT R1 BY R2", "0x5f3759df - (bits >> 1)")
    a(f"R2 = {MAGIC}")
    a("R12 = R2 - R1")
    a(f"R0 = {F1_5}")
    for _ in range(3):
        a("F1 = F3 * F12", "y = y * (1.5f - h * y * y)")
        a("F1 = F1 * F12")
        a("F1 = F0 - F1")
        a("F12 = F12 * F1")
    a.label("_nf_rd")
    # g, r and h of the filters (lp_hp and bp[0] share g = tan_accurate(g_f0), all share r = 1 / g_q)
    tan_accurate(a, "F9", "F13")
    a.put(N_G0, "R9")
    a(f"R10 = {ONE}")
    a(f"R11 = {TWO}")
    a.div("F10", "F10", "F15", "F4", "F5", "F11", "r_ = 1.0f / resonance")
    a.put(N_R, "R10")
    a("F4 = F10 * F9", "h_ = 1.0f / (1.0f + r_ g_ + g_ g_)")
    a(f"R5 = {ONE}")
    a("F4 = F5 + F4")
    a("F6 = F9 * F9")
    a("F4 = F4 + F6")
    a(f"R11 = {TWO}")
    a.div("F11", "F5", "F4", "F6", "F7", "F11")
    a.put(N_H0, "R11")
    tan_accurate(a, "F9", "F14")
    a.put(N_G1, "R9")
    a("F4 = F10 * F9")
    a(f"R5 = {ONE}")
    a("F4 = F5 + F4")
    a("F6 = F9 * F9")
    a("F4 = F4 + F6")
    a(f"R11 = {TWO}")
    a.div("F11", "F5", "F4", "F6", "F7", "F11")
    a.put(N_H1, "R11")
    # inputs and the mode gains
    a("R0 = DM(I2, M5)")
    a("F0 = F0 * F12", "input_1 = aux[i] * gain")
    a.put(N_IN1, "R0")
    a("R0 = DM(I3, M6)")
    a("F0 = F0 * F12", "input_2 = temp[i] * gain")
    a.put(N_IN2, "R0")
    a("R0 = DM(26, I1)")
    a.slot("R1", N_K3)
    a("F0 = F0 + F1", "mode = mode_modulation.Next()")
    a("DM(26, I1) = R0")
    a("F1 = -F0", "hp_gain = minf(-mode * 2.0f + 1.0f, 0.0f)")
    a(f"R2 = {TWO}")
    a("F1 = F1 * F2")
    a(f"R3 = {ONE}")
    a("F1 = F1 + F3")
    a("R4 = 0")
    a("COMP(F1, F4)")
    a("IF GE R1 = R4 OR R4")
    a.put(N_HPG, "R1")
    a(f"R5 = {HALF}")
    a("F5 = F0 - F5", "bp_gain = 1.0f - 2.0f * absf(mode - 0.5f)")
    a("F6 = -F5")
    a("COMP(F5, F4)")
    a("IF GE R6 = R5 OR R5")
    a("F6 = F2 * F6")
    a("F6 = F3 - F6")
    a.put(N_BPG, "R6")
    a("F7 = F0 * F2", "lp_gain = maxf(1.0f - mode * 2.0f, 0.0f)")
    a("F7 = F3 - F7")
    a("COMP(F7, F4)")
    a("IF LE R7 = R4 OR R4")
    a.put(N_LPG, "R7")
    # lp_hp_filter_: out[i] = hp_gain * hp + bp_gain * bp + lp_gain * lp
    a.slot("R9", N_G0)
    a.slot("R11", N_H0)
    a.slot("R8", N_IN1)
    svf_step(a, 8, "F9", "F10", "F11", "F8")
    a.slot("R4", N_HPG)
    a("F2 = F4 * F2")
    a.slot("R4", N_BPG)
    a("F1 = F4 * F1")
    a("F2 = F2 + F1")
    a.slot("R4", N_LPG)
    a("F0 = F4 * F0")
    a("F2 = F2 + F0")
    a("DM(I0, M6) = R2")
    # bp_filter_[0] on input_1, bp_filter_[1] on input_2: aux[i] = b0 + b1
    svf_step(a, 13, "F9", "F10", "F11", "F8")
    a("R12 = PASS R1", "b0")
    a.slot("R9", N_G1)
    a.slot("R11", N_H1)
    a.slot("R8", N_IN2)
    svf_step(a, 18, "F9", "F10", "F11", "F8")
    a("F1 = F12 + F1", "aux[i] = b0 + b1")
    a("DM(I2, M6) = R1")
    a.slot("R0", N_CNT)
    a("R1 = 1")
    a("R0 = R0 - R1")
    a.put(N_CNT, "R0")
    a("IF NE JUMP _nf_loop")
    # the filters' g_, r_, h_ as the last sample's svf_set_g_q left them
    a.slot("R0", N_G0)
    a.slot("R1", N_R)
    a.slot("R2", N_H0)
    a("DM(8, I1) = R0")
    a("DM(9, I1) = R1")
    a("DM(10, I1) = R2")
    a("DM(13, I1) = R0")
    a("DM(14, I1) = R1")
    a("DM(15, I1) = R2")
    a.slot("R0", N_G1)
    a.slot("R2", N_H1)
    a("DM(18, I1) = R0")
    a("DM(19, I1) = R1")
    a("DM(20, I1) = R2")
    a.label("_nf_done")
    epilogue(a, N_FRAME)
    return "\n".join(a.lines) + "\n"


def main() -> None:
    OUT.write_text(HEADER + "\n" + clocked_kernel() + "\n" + noise_filter_kernel())
    print(OUT)


if __name__ == "__main__":
    main()
