"""Generate lib/sam_sm.s: the SAM speech synth's sample loop (lib/sam_speech_synth.c) as a SISD kernel, bit-identical to
selcc's code of the C loop (-DPL_SAM_C).

    python3 modules/machines/plaits/src/dsp/lib/gen_sam_kernel.py

tests/plaits/test_sam_kernel.py checks it against the C on the concrete core.
"""

from __future__ import annotations

from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE / "sam_sm.s"
ONE, HALF, MHALF, TWO, F16 = (
    "0x3F800000",
    "0x3F000000",
    "0xBF000000",
    "0x40000000",
    "0x41800000",
)

HEADER = """\
// machines/plaits: the SAM speech synth's sample loop (lib/sam_speech_synth.c), hand-written SISD kernel.
// Generated by lib/gen_sam_kernel.py; do not edit by hand.
//
// sam_kernel(SAMSpeechSynth *s, const float *k, float *excitation, float *output, int size): k[0] = the frequency
//   interpolator's increment, k[1..3] = the formant frequencies (unsigned ints), k[4..6] = the same as floats,
//   k[7..9] = the formant amplitudes. Writes excitation and output and the state back (phase_, frequency_,
//   pulse_next_sample_, pulse_lp_, formant_phase_[3]), bit-identical to selcc's code of the C loop (-DPL_SAM_C)
//   (tests/plaits/test_sam_kernel.py).
//
// State on return: R0-R8, R12, I4 and the flags change; every other register is as on entry (R9-R11, R13-R15 saved
// above I7; I0, I1, I2, M6, L0, L1, L2, L4 pushed through R0, M6 = 1 and L0 = L1 = L2 = L4 = 0 set here). No SIMD.
// ABI: as the other kernels (lib/wavetable_sm.s). Assembled under .COMPRESS; integer additions in their 48-bit form.

.SECTION/PM seg_pmco;
.GLOBAL sam_kernel.;
.EXTERN pl_lut_sine.;
.COMPRESS;
"""
DAGS = ["I0", "I1", "I2", "M6", "L0", "L1", "L2", "L4"]
SAVES = ["R9", "R10", "R11", "R13", "R14", "R15"]
KS = list(range(7, 17))
CNT, LUT = 17, 18
FRAME = 18


def kernel() -> str:
    L: list[str] = []

    def a(t: str, c: str = "") -> None:
        line = f"    {t};"
        L.append(f"{line:<56}// {c}" if c else line)

    def lab(n: str) -> None:
        L.append(f"{n}:")

    def iadd(t: str, c: str = "") -> None:
        L.append("    .NOCOMPRESS;")
        a(t, c)
        L.append("    .COMPRESS;")

    def slot(r: str, s: int, c: str = "") -> None:
        a(f"{r} = DM({s}, I7)", c)

    def put(s: int, r: str, c: str = "") -> None:
        a(f"DM({s}, I7) = {r}", c)

    lab("sam_kernel.")
    for r in DAGS:
        a(f"R0 = {r}")
        a("DM(I7, M7) = R0")
    a("M6 = 1")
    for r in DAGS[4:]:
        a(f"{r} = 0")
    a(f"I7=MODIFY (I7,-{FRAME})(NW)")
    for i, r in enumerate(SAVES):
        put(i + 1, r)
    a("I2 = R4", "s")
    a("I4 = R8", "k")
    a("I0 = R12", "excitation")
    a("R0 = DM(1, I6)", "output")
    a("I1 = R0")
    for j, sl in enumerate(KS):
        a(f"R0 = DM({j}, I4)")
        put(sl, "R0")
    a("R0 = pl_lut_sine.")
    put(LUT, "R0")
    a("R0 = DM(2, I6)", "size")
    put(CNT, "R0")
    a("R15 = DM(0, I2)", "phase_")
    a("R9 = DM(1, I2)", "frequency_ (the interpolator's value)")
    a("R14 = DM(2, I2)", "pulse_next_sample")
    a("R13 = DM(3, I2)", "pulse_lp_")
    a("R12 = DM(4, I2)", "formant_phase_[0..2]")
    a("R11 = DM(5, I2)")
    a("R10 = DM(6, I2)")
    a("R1 = 0")
    a("COMP(R0, R1)")
    a("IF LE JUMP _sak_done")
    lab("_sak_loop")
    a("R8 = PASS R14", "pulse_this_sample = pulse_next_sample")
    a("R14 = 0", "pulse_next_sample = 0.0f")
    slot("R0", KS[0])
    a("F9 = F9 + F0", "f = fm.Next()")
    a("F15 = F15 + F9", "phase_ += f")
    a(f"R0 = {ONE}")
    a("COMP(F15, F0)", "phase_ >= 1.0f")
    a("IF LT JUMP _sak_nr")
    a("F15 = F15 - F0", "phase_ -= 1.0f")
    a(f"R4 = {TWO}")
    a("F1 = RECIPS F9", "t = phase_ / f (selcc division)")
    a("F2 = F9 * F1")
    a("F2 = F4 - F2")
    a("F1 = F1 * F2")
    a("F2 = F9 * F1")
    a("F2 = F4 - F2")
    a("F1 = F1 * F2")
    a("F4 = F15 * F1")
    a("F2 = F9 * F4")
    a("F2 = F15 - F2")
    a("F2 = F2 * F1")
    a("F3 = F4 + F2")
    for reg, sl in ((12, KS[4]), (11, KS[5]), (10, KS[6])):
        slot("R1", sl)
        a(
            "F1 = F3 * F1",
            "formant_phase_ = (unsigned int)(int)(t * formant_frequency_f)",
        )
        a(f"R{reg} = TRUNC F1")
    a(f"R0 = {HALF}")
    a("F0 = F0 * F3", "pulse_this_sample -= ThisBlepSample(t)")
    a("F0 = F0 * F3")
    a("F8 = F8 - F0")
    a(f"R0 = {ONE}")
    a("F1 = F0 - F3", "pulse_next_sample -= NextBlepSample(t)")
    a(f"R0 = {MHALF}")
    a("F0 = F0 * F1")
    a("F0 = F0 * F1")
    a("F14 = F14 - F0")
    a("JUMP _sak_ns")
    lab("_sak_nr")
    for reg, sl in ((12, KS[1]), (11, KS[2]), (10, KS[3])):
        slot("R1", sl)
        iadd(f"R{reg} = R{reg} + R1", "formant_phase_ += formant_frequency")
    lab("_sak_ns")
    a("F14 = F14 + F15", "pulse_next_sample += phase_")
    a(f"R0 = {HALF}")
    a("F0 = F8 - F0", "d = pulse_this_sample - 0.5f - pulse_lp_")
    a("F0 = F0 - F13")
    a(f"R1 = {F16}")
    a("F1 = F1 * F9", "pulse_lp_ += minf(16.0f * f, 1.0f) * d")
    a(f"R2 = {ONE}")
    a("COMP(F1, F2)")
    a("IF GE R1 = R2 OR R2")
    a("F1 = F1 * F0")
    a("F13 = F13 + F1")
    a("DM(I0, M6) = R0", "excitation[n] = d")
    a("R6 = -23")
    slot("R7", LUT)
    a("R3 = 0", "sum = 0.0f")
    for reg, sl in ((12, KS[7]), (11, KS[8]), (10, KS[9])):
        a(
            f"R0 = LSHIFT R{reg} BY R6",
            "sum += sine[formant_phase_ >> 23] * formant_amplitude",
        )
        a("R0 = LSHIFT R0 BY 2")
        iadd("R0 = R0 + R7")
        a("I4 = R0")
        slot("R1", sl)
        a("R4 = 0", "(DAG gap)")
        a("R5 = 0")
        a("R0 = DM(I4, M5)")
        a("F0 = F0 * F1")
        a("F3 = F3 + F0")
    a(f"R0 = {ONE}")
    a("F0 = F0 - F15", "sum *= (1.0f - phase_)")
    a("F3 = F3 * F0")
    a("DM(I1, M6) = R3", "output[n] = sum")
    slot("R0", CNT)
    a("R1 = 1")
    iadd("R0 = R0 - R1")
    put(CNT, "R0")
    a("IF NE JUMP _sak_loop")
    lab("_sak_done")
    a("DM(0, I2) = R15")
    a("DM(1, I2) = R9")
    a("DM(2, I2) = R14")
    a("DM(3, I2) = R13")
    a("DM(4, I2) = R12")
    a("DM(5, I2) = R11")
    a("DM(6, I2) = R10")
    for i, r in enumerate(SAVES):
        slot(r, i + 1)
    a(f"I7=MODIFY (I7,{FRAME})(NW)")
    for i, r in enumerate(reversed(DAGS)):
        a(f"{r} = DM({i + 1}, I7)")
    a("I12 = DM(M7, I6)")
    a("JUMP (M14, I12) (DB)")
    a("RFRAME")
    a("NOP")
    return "\n".join(L) + "\n"


def main() -> None:
    OUT.write_text(HEADER + "\n" + kernel())
    print(OUT)


if __name__ == "__main__":
    main()
