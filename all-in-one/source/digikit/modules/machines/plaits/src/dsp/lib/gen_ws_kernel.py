"""Generate lib/ws_sm.s: ASYM-TRI's sample loops (engines/waveshaping.c: slope_render's loop and ws_render's waveshaper
loop) as SISD kernels, bit-identical to selcc's code of the C (-DPL_WS_C).

    python3 modules/machines/plaits/src/dsp/lib/gen_ws_kernel.py

Every operation is the C's, with the same operands in the same order (commutative swaps only); the integrated bleps,
selcc's divisions, ws_table, itof_small, InterpolateHermite and Sine with their range guards (in selcc's comparison
order: a NaN index reads the table at 1.0f in InterpolateHermite and Sine takes a NaN phase as 0) are written out.
tests/plaits/test_ws_kernel.py checks them against the C on the concrete core.
"""

from __future__ import annotations

from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE / "ws_sm.s"
C = {
    "one": "0x3F800000",
    "half": "0x3F000000",
    "mhalf": "0xBF000000",
    "two": "0x40000000",
    "q": "0x3E800000",
    "0.1875": "0x3E400000",
    "1.5": "0x3FC00000",
    "3.9999": "0x407FFE5D",
    "127": "0x42FE0000",
    "128": "0x43000000",
    "512": "0x44000000",
    "2^23": "0x4B000000",
    "-2^23": "0xCB000000",
    "2^31": "0x4F000000",
    "-2^31": "0xCF000000",
}

HEADER = """\
// machines/plaits: ASYM-TRI's sample loops (engines/waveshaping.c), hand-written SISD kernels.
// Generated by lib/gen_ws_kernel.py; do not edit by hand.
//
// slope_kernel(Slope *s, const float *k, float *out, int size): slope_render's loop; k[0..1] = the increments of
//   frequency_ and pw_. Writes out and the state back.
// ws_kernel(WS *s, const float *k, float *out, float *aux, int size): ws_render's loop; k[0..2] = the increments of
//   previous_shape_, previous_wavefolder_gain_, previous_overtone_gain_; k[3..7] = the five waveshaper tables
//   (ws_table 0..4), k[8] = lut_fold + 1, k[9] = lut_fold_2 + 1, k[10] = lut_sine (addresses). out and aux hold the two
//   slopes on entry and receive the folded output and the overtone mix.
// Both bit-identical to selcc's code of the C (-DPL_WS_C) (tests/plaits/test_ws_kernel.py).
//
// State on return: R0-R8, R12, I4 and the flags change; every other register is as on entry (R9-R11, R13-R15 saved
// above I7; I0, I1, I2, M6, L0, L1, L2, L4 pushed through R0, M6 = 1 and L0 = L1 = L2 = L4 = 0 set here). No SIMD.
// ABI: as the other kernels (lib/wavetable_sm.s). Assembled under .COMPRESS; integer additions in their 48-bit form.

.SECTION/PM seg_pmco;
.GLOBAL slope_kernel.;
.GLOBAL ws_kernel.;
.COMPRESS;
"""
DAGS = ["I0", "I1", "I2", "M6", "L0", "L1", "L2", "L4"]
SAVES = ["R9", "R10", "R11", "R13", "R14", "R15"]


class Asm:
    def __init__(self) -> None:
        self.L: list[str] = []

    def __call__(self, t: str, c: str = "") -> None:
        line = f"    {t};"
        self.L.append(f"{line:<56}// {c}" if c else line)

    def lab(self, n: str) -> None:
        self.L.append(f"{n}:")

    def iadd(self, t: str, c: str = "") -> None:
        self.L.append("    .NOCOMPRESS;")
        self(t, c)
        self.L.append("    .COMPRESS;")

    def k(self, r: str, n: str) -> None:
        self(f"{r} = {C[n]}", n)

    def slot(self, r: str, s: int, c: str = "") -> None:
        self(f"{r} = DM({s}, I7)", c)

    def put(self, s: int, r: str, c: str = "") -> None:
        self(f"DM({s}, I7) = {r}", c)

    def div(
        self, res: str, n: str, d: str, y: str, t: str, w: str, c: str = ""
    ) -> None:
        self(f"{y} = RECIPS {d}")
        self(f"{t} = {d} * {y}", c or "selcc division")
        self(f"{t} = {w} - {t}")
        self(f"{y} = {y} * {t}")
        self(f"{t} = {d} * {y}")
        self(f"{t} = {w} - {t}")
        self(f"{y} = {y} * {t}")
        self(f"{w} = {n} * {y}")
        self(f"{t} = {d} * {w}")
        self(f"{t} = {n} - {t}")
        self(f"{t} = {t} * {y}")
        self(f"{res} = {w} + {t}")

    def prologue(self, name: str, frame: int) -> None:
        self.lab(name)
        for r in DAGS:
            self(f"R0 = {r}")
            self("DM(I7, M7) = R0")
        self("M6 = 1")
        for r in DAGS[4:]:
            self(f"{r} = 0")
        self(f"I7=MODIFY (I7,-{frame})(NW)")
        for i, r in enumerate(SAVES):
            self.put(i + 1, r)

    def epilogue(self, frame: int) -> None:
        for i, r in enumerate(SAVES):
            self.slot(r, i + 1)
        self(f"I7=MODIFY (I7,{frame})(NW)")
        for i, r in enumerate(reversed(DAGS)):
            self(f"{r} = DM({i + 1}, I7)")
        self("I12 = DM(M7, I6)")
        self("JUMP (M14, I12) (DB)")
        self("RFRAME")
        self("NOP")


def nib(a: Asm, res: str, x: str) -> None:
    """res = NextIntegratedBlepSample(x): ((0.1875 - t1) + 1.5 t2) - t4; uses R0, R4, R5, R7 (res may be one)."""
    a.k("R0", "half")
    a(f"F4 = F0 * {x}", "t1 = 0.5f * t")
    a("F5 = F4 * F4", "t2")
    a("F7 = F5 * F5", "t4")
    a.k("R0", "0.1875")
    a("F4 = F0 - F4")
    a.k("R0", "1.5")
    a("F5 = F0 * F5")
    a("F4 = F4 + F5")
    a(f"{res} = F4 - F7")


# slope_kernel: frame slots
S_KF, S_KP, S_CNT, S_SU, S_SD, S_T = range(7, 13)
S_FRAME = 12


def slope_kernel() -> str:
    a = Asm()
    a.prologue("slope_kernel.", S_FRAME)
    a("I2 = R4", "s")
    a("I4 = R8", "k")
    a("I0 = R12", "out")
    a("R0 = DM(0, I4)")
    a.put(S_KF, "R0")
    a("R0 = DM(1, I4)")
    a.put(S_KP, "R0")
    a("R0 = DM(1, I6)", "size")
    a.put(S_CNT, "R0")
    a("R15 = DM(0, I2)", "phase_")
    a("R14 = DM(1, I2)", "next_sample_")
    a("R11 = DM(4, I2)", "high_")
    a("R10 = DM(5, I2)", "frequency_")
    a("R9 = DM(6, I2)", "pw_")
    a("R1 = 0")
    a("COMP(R0, R1)")
    a("IF LE JUMP _slk_done")
    a.lab("_slk_loop")
    a("R13 = PASS R14", "this_sample = next_sample")
    a("R14 = 0", "next_sample = 0.0f")
    a.slot("R0", S_KF)
    a("F10 = F10 + F0", "frequency = fm.Next()")
    a.slot("R0", S_KP)
    a("F9 = F9 + F0", "pw = pwm.Next()")
    a("F15 = F15 + F10", "phase_ += frequency")
    a.k("R0", "one")
    a.k("R3", "two")
    a.k("R7", "two")
    a("F4 = F0 - F9", "1.0f - pw")
    a("F1 = RECIPS F9", "slope_up = 1.0f / pw, slope_down = 1.0f / (1.0f - pw)")
    a("F5 = RECIPS F4")
    a("F2 = F9 * F1")
    a("F6 = F4 * F5")
    a("F2 = F3 - F2")
    a("F6 = F7 - F6")
    a("F1 = F1 * F2")
    a("F5 = F5 * F6")
    a("F2 = F9 * F1")
    a("F6 = F4 * F5")
    a("F2 = F3 - F2")
    a("F6 = F7 - F6")
    a("F1 = F1 * F2")
    a("F5 = F5 * F6")
    a("F3 = F0 * F1")
    a("F7 = F0 * F5")
    a("F2 = F9 * F3")
    a("F6 = F4 * F7")
    a("F2 = F0 - F2")
    a("F6 = F0 - F6")
    a("F2 = F2 * F1")
    a("F6 = F6 * F5")
    a("F3 = F3 + F2")
    a("F7 = F7 + F6")
    a.put(S_SU, "R3")
    a.put(S_SD, "R7")
    # if (high_ ^ (phase_ < pw))
    a("R1 = 0")
    a("R2 = 1")
    a("COMP(F15, F9)", "phase_ < pw")
    a("IF LT R1 = R2 OR R2")
    a("COMP(R1, R11)")
    a("IF EQ JUMP _slk_n1")
    a.put(S_T, "R1", "(the new high_)")
    a("F1 = F15 - F9", "t = (phase_ - pw) / frequency")
    a.k("R4", "two")
    a.div("F2", "F1", "F10", "F5", "F6", "F4")
    a.slot("R0", S_SU)
    a.slot("R1", S_SD)
    a("F8 = F0 + F1", "discontinuity = (slope_up + slope_down) * frequency")
    a("F8 = F8 * F10")
    a.k("R1", "one")
    a("F3 = F1 - F2", "this_sample -= ThisIntegratedBlepSample(t) * discontinuity")
    nib(a, "F1", "F3")
    a("F1 = F1 * F8")
    a("F13 = F13 - F1")
    nib(a, "F1", "F2")
    a("F1 = F1 * F8", "next_sample -= NextIntegratedBlepSample(t) * discontinuity")
    a("F14 = F14 - F1")
    a.slot("R11", S_T, "high_ = phase_ < pw")
    a.lab("_slk_n1")
    a.k("R0", "one")
    a("COMP(F15, F0)", "phase_ >= 1.0f")
    a("IF LT JUMP _slk_n2")
    a("F15 = F15 - F0")
    a.k("R4", "two")
    a.div("F2", "F15", "F10", "F5", "F6", "F4", "t = phase_ / frequency")
    a.slot("R0", S_SU)
    a.slot("R1", S_SD)
    a("F8 = F0 + F1")
    a("F8 = F8 * F10")
    a.k("R1", "one")
    a("F3 = F1 - F2", "this_sample += ThisIntegratedBlepSample(t) * discontinuity")
    nib(a, "F1", "F3")
    a("F1 = F1 * F8")
    a("F13 = F13 + F1")
    nib(a, "F1", "F2")
    a("F1 = F1 * F8", "next_sample += NextIntegratedBlepSample(t) * discontinuity")
    a("F14 = F14 + F1")
    a("R11 = 1", "high_ = 1")
    a.lab("_slk_n2")
    a("R0 = 0")
    a("COMP(R11, R0)", "high_ ? phase_ * slope_up : 1.0f - (phase_ - pw) * slope_down")
    a("IF EQ JUMP _slk_lo")
    a.slot("R1", S_SU)
    a("F1 = F15 * F1")
    a("JUMP _slk_ns")
    a.lab("_slk_lo")
    a.slot("R2", S_SD)
    a("F1 = F15 - F9")
    a("F1 = F1 * F2")
    a.k("R2", "one")
    a("F1 = F2 - F1")
    a.lab("_slk_ns")
    a("F14 = F14 + F1", "next_sample += ..")
    a.k("R0", "two")
    a("F0 = F0 * F13", "*out++ = 2.0f * this_sample - 1.0f")
    a.k("R1", "one")
    a("F0 = F0 - F1")
    a("DM(I0, M6) = R0")
    a.slot("R0", S_CNT)
    a("R1 = 1")
    a.iadd("R0 = R0 - R1")
    a.put(S_CNT, "R0")
    a("IF NE JUMP _slk_loop")
    a.lab("_slk_done")
    a("DM(0, I2) = R15")
    a("DM(1, I2) = R14")
    a("DM(4, I2) = R11")
    a("DM(5, I2) = R10")
    a("DM(6, I2) = R9")
    a.epilogue(S_FRAME)
    return "\n".join(a.L) + "\n"


# ws_kernel: frame slots
W_K = list(range(7, 18))  # k[0..10]
W_CNT, W_SF, W_WF, W_IDX, W_FOLD = range(18, 23)
W_FRAME = 22


def hermite(a: Asm, p: str, tbl_slot: int) -> None:
    """F0 = InterpolateHermite(table (slot), slot W_IDX, 512.0f); uses R0-R8."""
    a.slot("R1", W_IDX)
    a("R2 = 0")
    a(
        "COMP(F1, F2)",
        "if (!(index >= 0.0f)) index = 0.0f; else if (index > 1.0f) index = 1.0f",
    )
    a("IF LT R1 = R2 OR R2")
    a.k("R2", "one")
    a("COMP(F1, F2)")
    a("IF GT R1 = R2 OR R2")
    a.k("R2", "512")
    a("F1 = F1 * F2", "index *= size")
    a("R2 = TRUNC F1", "index_integral")
    a("R3 = R13 OR R2")
    a("F3 = F3 - F13")
    a("F8 = F1 - F3", "f = index_fractional")
    a("R2 = LSHIFT R2 BY 2")
    a.slot("R3", tbl_slot)
    a.iadd("R2 = R2 + R3")
    a("I4 = R2")
    a.k("R6", "half")
    a("R3 = 0", "(DAG gap)")
    a("R4 = DM(-1, I4)", "xm1")
    a("R5 = DM(0, I4)", "x0")
    a("R1 = DM(1, I4)", "x1")
    a("R7 = DM(2, I4)", "x2")
    a("F0 = F1 - F4", "c = (x1 - xm1) * 0.5f")
    a("F0 = F0 * F6")
    a("F1 = F5 - F1", "v = x0 - x1")
    a("F2 = F0 + F1", "w = c + v")
    a("F3 = F7 - F5", "a = w + v + (x2 - x0) * 0.5f")
    a("F3 = F3 * F6")
    a("F4 = F2 + F1")
    a("F3 = F4 + F3")
    a("F2 = F2 + F3", "b_neg = w + a")
    a("F3 = F3 * F8", "(((a * f) - b_neg) * f + c) * f + x0")
    a("F3 = F3 - F2")
    a("F3 = F3 * F8")
    a("F3 = F3 + F0")
    a("F3 = F3 * F8")
    a("F0 = F3 + F5")


def ws_kernel() -> str:
    a = Asm()
    a.prologue("ws_kernel.", W_FRAME)
    a("I2 = R4", "s")
    a("I4 = R8", "k")
    a("I0 = R12", "out")
    a("R0 = DM(1, I6)", "aux")
    a("I1 = R0")
    for j, sl in enumerate(W_K):
        a(f"R0 = DM({j}, I4)")
        a.put(sl, "R0")
    a("R0 = DM(2, I6)", "size")
    a.put(W_CNT, "R0")
    a.k("R13", "2^23")
    a("R1 = 0")
    a("COMP(R0, R1)")
    a("IF LE JUMP _wsk_done")
    a.lab("_wsk_loop")
    a("R0 = DM(14, I2)")
    a.slot("R1", W_K[0])
    a("F0 = F0 + F1", "shape = shape_modulation.Next() * 3.9999f")
    a("DM(14, I2) = R0")
    a.k("R1", "3.9999")
    a("F0 = F0 * F1")
    a("R9 = TRUNC F0", "shape_integral")
    a("R1 = R13 OR R9")
    a("F1 = F1 - F13")
    a("F0 = F0 - F1", "shape_fractional")
    a.put(W_SF, "R0")
    # ws_table(i) for i = shape_integral and + 1: 0..3 their table, anything else the double bump (k[7])
    for reg, add in ((10, 0), (11, 1)):
        a(f"R0 = {add}")
        a.iadd("R0 = R9 + R0")
        a.slot(f"R{reg}", W_K[7], "ws_table: lut_ws_double_bump unless 0..3")
        a("R1 = 0")
        a("COMP(R0, R1)")
        a(f"IF LT JUMP _wst{reg}")
        a("R1 = 3")
        a("COMP(R0, R1)")
        a(f"IF GT JUMP _wst{reg}")
        a("R0 = LSHIFT R0 BY 2", "(the frame is byte-addressed)")
        a("R1 = I7")
        a.iadd("R0 = R0 + R1")
        a("I4 = R0")
        a("R1 = 0", "(DAG gap)")
        a("R1 = 0")
        a("R1 = 0")
        a(f"R{reg} = DM({W_K[3]}, I4)", "k[3 + i] on the frame")
        a.lab(f"_wst{reg}")
    # ws_index = 127 out[i] + 128 and its integral / fractional parts with upstream's guards
    a("R0 = DM(I0, M5)")
    a.k("R1", "127")
    a("F0 = F1 * F0", "ws_index = 127.0f * out[i] + 128.0f")
    a.k("R1", "128")
    a("F0 = F0 + F1")
    a("R14 = 0", "ws_index_integral = 0")
    a("R15 = 0", "ws_index_fractional = 0.0f")
    a.k("R1", "-2^23")
    a("COMP(F0, F1)", "ws_index > -8388608.0f && ws_index < 8388608.0f")
    a("IF LE JUMP _wsk_i2")
    a.k("R1", "2^23")
    a("COMP(F0, F1)")
    a("IF GE JUMP _wsk_i2")
    a("R14 = TRUNC F0")
    a("R1 = 0")
    a("COMP(R14, R1)", "itof_small: i < 0 ? -itof_nonneg(-i) : itof_nonneg(i)")
    a("IF GE JUMP _wsk_ip")
    a("R1 = -R14")
    a("R1 = R13 OR R1")
    a("F1 = F1 - F13")
    a("F1 = -F1")
    a("JUMP _wsk_id")
    a.lab("_wsk_ip")
    a("R1 = R13 OR R14")
    a("F1 = F1 - F13")
    a.lab("_wsk_id")
    a("F15 = F0 - F1", "ws_index_fractional")
    a("JUMP _wsk_i4")
    a.lab("_wsk_i2")
    a.k("R1", "-2^31")
    a("COMP(F0, F1)", "ws_index >= -2^31 && ws_index < 2^31: integral only")
    a("IF LT JUMP _wsk_i4")
    a.k("R1", "2^31")
    a("COMP(F0, F1)")
    a("IF GE JUMP _wsk_i4")
    a("R14 = TRUNC F0")
    a.lab("_wsk_i4")
    a("R1 = 255")
    a("R14 = R14 AND R1", "ws_index_integral &= 255")
    a("R0 = LSHIFT R14 BY 2")
    a.iadd("R1 = R10 + R0")
    a("I4 = R1")
    a.iadd("R2 = R11 + R0")
    a("R3 = 0", "(DAG gap)")
    a("R4 = 0")
    a("R5 = 0")
    a("R0 = DM(0, I4)", "x0")
    a("R1 = DM(1, I4)", "x1")
    a("I4 = R2")
    a("F1 = F1 - F0", "x = x0 + (x1 - x0) * ws_index_fractional")
    a("F1 = F1 * F15")
    a("F1 = F0 + F1")
    a("R4 = 0", "(DAG gap)")
    a("R2 = DM(0, I4)", "y0")
    a("R3 = DM(1, I4)", "y1")
    a("F3 = F3 - F2", "y = y0 + (y1 - y0) * ws_index_fractional")
    a("F3 = F3 * F15")
    a("F3 = F2 + F3")
    a.slot("R4", W_SF)
    a("F3 = F3 - F1", "mix = x + (y - x) * shape_fractional")
    a("F3 = F3 * F4")
    a("F3 = F1 + F3")
    a("R0 = DM(15, I2)")
    a.slot("R1", W_K[1])
    a("F0 = F0 + F1", "index = mix * wf_gain_modulation.Next() + 0.5f")
    a("DM(15, I2) = R0")
    a("F3 = F3 * F0")
    a.k("R1", "half")
    a("F3 = F3 + F1")
    a.put(W_IDX, "R3")
    hermite(a, "_wsh1", W_K[8])
    a.put(W_FOLD, "R0", "fold")
    hermite(a, "_wsh2", W_K[9])
    a("F9 = -F0", "fold_2 = -InterpolateHermite(..)")
    # sine = Sine(aux[i] * 0.25f + 0.5f)
    a("R0 = DM(I1, M5)")
    a.k("R1", "q")
    a("F0 = F0 * F1")
    a.k("R1", "half")
    a("F0 = F0 + F1")
    a("R2 = 0")
    a.k("R1", "2^23")
    a("COMP(F0, F1)", "Sine: !(phase >= 0 && phase < 2^23): phase = 0")
    a("IF GE R0 = R2 OR R2")
    a("COMP(F0, F2)")
    a("IF LT R0 = R2 OR R2")
    a("R1 = TRUNC F0", "phase -= itof_nonneg((int)phase)")
    a("R1 = R13 OR R1")
    a("F1 = F1 - F13")
    a("F0 = F0 - F1")
    a.k("R1", "512")
    a("F0 = F0 * F1", "phase *= 512.0f")
    a("R2 = TRUNC F0")
    a("R3 = R13 OR R2")
    a("F3 = F3 - F13")
    a("F3 = F0 - F3", "phase_fractional")
    a("R2 = LSHIFT R2 BY 2")
    a.slot("R4", W_K[10])
    a.iadd("R2 = R2 + R4")
    a("I4 = R2")
    a("R5 = 0", "(DAG gap)")
    a("R6 = 0")
    a("R7 = 0")
    a("R0 = DM(0, I4)", "a")
    a("R1 = DM(1, I4)", "b")
    a("F1 = F1 - F0", "a + (b - a) * phase_fractional")
    a("F1 = F1 * F3")
    a("F0 = F0 + F1")
    a.slot("R2", W_FOLD)
    a("DM(I0, M6) = R2", "out[i] = fold")
    a("R2 = DM(16, I2)")
    a.slot("R1", W_K[2])
    a(
        "F2 = F2 + F1",
        "aux[i] = sine + (fold_2 - sine) * overtone_gain_modulation.Next()",
    )
    a("DM(16, I2) = R2")
    a("F9 = F9 - F0")
    a("F9 = F9 * F2")
    a("F0 = F0 + F9")
    a("DM(I1, M6) = R0")
    a.slot("R0", W_CNT)
