"""Generate lib/va_mix_sm.s: VA's two mixing loops (engines/va.c, va_render: AUX = (AUX - OUT) / 2 and OUT = OUT * saw
gain + square gain * the square) as SISD DO-loop kernels, bit-identical to selcc's code of the C loops (-DPL_VA_C).

    python3 modules/machines/plaits/src/dsp/lib/gen_va_mix_kernel.py

tests/plaits/test_va_kernel.py checks va_render with them against the C on the concrete core.
"""

from __future__ import annotations

from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE / "va_mix_sm.s"

HEADER = """\
// machines/plaits: VA's mixing loops (engines/va.c, va_render), hand-written SISD kernels.
// Generated by lib/gen_va_mix_kernel.py; do not edit by hand.
//
// va_aux_kernel(float *aux, const float *out, int size): aux[i] = (aux[i] - out[i]) * 0.5f.
// va_out_kernel(float *out, const float *temp, float *g, int size): g = {saw value, saw increment, square value, square
//   increment}; out[i] = out[i] * (saw += saw increment) + (square += square increment) * temp[i]; the two values go
//   back to g[0] and g[2]. Both bit-identical to selcc's code of the C loops (-DPL_VA_C).
//
// State on return: R0-R8, R12, I4 and the flags change; every other register is as on entry (I0, I1, M6, L0, L1, L4
// pushed through R0, M6 = 1 and L0 = L1 = L4 = 0 set here). No SIMD.

.SECTION/PM seg_pmco;
.GLOBAL va_aux_kernel.;
.GLOBAL va_out_kernel.;
.COMPRESS;
"""


def kernels() -> str:
    L: list[str] = []

    def a(t: str, c: str = "") -> None:
        line = f"    {t};"
        L.append(f"{line:<56}// {c}" if c else line)

    def lab(n: str) -> None:
        L.append(f"{n}:")

    dags = ["I0", "I1", "M6", "L0", "L1", "L4"]

    def pro(name: str) -> None:
        lab(name)
        for r in dags:
            a(f"R0 = {r}")
            a("DM(I7, M7) = R0")
        a("M6 = 1")
        for r in ("L0", "L1", "L4"):
            a(f"{r} = 0")

    def epi() -> None:
        for i, r in enumerate(reversed(dags)):
            a(f"{r} = DM({i + 1}, I7)")
        a("I12 = DM(M7, I6)")
        a("JUMP (M14, I12) (DB)")
        a("RFRAME")
        a("NOP")

    pro("va_aux_kernel.")
    a("I0 = R4", "aux")
    a("I1 = R8", "out")
    a("R2 = 0x3F000000", "0.5f")
    a("R0 = 0")
    a("COMP(R12, R0)")
    a("IF LE JUMP _vak_done")
    a("LCNTR = R12, DO _vak_e UNTIL LCE")
    a("R0 = DM(I0, M5)")
    a("R1 = DM(I1, M6)")
    a("F0 = F0 - F1", "(aux[i] - out[i]) * 0.5f")
    a("F0 = F0 * F2")
    lab("_vak_e")
    a("DM(I0, M6) = R0")
    lab("_vak_done")
    epi()
    pro("va_out_kernel.")
    a("I0 = R4", "out")
    a("I1 = R8", "temp")
    a("I4 = R12", "g")
    a("R3 = DM(0, I4)", "saw value")
    a("R4 = DM(1, I4)", "saw increment")
    a("R5 = DM(2, I4)", "square value")
    a("R6 = DM(3, I4)", "square increment")
    a("R8 = DM(1, I6)", "size")
    a("R0 = 0")
    a("COMP(R8, R0)")
    a("IF LE JUMP _vok_done")
    a("LCNTR = R8, DO _vok_e UNTIL LCE")
    a("R0 = DM(I0, M5)")
    a("F3 = F3 + F4", "saw_gain_modulation.Next()")
    a("F0 = F0 * F3", "out[i] * saw")
    a("R1 = DM(I1, M6)")
    a("F5 = F5 + F6", "square_gain_modulation.Next()")
    a("F1 = F5 * F1", "square * temp[i]")
    a("F0 = F0 + F1")
    lab("_vok_e")
    a("DM(I0, M6) = R0")
    a("DM(0, I4) = R3")
    a("DM(2, I4) = R5")
    lab("_vok_done")
    epi()
    return "\n".join(L) + "\n"


def main() -> None:
    OUT.write_text(HEADER + "\n" + kernels())
    print(OUT)


if __name__ == "__main__":
    main()
