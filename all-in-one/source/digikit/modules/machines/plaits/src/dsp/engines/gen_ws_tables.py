"""Generate ws_tables.h: the tables of Plaits' waveshaping engine, from upstream plaits/resources.cc (MIT).

Run from the repo root (needs the upstream checkout, ../eurorack by default):
    uv run python modules/machines/plaits/src/dsp/engines/gen_ws_tables.py [path/to/plaits/resources.cc]

Every value is written as the IEEE single bit pattern of the value upstream's build holds: a float literal is a C
double rounded to float (as the C++ compiler does), an int16 waveshaper entry v becomes v / 32768 (exact), so the
port reads `WS_F(table)[i]` where upstream computes `static_cast<float>(table[i]) / 32768.0f`, with equal bits.
Selache's C compiler writes negative floats in initialised tables with wrong bits (docs/findings/20-patch-toolchains.md,
"selcc"); unsigned integers it writes as they are, hence the bit patterns. They are plain `unsigned int` arrays read
through a `const float *`, not arrays of a union: selcc places every union member after the previous one, as in a
struct (finding 20), so `u[i].f` would read the next entry.
"""

from __future__ import annotations

import re
import struct
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
DEFAULT = HERE.parents[5].parent / "eurorack" / "plaits" / "resources.cc"

# (upstream name, entries kept, kind). lut_sine: InterpolateWrap reads indices 0..512 only.
TABLES = [
    ("lut_sine", 513, "float"),
    ("lut_fold", 516, "float"),
    ("lut_fold_2", 516, "float"),
    ("lut_ws_inverse_tan", 257, "i16"),
    ("lut_ws_inverse_sin", 257, "i16"),
    ("lut_ws_linear", 257, "i16"),
    ("lut_ws_bump", 257, "i16"),
    ("lut_ws_double_bump", 257, "i16"),
]


def f32_bits(x: float) -> int:
    return int(struct.unpack("<I", struct.pack("<f", x))[0])


def body(src: str, name: str, kind: str) -> list[str]:
    ctype = "float" if kind == "float" else "int16_t"
    m = re.search(rf"const {ctype} {name}\[\] = \{{(.*?)\}};", src, re.S)
    assert m, name
    return [t for t in re.split(r"[\s,]+", m.group(1)) if t]


def main() -> None:
    path = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT
    src = path.read_text()
    notice = src.split("// ----")[0].rstrip() + "\n"
    out = [
        notice,
        "// -----------------------------------------------------------------------------",
        "//",
        "// GENERATED by gen_ws_tables.py from upstream plaits/resources.cc - do not edit.",
        "// The tables of Plaits' WaveshapingEngine as IEEE single bit patterns (see the generator).",
        "// Included by waveshaping.c only.",
        "",
        "#ifndef PLAITS_WS_TABLES_H",
        "#define PLAITS_WS_TABLES_H",
        "",
        "/* A table's entries as floats (the host build compiles with -fno-strict-aliasing). */",
        "#define WS_F(table) ((const float *)(table))",
        "",
    ]
    for name, keep, kind in TABLES:
        toks = body(src, name, kind)
        assert len(toks) >= keep, (name, len(toks))
        vals = [float(t) if kind == "float" else int(t) / 32768.0 for t in toks[:keep]]
        out.append(f"static const unsigned int {name}[{keep}] = {{")
        for i in range(0, keep, 4):
            row = ", ".join(f"0x{f32_bits(v):08x}u" for v in vals[i : i + 4])
            out.append(f"  {row},")
        out.append("};")
        out.append("")
    out.append("#endif")
    (HERE / "ws_tables.h").write_text("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
