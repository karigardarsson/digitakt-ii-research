"""Generate lib/fm_sm.s: 2FM's sample loop (engines/fm.c, fm_render: the 4x oversampled two-operator FM with its sub
oscillator and the 4x downsamplers) as a SISD kernel, bit-identical to selcc's code of the C loop (-DPL_FM_C).

    python3 modules/machines/plaits/src/dsp/lib/gen_fm_kernel.py

Every operation is the C's, with the same operands in the same order (commutative swaps only); SinePM and ftou are
written out (their branches as selects of both results, the conditions selcc's). One exact hoist: max_uint32 *
_modulator_frequency is the same product in the four oversampled steps of a sample, so it is computed once per sample.
tests/plaits/test_fm_kernel.py checks it against the C on the concrete core.
"""

from __future__ import annotations

from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE / "fm_sm.s"
ONE, HALF, QUARTER = "0x3F800000", "0x3F000000", "0x3E800000"
F32, F2_26, F2_31, MAXU = "0x42000000", "0x4C800000", "0x4F000000", "0x4F800000"
F0_05 = "0x3D4CCCCD"

HEADER = """\
// machines/plaits: 2FM's sample loop (engines/fm.c, fm_render), hand-written SISD kernel.
// Generated by lib/gen_fm_kernel.py; do not edit by hand.
//
// fm_kernel(FM *s, const float *k, float *out, float *aux, int size): s = the engine (the three phases, the four
//   interpolators' values previous_carrier_frequency_ .. previous_feedback_, previous_sample_, sub_fir_, carrier_fir_);
//   k[0..3] = the increments of the carrier frequency, modulator frequency, amount and feedback; k[4..7] =
//   lut_4x_downsampler_fir[0..3]. Writes out (carrier) and aux (sub) and the state back, bit-identical to selcc's code
//   of the C loop (-DPL_FM_C) (tests/plaits/test_fm_kernel.py).
//
// State on return: R0-R8, R12, I4 and the flags change; every other register is as on entry (R9-R11, R13-R15 saved
// above I7; I0, I1, I2, M6, L0, L1, L2, L4 pushed through R0, M6 = 1 and L0 = L1 = L2 = L4 = 0 set here). No SIMD.
// ABI: as the other kernels (lib/wavetable_sm.s). Assembled under .COMPRESS; integer additions in their 48-bit form.

.SECTION/PM seg_pmco;
.GLOBAL fm_kernel.;
.EXTERN pl_lut_sine.;
.COMPRESS;
"""

DAGS = ["I0", "I1", "I2", "M6", "L0", "L1", "L2", "L4"]
SAVES = ["R9", "R10", "R11", "R13", "R14", "R15"]
FIR = (7, 8, 9, 10)
CNT, AMT, PFB, CINC, CHALF, MAXMF, MFB, LUT, K0, K1, K2, K3 = range(11, 23)
FRAME = 22


def kernel() -> str:
    L: list[str] = []

    def a(t: str, c: str = "") -> None:
        line = f"    {t};"
        L.append(f"{line:<56}// {c}" if c else line)

    def lab(n: str) -> None:
        L.append(f"{n}:")

    def iadd(t: str, c: str = "") -> None:
        L.append("    .NOCOMPRESS;")
        a(t, c)
        L.append("    .COMPRESS;")

    def slot(r: str, k: int, c: str = "") -> None:
        a(f"{r} = DM({k}, I7)", c)

    def put(k: int, r: str, c: str = "") -> None:
        a(f"DM({k}, I7) = {r}", c)

    def ftou(dst: int, x: int) -> None:
        """R{dst} = ftou(F{x}); uses R2-R4 (x kept; dst may be 1)."""
        a(f"R2 = {F2_31}")
        a(f"F3 = F{x} - F2", "ftou: x >= 2^31 ? (int)(x - 2^31) + 2^31 : (int)x")
        a("R3 = TRUNC F3")
        a("R4 = 0x80000000")
        iadd("R3 = R3 + R4")
        a(f"R{dst} = TRUNC F{x}")
        a(f"COMP(F{x}, F2)")
        a(f"IF GE R{dst} = R3 OR R3")

    def sinepm(ph: str, pm: int) -> None:
        """F0 = SinePM(R{ph}, F{pm}); uses R0-R4 (pm may be among them)."""
        a(f"R1 = {F32}")
        a(f"F1 = F{pm} + F1", "SinePM: x = (pm + 32.0f) * 2^26")
        a(f"R2 = {F2_26}")
        a("F1 = F1 * F2")
        a(f"R2 = {F2_31}")
        a("F3 = F1 - F2", "if (x >= 2^31) x -= 2^31")
        a("COMP(F1, F2)")
        a("IF GE R1 = R3 OR R3")
        a("R1 = TRUNC F1")
        a("R1 = LSHIFT R1 BY 6")
        iadd(f"R1 = R{ph} + R1", "phase += (int)x << 6")
        a("R2 = -23")
        a("R2 = LSHIFT R1 BY R2", "integral = phase >> 23")
        a("R3 = 0x7FFFFF")
        a("R3 = R1 AND R3")
        a(f"R4 = {ONE}")
        a(
            "R3 = R3 OR R4",
            "fractional = (0x3F800000 | (phase & 0x7FFFFF)) as a float - 1.0f",
        )
        a("F3 = F3 - F4")
        a("R2 = LSHIFT R2 BY 2")
        slot("R4", LUT)
        iadd("R2 = R2 + R4")
        a("I4 = R2")
        a("R4 = 0", "(DAG gap)")
        a("R1 = 0")
        a("R0 = DM(I4, M5)", "a")
        a("R2 = DM(1, I4)", "b")
        a("F2 = F2 - F0", "a + (b - a) * fractional")
        a("F2 = F2 * F3")
        a("F0 = F0 + F2")

    lab("fm_kernel.")
    for r in DAGS:
        a(f"R0 = {r}")
        a("DM(I7, M7) = R0")
    a("M6 = 1")
    for r in DAGS[4:]:
        a(f"{r} = 0")
    a(f"I7=MODIFY (I7,-{FRAME})(NW)")
    for i, r in enumerate(SAVES):
        put(i + 1, r)
    a("I2 = R4", "s")
    a("I4 = R8", "k")
    a("I0 = R12", "out")
    a("R0 = DM(1, I6)", "aux")
    a("I1 = R0")
    for j, sl in enumerate((K0, K1, K2, K3) + FIR):
        a(f"R0 = DM({j}, I4)")
        put(sl, "R0")
    a("R0 = pl_lut_sine.")
    put(LUT, "R0")
    a("R0 = DM(2, I6)", "size")
    put(CNT, "R0")
    a("R15 = DM(0, I2)", "carrier_phase_")
    a("R14 = DM(1, I2)", "modulator_phase_")
    a("R13 = DM(2, I2)", "sub_phase_")
    a("R12 = DM(7, I2)", "previous_sample_")
    a("R9 = DM(8, I2)", "sub head (sub_fir_)")
    a("R11 = DM(9, I2)", "carrier head (carrier_fir_)")
    a("R10 = 0", "carrier tail")
    a("R8 = 0", "sub tail")
    a("R1 = 0")
    a("COMP(R0, R1)")
    a("IF LE JUMP _fmk_done")
    lab("_fmk_loop")
    a("R0 = DM(5, I2)")
    slot("R1", K2)
    a("F0 = F0 + F1", "amount")
    a("DM(5, I2) = R0")
    put(AMT, "R0")
    a("R0 = DM(6, I2)")
    slot("R1", K3)
    a("F0 = F0 + F1", "feedback")
    a("DM(6, I2) = R0")
    a(f"R1 = {HALF}")
    a(
        "F1 = F1 * F0",
        "phase_feedback = feedback < 0.0f ? 0.5f * feedback * feedback : 0.0f",
    )
    a("F1 = F1 * F0")
    a("R2 = 0")
    a("COMP(F0, F2)")
    a("IF GE R1 = R2 OR R2")
    put(PFB, "R1")
    a(f"R1 = {QUARTER}")
    a(
        "F1 = F1 * F0",
        "modulator_fb = feedback > 0.0f ? 0.25f * feedback * feedback : 0.0f",
    )
    a("F1 = F1 * F0")
    a("COMP(F0, F2)")
    a("IF LE R1 = R2 OR R2")
    put(MFB, "R1")
    a("R0 = DM(3, I2)")
    slot("R1", K0)
    a("F0 = F0 + F1", "carrier_frequency")
    a("DM(3, I2) = R0")
    a(f"R5 = {MAXU}")
    a("F0 = F5 * F0", "max_uint32 * carrier_frequency")
    ftou(1, 0)
    put(CINC, "R1", "carrier_increment")
    a("R2 = -1")
    a("R1 = LSHIFT R1 BY R2", "carrier_increment >> 1")
    put(CHALF, "R1")
    a("R0 = DM(4, I2)")
    slot("R1", K1)
    a("F0 = F0 + F1", "_modulator_frequency")
    a("DM(4, I2) = R0")
    a(
        "F0 = F5 * F0",
        "max_uint32 * _modulator_frequency (the same product in the four steps)",
    )
    put(MAXMF, "R0")
    for j in range(4):
        slot("R1", PFB)
        a(
            "F0 = F12 * F1",
            f"step {j}: modulator_phase_ += ftou(max * f * (1.0f + previous_sample_ * phase_feedback))",
        )
        a(f"R1 = {ONE}")
        a("F0 = F1 + F0")
        slot("R1", MAXMF)
        a("F0 = F1 * F0")
        ftou(1, 0)
        iadd("R14 = R14 + R1")
        slot("R1", CINC)
        iadd("R15 = R15 + R1", "carrier_phase_ += carrier_increment")
        slot("R1", CHALF)
        iadd("R13 = R13 + R1", "sub_phase_ += carrier_increment >> 1")
        slot("R1", MFB)
        a(
            "F5 = F1 * F12",
            "modulator = SinePM(modulator_phase_, modulator_fb * previous_sample_)",
        )
        sinepm("14", 5)
        a("R5 = PASS R0")
        slot("R1", AMT)
        a("F6 = F1 * F5", "carrier = SinePM(carrier_phase_, amount * modulator)")
        sinepm("15", 6)
        a("R6 = PASS R0")
        slot("R1", AMT)
        a("F7 = F1 * F6", "sub = SinePM(sub_phase_, amount * carrier * 0.25f)")
        a(f"R1 = {QUARTER}")
        a("F7 = F7 * F1")
        sinepm("13", 7)
        a("R7 = PASS R0")
        a("F0 = F6 - F12", "ONE_POLE(previous_sample_, carrier, 0.05f)")
        a(f"R1 = {F0_05}")
        a("F0 = F1 * F0")
        a("F12 = F12 + F0")
        slot("R1", FIR[3 - j])
        slot("R2", FIR[j])
        a("F0 = F6 * F1", "carrier head += carrier * fir[3 - j]")
        a("F11 = F11 + F0")
        a("F0 = F6 * F2", "carrier tail += carrier * fir[j]")
        a("F10 = F10 + F0")
        a("F0 = F7 * F1", "sub head += sub * fir[3 - j]")
        a("F9 = F9 + F0")
        a("F0 = F7 * F2", "sub tail += sub * fir[j]")
        a("F8 = F8 + F0")
    a("DM(I0, M6) = R11", "*out++ = down_read(&carrier_downsampler)")
    a("R11 = PASS R10")
    a("R10 = 0")
    a("DM(I1, M6) = R9", "*aux++ = down_read(&sub_downsampler)")
    a("R9 = PASS R8")
    a("R8 = 0")
    slot("R0", CNT)
    a("R1 = 1")
    iadd("R0 = R0 - R1")
    put(CNT, "R0")
    a("IF NE JUMP _fmk_loop")
    lab("_fmk_done")
    a("DM(0, I2) = R15")
    a("DM(1, I2) = R14")
    a("DM(2, I2) = R13")
    a("DM(7, I2) = R12")
    a("DM(8, I2) = R9", "down_commit")
    a("DM(9, I2) = R11")
    for i, r in enumerate(SAVES):
        slot(r, i + 1)
    a(f"I7=MODIFY (I7,{FRAME})(NW)")
    for i, r in enumerate(reversed(DAGS)):
        a(f"{r} = DM({i + 1}, I7)")
    a("I12 = DM(M7, I6)")
    a("JUMP (M14, I12) (DB)")
    a("RFRAME")
    a("NOP")
    return "\n".join(L) + "\n"


def main() -> None:
    OUT.write_text(HEADER + "\n" + kernel())
    print(OUT)


if __name__ == "__main__":
    main()
