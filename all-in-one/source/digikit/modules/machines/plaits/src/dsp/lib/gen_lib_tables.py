"""Generate lib/tables.c and lib/tables.h: the upstream tables the 2FM, FORMANT, ADDITIVE and RINGS engines share, once for
the whole PLAITS object, from upstream plaits/resources.cc and stmlib/dsp/units.cc (MIT, Emilie Gillet).

Run from the repo root (needs the upstream checkout, ../eurorack by default, with stmlib populated):
    uv run python modules/machines/plaits/src/dsp/lib/gen_lib_tables.py [path/to/eurorack]

As engines/gen_ws_tables.py: every value is written as the IEEE single bit pattern of the float upstream's build holds
(a C double literal rounded to float), in a plain `unsigned int` array read through `PL_F(table)`, a `const float *`.
Selache's C compiler writes negative floats in initialised tables with wrong bits, and places union members like
struct members (docs/findings/20-patch-toolchains.md), so neither a float table nor a union table would be safe.
The arrays are global (`pl_lut_*`), defined once in tables.c, so the engines that include tables.h share one copy.
"""

from __future__ import annotations

import re
import struct
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
DEFAULT = HERE.parents[5].parent / "eurorack"

# (file under the eurorack checkout, upstream name, entries kept)
TABLES = [
    ("plaits/resources.cc", "lut_sine", 641),
    ("plaits/resources.cc", "lut_fm_frequency_quantizer", 130),
    ("plaits/resources.cc", "lut_4x_downsampler_fir", 4),
    ("stmlib/dsp/units.cc", "lut_pitch_ratio_high", 256),
    ("stmlib/dsp/units.cc", "lut_pitch_ratio_low", 256),
    ("plaits/resources.cc", "lut_stiffness", 65),
    ("plaits/resources.cc", "lut_svf_shift", 257),
]


def f32_bits(x: float) -> int:
    return int(struct.unpack("<I", struct.pack("<f", x))[0])


def body(src: str, name: str) -> list[str]:
    m = re.search(rf"const float {name}\[\d*\] = \{{(.*?)\}};", src, re.S)
    assert m, name
    return [t for t in re.split(r"[\s,]+", m.group(1)) if t]


def main() -> None:
    root = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT
    notice = (root / "plaits" / "resources.cc").read_text().split("// ----")[
        0
    ].rstrip() + "\n"
    head = [
        notice,
        "// -----------------------------------------------------------------------------",
        "//",
        "// GENERATED by lib/gen_lib_tables.py from upstream plaits/resources.cc and stmlib/dsp/units.cc - do not edit.",
        "// IEEE single bit patterns of upstream's float tables (see the generator).",
        "",
    ]
    h = [
        *head,
        "#ifndef PLAITS_LIB_TABLES_H",
        "#define PLAITS_LIB_TABLES_H",
        "",
        "/* A table's entries as floats (the host build compiles with -fno-strict-aliasing). */",
        "#define PL_F(table) ((const float *)(table))",
        "",
    ]
    c = [*head, '#include "tables.h"', ""]
    for path, name, keep in TABLES:
        toks = body((root / path).read_text(), name)
        assert len(toks) >= keep, (name, len(toks))
        vals = [float(t) for t in toks[:keep]]
        h.append(f"extern const unsigned int pl_{name}[{keep}];")
        c.append(f"const unsigned int pl_{name}[{keep}] = {{")
        for i in range(0, keep, 4):
            row = ", ".join(f"0x{f32_bits(v):08x}u" for v in vals[i : i + 4])
            c.append(f"  {row},")
        c.append("};")
        c.append("")
    total = 4 * sum(keep for _, _, keep in TABLES)
    h += [
        "",
        "/* The bytes of these tables (selcc wants code in every unit it compiles for patchkit: tables.c has this). */",
        "int pl_lib_tables_bytes(void);",
        "",
        "#endif",
    ]
    c += [f"int pl_lib_tables_bytes(void) {{ return {total}; }}", ""]
    (HERE / "tables.h").write_text("\n".join(h) + "\n")
    (HERE / "tables.c").write_text("\n".join(c))


if __name__ == "__main__":
    main()
