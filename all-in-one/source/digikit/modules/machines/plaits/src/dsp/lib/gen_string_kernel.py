"""Generate lib/string_sm.s: STRING's sample loops (engines/string_engine.c: string_process's loop with the Hermite and
linear delay reads, the all-pass, the DC blocker and the damping filter; string_voice_render's excitation noise, low
pass and aux sum) as SISD kernels, bit-identical in output to selcc's code of the C (-DPL_STRING_C).

    python3 modules/machines/plaits/src/dsp/lib/gen_string_kernel.py

Every float operation is the C's, with the same operands in the same order (commutative swaps only); comparisons use
selcc's operand order and its condition or the complement (selects instead of branches where selcc branches).

The delay lines are not cleared at init (string_voice_init in the DSP build sets fresh_string_ = fresh_stretch_ = 0
instead). A line is written at its write pointer wp, which then moves down by one, so the word at offset o from wp
(1 <= o <= size) was written o writes ago, and the word at offset 0 size writes ago: the C reads its cleared memory
exactly when ((o - 1) & mask) >= the writes since init. The checked loops count the writes and select 0.0f for such
taps (never computing on the word); once string_ has had 1024 writes (and stretch_ 256, in the dispersion mode) the
unchecked loops run. tests/plaits/test_string_kernel.py checks both against the C on the concrete core.
"""

