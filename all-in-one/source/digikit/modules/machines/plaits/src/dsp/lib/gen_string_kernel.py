HEADER = """\
// machines/plaits: STRING's sample loops (engines/string_engine.c), hand-written SISD kernels.
// Generated by lib/gen_string_kernel.py; do not edit by hand.
//
// string_loop_kernel(StringVoice *v, float *k, const float *in, float *out, int size, unsigned int *rng,
//   int dispersion): string_process's sample loop. k[] (string_engine.c): src_ratio, the delay interpolator's value
//   (in/out) and increment, the per-block values and the loop's literals. The delay lines are never cleared: reads
//   of the C's cleared memory give 0.0f (lib/gen_string_kernel.py, fresh_string_ / fresh_stretch_).
// string_excite_kernel(Svf *f, float *temp, float *aux, int size, int noise_samples, unsigned int *rng, float *k):
//   the excitation (noise_samples draws of 2 r - 1, then zeros), its low pass into temp, aux += temp.
//   Bit-identical in output to selcc's code of the C (-DPL_STRING_C) (tests/plaits/test_string_kernel.py).
//
// State on return: R0-R8, R12 and the flags change; every other register is as on entry (R9-R11, R13-R15 saved
// above I7; the DAG registers used pushed through R0, M6 = 1 and their L = 0 set here). No SIMD.
// ABI: as the other kernels (lib/wavetable_sm.s). Assembled under .COMPRESS; integer additions in their 48-bit form.

.SECTION/PM seg_pmco;
.GLOBAL string_loop_kernel.;
.GLOBAL string_excite_kernel.;
.COMPRESS;
"""

SAVES = ["R9", "R10", "R11", "R13", "R14", "R15"]


class Asm:
    def __init__(self) -> None:
        self.lines: list[str] = []

    def __call__(self, text: str, comment: str = "") -> None:
        line = f"    {text};"
        line = f"{line:<56}// {comment}" if comment else line
        if "DM(M" in text:  # the compressed pre-modify form is sized differently by our decoder: 48-bit
            self.lines += ["    .NOCOMPRESS;", line, "    .COMPRESS;"]
        else:
            self.lines.append(line)

    def label(self, name: str) -> None:
        self.lines.append(f"{name}:")

    def iadd(self, text: str, comment: str = "") -> None:
        self.lines.append("    .NOCOMPRESS;")
        self(text, comment)
        self.lines.append("    .COMPRESS;")

    def prologue(self, name: str, dags: list[str], frame: int) -> None:
        self.label(f"{name}.")
        for r in dags:
            self(f"R0 = {r}")
            self("DM(I7, M7) = R0")
        self("M6 = 1")
        for r in dags:
            if r.startswith("L"):
                self(f"{r} = 0")
        self(f"I7=MODIFY (I7,-{frame})(NW)")
        for i, r in enumerate(SAVES):
            self(f"DM({i + 1}, I7) = {r}")

    def epilogue(self, dags: list[str], frame: int) -> None:
        for i, r in enumerate(SAVES):
            self(f"{r} = DM({i + 1}, I7)")
        self(f"I7=MODIFY (I7,{frame})(NW)")
        for i, r in enumerate(reversed(dags)):
            self(f"{r} = DM({i + 1}, I7)")
        self("I12 = DM(M7, I6)")
        self("JUMP (M14, I12) (DB)")
        self("RFRAME")
        self("NOP")


def rng_float(a: Asm, dst: str, big: int, c65536: int, y32: int, d32: int) -> None:
    """dst = rng_float(&rng) (drums.h) with the word in R13, as lib/gen_drum_kernels.py. Uses R4-R8."""
    a("R4 = 1664525")
    a("R5 = 1013904223")
    a(f"R13 = R13 * R4 (SSI), R6 = DM({big}, I4)", "rng_word")
    a("R13 = R13 + R5")
    a("R7 = FEXT R13 BY 16:16", "w >> 16")
    a("R8 = FEXT R13 BY 0:16", "w & 0xFFFF")
    a("R7 = R7 OR R6", "itof_nonneg")
    a("R8 = R8 OR R6")
    a(f"F7 = F7 - F6, R5 = DM({c65536}, I4)")
    a("F8 = F8 - F6")
    a(f"F7 = F7 * F5, R5 = DM({y32}, I4)", "hi * 65536.0f")
    a(f"F7 = F7 + F8, R6 = DM({d32}, I4)", "+ lo")
    a("F8 = F7 * F5", "/ 4294967296.0f: q")
    a("F4 = F6 * F8")
    a("F4 = F7 - F4")
    a("F4 = F4 * F5")
    a(f"{dst} = F8 + F4")


def recip_const(a: Asm, d: int, two: int, y: int) -> None:
    """k[y] = the reciprocal selcc's division by the constant k[d] reaches after its two Newton steps."""
    a(f"R8 = DM({d}, I4)")
    a(f"R4 = DM({two}, I4)")
    a("F9 = RECIPS F8")
    a("F10 = F8 * F9")
    a("F10 = F4 - F10")
    a("F9 = F9 * F10")
    a("F10 = F8 * F9")
    a("F10 = F4 - F10")
    a("F9 = F9 * F10")
    a(f"DM({y}, I4) = R9")


