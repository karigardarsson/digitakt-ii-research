    a("R1 = 1")
    a.iadd("R12 = R12 - R1")
    a("IF NE JUMP _ste_zl")
    a.label("_ste_done")
    a("DM(I2, M5) = R13", "rng")
    a(f"R0 = DM({S_EF}, I7)")
    a("I2 = R0")
    a("R0 = 0", "(DAG gap)")
    a("R1 = 0")
    a("R2 = 0")
    a("DM(3, I2) = R14", "state_1")
    a("DM(4, I2) = R15", "state_2")
    a.epilogue(EX_DAGS, EX_FRAME)


