LOOP_DAGS = ["I0", "I1", "I2", "I3", "I4", "I5", "M0", "M1", "M2", "M3", "M4", "M6", "L0", "L1", "L2", "L3", "L4", "L5"]


def check_tap(a: Asm, x: str, base: str, add: int, mask: str, fresh: str, zero: str, tmp: str) -> None:
    """x = 0 when ((base + add) & mask) >= fresh: the C would read a word still cleared (base + add = offset - 1)."""
    if add == 0:
        a(f"{tmp} = {base} AND {mask}")
    else:
        a(f"{tmp} = {abs(add)}")
        a.iadd(f"{tmp} = {base} {'+' if add > 0 else '-'} {tmp}")
        a(f"{tmp} = {tmp} AND {mask}")
    a(f"COMP({tmp}, {fresh})")
    a(f"IF GE {x} = {zero} OR {zero}", "a word the C reads as cleared")


def hermite(a: Asm, checked: bool) -> None:
    """F0 = dl_read_hermite(string_, wp (R9), mask, delay (F3)). Uses R0-R8, R12, M0-M3."""
    a("R4 = TRUNC F3", "integral = (int)delay")
    a(f"R5 = DM({K_BIAS}, I4)")
    a("R6 = R5 OR R4", "itof_nonneg(integral)")
    a("F6 = F6 - F5")
    a("F12 = F3 - F6", "f = delay - itof_nonneg(integral)")
    a.iadd("R6 = R9 + R4", "t = wp + integral (+ size: the mask drops it)")
    a("R7 = 1023")
    a("R8 = 1")
    a.iadd("R5 = R6 - R8")
    a("R5 = R5 AND R7")
    a("M0 = R5", "(t - 1) & mask")
    a("R5 = R6 AND R7")
    a("M1 = R5", "t & mask")
    a.iadd("R5 = R6 + R8")
    a("R5 = R5 AND R7")
    a("M2 = R5", "(t + 1) & mask")
    a("R8 = 2")
    a.iadd("R5 = R6 + R8")
    a("R5 = R5 AND R7")
    a("M3 = R5", "(t + 2) & mask")
    a(f"R8 = DM({K_HALF}, I4)", "(DAG gap)")
    a("R0 = DM(M0, I2)", "xm1")
    a("R1 = DM(M1, I2)", "x0")
    a("R2 = DM(M2, I2)", "x1")
    a("R3 = DM(M3, I2)", "x2")
    if checked:
        a(f"R6 = DM({S_FS}, I7)", "fresh_string_")
        a("R8 = 0")
        check_tap(a, "R0", "R4", -2, "R7", "R6", "R8", "R5")
        check_tap(a, "R1", "R4", -1, "R7", "R6", "R8", "R5")
        check_tap(a, "R2", "R4", 0, "R7", "R6", "R8", "R5")
        check_tap(a, "R3", "R4", 1, "R7", "R6", "R8", "R5")
        a(f"R8 = DM({K_HALF}, I4)")
    a("F5 = F2 - F0", "c = (x1 - xm1) * 0.5f")
    a("F5 = F5 * F8")
    a("F6 = F1 - F2", "v = x0 - x1")
    a("F7 = F5 + F6", "w = c + v")
    a("F4 = F7 + F6", "a = w + v + (x2 - x0) * 0.5f")
    a("F2 = F3 - F1")
    a("F2 = F2 * F8")
    a("F4 = F4 + F2")
    a("F7 = F7 + F4", "b_neg = w + a")
    a("F0 = F4 * F12", "(((a * f) - b_neg) * f + c) * f + x0")
    a("F0 = F0 - F7")
    a("F0 = F0 * F12")
    a("F0 = F0 + F5")
    a("F0 = F0 * F12")
    a("F0 = F0 + F1")


def linear_allpass(a: Asm, checked: bool) -> None:
    """main_delay in F5, ap_delay in F4: F0 = dl_read(string_, wp, main_delay), then stretch_.Allpass (C order)."""
    a("R2 = TRUNC F5", "integral = (int)main_delay")
    a(f"R6 = DM({K_BIAS}, I4)")
    a("R7 = R6 OR R2", "itof_nonneg(integral)")
    a("F7 = F7 - F6")
    a("F12 = F5 - F7", "fractional")
    a.iadd("R6 = R9 + R2", "wp + integral")
    a("R7 = 1023")
    a("R5 = R6 AND R7")
    a("M0 = R5")
    a("R8 = 1")
    a.iadd("R5 = R6 + R8")
    a("R5 = R5 AND R7")
    a("M1 = R5")
    a("R3 = TRUNC F4", "ap_int = (int)ap_delay")
    a(f"R6 = DM({S_AWP}, I7)", "stretch write pointer")
    a("M3 = R6")
    a.iadd("R5 = R6 + R3")
    a("R8 = 255")
    a("R5 = R5 AND R8")
    a("M2 = R5", "(awp + ap_int) & STRETCH_MASK")
    a("R0 = DM(M0, I2)", "a")
    a("R1 = DM(M1, I2)", "b")
    if checked:
        a(f"R6 = DM({S_FS}, I7)")
        a("R8 = 0")
        check_tap(a, "R0", "R2", -1, "R7", "R6", "R8", "R5")
        check_tap(a, "R1", "R2", 0, "R7", "R6", "R8", "R5")
    a("F1 = F1 - F0", "s = a + (b - a) * fractional")
    a("F1 = F1 * F12")
    a("F0 = F0 + F1")
    a("R5 = DM(M2, I3)", "rd")
    if checked:
        a(f"R6 = DM({S_FA}, I7)", "fresh_stretch_")
        a("R8 = 0")
        a("R7 = 255")
        check_tap(a, "R5", "R3", -1, "R7", "R6", "R8", "R1")
    a(f"R6 = DM({K_APG}, I4)")
    a("F7 = F6 * F5", "wr = s + ap_gain * rd")
    a("F7 = F0 + F7")
    a("DM(M3, I3) = R7", "stretch_[awp] = wr")
    a(f"R8 = DM({S_AWP}, I7)")
    a("R1 = 1")
    a.iadd("R8 = R8 - R1")
    a("R1 = 255")
    a("R8 = R8 AND R1")
    a(f"DM({S_AWP}, I7) = R8", "awp = (awp - 1) & STRETCH_MASK")
    if checked:
        a(f"R1 = DM({S_FA}, I7)")
        a("R2 = 1")
        a.iadd("R1 = R1 + R2")
        a(f"DM({S_FA}, I7) = R1")
    a("F7 = -F7", "s = -wr * ap_gain + rd")
    a("F7 = F7 * F6")
    a("F0 = F7 + F5")


def body(a: Asm, p: str, disp: bool, checked: bool) -> None:
    a.label(f"{p}_loop")
    a(f"R1 = DM({K_RATIO}, I4)")
    a("F15 = F15 + F1", "src_phase += src_ratio")
    a(f"R2 = DM({K_ONE}, I4)")
    a("COMP(F15, F2)")
    a(f"IF LE JUMP {p}_out")
    a("F15 = F15 - F2", "src_phase -= 1.0f")
    a(f"R1 = DM({K_INC}, I4)")
    a("F14 = F14 + F1", "d = next(&delay_modulation)")
    if not disp:
        a(f"R3 = DM({K_BC}, I4)")
        a("F3 = F13 * F3", "d *= 1.0f - curved_bridge * bridge_curving")
        a("F3 = F2 - F3")
        a("F3 = F14 * F3")
        hermite(a, checked)
        a("R2 = 0")
        a("F1 = -F0", "value = absf(s) - 0.025f")
        a("COMP(F0, F2)")
        a("IF GE R1 = R0 OR R0")
        a(f"R3 = DM({K_C025}, I4)")
        a("F1 = F1 - F3")
        a("F4 = -F1", "absf(value) + value")
        a("COMP(F1, F2)")
        a("IF GE R4 = R1 OR R1")
        a("F4 = F4 + F1")
        a(f"R5 = DM({K_ONE}, I4)", "sign = s > 0.0f ? 1.0f : -1.5f")
        a(f"R6 = DM({K_M15}, I4)")
        a("COMP(F0, F2)")
        a("IF LE R5 = R6 OR R6")
        a("F13 = F4 * F5", "curved_bridge")
    else:
        rng_float(a, "F0", K_BIAS, K_C65536, K_Y32, K_D32)
        a(f"R1 = DM({K_HALF}, I4)")
        a("F0 = F0 - F1", "noise = rng_float(rng) - 0.5f")
        a(f"R1 = DM({S_DN}, I7)")
        a("F2 = F0 - F1", "ONE_POLE(dispersion_noise, noise, noise_filter)")
        a(f"R3 = DM({K_NF}, I4)")
        a("F2 = F3 * F2")
        a("F1 = F1 + F2")
        a(f"DM({S_DN}, I7) = R1")
        a(f"R2 = DM({K_NA}, I4)")
        a("F2 = F1 * F2", "d *= 1.0f + dispersion_noise * noise_amount")
        a(f"R3 = DM({K_ONE}, I4)")
        a("F2 = F3 + F2")
        a("F3 = F14 * F2")
        a(f"R4 = DM({K_SP}, I4)")
        a("F4 = F3 * F4", "ap_delay = d * stretch_point")
        a(f"R5 = DM({K_K1}, I4)")
        a("F5 = F4 * F5", "main_delay = d - ap_delay * k1 * stretch_correction")
        a(f"R6 = DM({K_SC}, I4)")
        a("F5 = F5 * F6")
        a("F5 = F3 - F5")
        a(f"R6 = DM({K_FOUR}, I4)")
        a("COMP(F4, F6)", "ap_delay >= 4.0f && main_delay >= 4.0f")
        a(f"IF LT JUMP {p}_h")
        a("COMP(F5, F6)")
        a(f"IF LT JUMP {p}_h")
        linear_allpass(a, checked)
        a(f"JUMP {p}_s")
        a.label(f"{p}_h")
        hermite(a, checked)
        a.label(f"{p}_s")
    a("R1 = DM(I0, M5)", "s += *in")
    a("F0 = F0 + F1")
    a(f"R2 = DM({K_M20}, I4)", "CONSTRAIN(s, -20.0f, 20.0f)")
    a("COMP(F0, F2)")
    a("IF LT R0 = R2 OR R2")
    a(f"R2 = DM({K_P20}, I4)")
    a("COMP(F0, F2)")
    a("IF GT R0 = R2 OR R2")
    a(f"R1 = DM({V_DCX}, I5)", "dc blocker: old_x")
    a(f"DM({V_DCX}, I5) = R0", "dc_x_ = s")
    a(f"R2 = DM({V_DCY}, I5)")
    a(f"R3 = DM({K_DC}, I4)")
    a("F2 = F2 * F3", "dc_y_ = dc_y_ * 0.999583304f + s - old_x")
    a("F2 = F2 + F0")
    a("F0 = F2 - F1")
    a(f"DM({V_DCY}, I5) = R0")
    a(f"R1 = DM({V_R}, I5)", "damping low pass")
    a(f"R2 = DM({V_S1}, I5)")
    a(f"R3 = DM({V_G}, I5)")
    a(f"R4 = DM({V_S2}, I5)")
    a(f"R5 = DM({V_H}, I5)")
    a("F6 = F1 * F2", "hp = (s - r * s1 - g * s1 - s2) * h")
    a("F6 = F0 - F6")
    a("F7 = F3 * F2")
    a("F6 = F6 - F7")
    a("F6 = F6 - F4")
    a("F6 = F6 * F5")
    a("F8 = F3 * F6", "g * hp")
    a("F7 = F8 + F2", "bp = g * hp + s1")
    a("F8 = F8 + F7", "s1 = g * hp + bp")
    a("F1 = F3 * F7", "g * bp")
    a("F0 = F1 + F4", "lp = g * bp + s2")
    a("F1 = F1 + F0", "s2 = g * bp + lp")
    a(f"DM({V_S1}, I5) = R8")
    a(f"DM({V_S2}, I5) = R1")
    a("DM(M4, I2) = R0", "string_[wp] = s")
    a("R1 = 1")
    a.iadd("R9 = R9 - R1")
    a("R1 = 1023")
    a("R9 = R9 AND R1", "wp = (wp - 1) & mask")
    a("M4 = R9")
    if checked:
        a(f"R1 = DM({S_FS}, I7)")
        a("R2 = 1")
        a.iadd("R1 = R1 + R2", "fresh_string_ += 1")
        a(f"DM({S_FS}, I7) = R1")
    a("R10 = PASS R11", "out1 = out0")
    a("R11 = PASS R0", "out0 = s")
    a.label(f"{p}_out")
    a("F0 = F11 - F10", "*out++ += out1 + (out0 - out1) * src_phase")
    a("F0 = F0 * F15")
    a("F0 = F10 + F0")
    a("R1 = DM(I1, M5)")
    a("F1 = F1 + F0")
    a("DM(I1, M6) = R1")
    a("R2 = DM(I0, M6)", "in++")
    a(f"R0 = DM({S_CNT}, I7)")
    a("R1 = 1")
    a.iadd("R0 = R0 - R1")
    a(f"DM({S_CNT}, I7) = R0")
    a(f"IF NE JUMP {p}_loop")
    a(f"JUMP {'_stk_dend' if disp else '_stk_cend'}")


def loop_kernel(a: Asm) -> None:
    a.prologue("string_loop_kernel", LOOP_DAGS, FRAME)
    a("I2 = R4", "string_")
    a(f"R0 = {STRETCH_OFFSET}")
    a.iadd("R0 = R4 + R0")
    a("I3 = R0", "stretch_")
    a(f"R0 = {STATE_OFFSET}")
    a.iadd("R0 = R4 + R0")
    a("I5 = R0", "&v->iir_damping_filter_ and the state after it")
    a("I4 = R8", "k")
    a("I0 = R12", "in")
    a("R0 = DM(1, I6)", "out")
    a("I1 = R0")
    recip_const(a, K_D32, K_TWO, K_Y32)
    a("R0 = DM(3, I6)", "rng")
    a(f"DM({S_RNGP}, I7) = R0")
    a(f"R15 = DM({V_SRC}, I5)", "src_phase")
    a(f"R14 = DM({K_DM}, I4)", "the delay interpolator's value")
    a(f"R11 = DM({V_OUT0}, I5)")
    a(f"R10 = DM({V_OUT1}, I5)")
    a(f"R9 = DM({V_SWP}, I5)", "wp")
    a("M4 = R9")
    a(f"R0 = DM({V_AWP}, I5)")
    a(f"DM({S_AWP}, I7) = R0")
    a(f"R0 = DM({V_FS}, I5)")
    a(f"DM({S_FS}, I7) = R0")
    a(f"R0 = DM({V_FA}, I5)")
    a(f"DM({S_FA}, I7) = R0")
    a(f"R0 = DM({V_DN}, I5)")
    a(f"DM({S_DN}, I7) = R0")
    a("R0 = DM(2, I6)", "size")
    a(f"DM({S_CNT}, I7) = R0")
    a("R1 = 0")
    a("COMP(R0, R1)")
    a("IF LE JUMP _stk_end")
    a(f"R2 = DM({S_FS}, I7)")
    a("R3 = 1024")
    a("R0 = DM(4, I6)", "dispersion")
    a("COMP(R0, R1)")
    a("IF NE JUMP _stk_disp")
    a(f"R13 = DM({V_CB}, I5)", "curved_bridge")
    a("COMP(R2, R3)")
    a("IF LT JUMP _stk_cc_loop")
    a("JUMP _stk_cf_loop")
    a.label("_stk_disp")
    a(f"R0 = DM({S_RNGP}, I7)")
    a("I0 = R0")
    a(f"R4 = DM({S_FA}, I7)")
    a("R5 = 256")
    a("R0 = PASS R12", "(DAG gap)")
    a("R13 = DM(I0, M5)", "the generator's word")
    a("I0 = R12", "in")
    a("COMP(R2, R3)")
    a("IF LT JUMP _stk_dc_loop")
