E_BIG, E_C65536, E_Y32, E_D32, E_TWO, E_ONE = range(6)
EX_DAGS = ["I0", "I1", "I2", "I4", "M6", "L0", "L1", "L2", "L4"]
EX_FRAME = 8
S_ERNG, S_EF = 7, 8


def svf_lp(a: Asm) -> None:
    """F0 = the excitation low pass of F0 (g R9, r R10, h R11, state_1 R14, state_2 R15), temp[n] = it, aux[n] += it."""
    a("F1 = F10 * F14", "hp = (x - r * s1 - g * s1 - s2) * h")
    a("F1 = F0 - F1")
    a("F2 = F9 * F14")
    a("F1 = F1 - F2")
    a("F1 = F1 - F15")
    a("F1 = F1 * F11")
    a("F2 = F9 * F1", "g * hp")
    a("F3 = F2 + F14", "bp = g * hp + s1")
    a("F14 = F2 + F3", "s1 = g * hp + bp")
    a("F2 = F9 * F3", "g * bp")
    a("F0 = F2 + F15", "lp = g * bp + s2")
    a("F15 = F2 + F0", "s2 = g * bp + lp")
    a("DM(I0, M6) = R0", "temp[n] = lp")
    a("R1 = DM(I1, M5)", "aux[n] += temp[n]")
    a("F1 = F1 + F0")
    a("DM(I1, M6) = R1")


def excite_kernel(a: Asm) -> None:
    a.prologue("string_excite_kernel", EX_DAGS, EX_FRAME)
    a(f"DM({S_EF}, I7) = R4", "f")
    a("I0 = R8", "temp")
    a("I1 = R12", "aux")
    a("R0 = DM(4, I6)", "k")
    a("I4 = R0")
    a("I2 = R4")
    a("R0 = DM(3, I6)", "rng")
    a(f"DM({S_ERNG}, I7) = R0")
    recip_const(a, E_D32, E_TWO, E_Y32)
    a("R9 = DM(0, I2)", "g")
    a("R10 = DM(1, I2)", "r")
    a("R11 = DM(2, I2)", "h")
    a("R14 = DM(3, I2)", "state_1")
    a("R15 = DM(4, I2)", "state_2")
    a(f"R0 = DM({S_ERNG}, I7)")
    a("I2 = R0")
    a("R12 = DM(2, I6)", "noise_samples")
    a("R0 = 0")
    a("R1 = 0", "(DAG gap)")
    a("R13 = DM(I2, M5)", "the generator's word")
    a("COMP(R12, R0)")
    a("IF LE JUMP _ste_z")
    a.label("_ste_n")
    rng_float(a, "F0", E_BIG, E_C65536, E_Y32, E_D32)
    a(f"R1 = DM({E_TWO}, I4)", "2.0f * rng_float(rng) - 1.0f")
    a("F0 = F1 * F0")
    a(f"R1 = DM({E_ONE}, I4)")
    a("F0 = F0 - F1")
    svf_lp(a)
    a("R1 = 1")
    a.iadd("R12 = R12 - R1")
    a("IF NE JUMP _ste_n")
    a.label("_ste_z")
    a("R12 = DM(1, I6)", "size - noise_samples zeros")
    a("R1 = DM(2, I6)")
    a.iadd("R12 = R12 - R1")
    a("R0 = 0")
    a("COMP(R12, R0)")
