    a.iadd("R2 = R2 + R3")
    a("I3 = R2")
    a("R5 = 0", "(DAG gap)")
    a("R6 = 0")
    a("R7 = 0")
    a("R3 = DM(0, I3)")
    a("R4 = DM(1, I3)")
    a("F4 = F4 - F3")
    a("F4 = F4 * F0")
