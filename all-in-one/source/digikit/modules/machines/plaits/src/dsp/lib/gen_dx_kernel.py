def sine_op(a: Asm, j: int) -> None:
    """pm (F0) = SinePM(phase[j] += frequency[j], pm) * amplitude[j]; amplitude[j] += amplitude_increment[j].
    R5 = 32.0f, R6 = 2^26, R7 = 2^31, R8 = 1.0f; I4 = &k->frequency[i]; I2 = lut_sine, I3 = lut_sine + 1."""
    p, amp = PH[j], AMP[j]
    a(f"R1 = DM({j}, I4)")
    a.iadd(f"{p} = {p} + R1", f"phase[{j}] += frequency[{j}]")
    a("F0 = F0 + F5", "x = (pm + 32.0f) * 67108864.0f")
    a("F0 = F0 * F6")
    a("F2 = F0 - F7", "if (x >= 2147483648.0f) x -= 2147483648.0f")
    a("COMP(F0, F7)")
    a("IF GE R0 = R2 OR R2")
    a("R0 = TRUNC F0", "(unsigned int)(int)x << 6")
    a("R0 = LSHIFT R0 BY 6")
    a.iadd(f"R0 = {p} + R0", "phase += ..")
    a("R1 = LSHIFT R0 BY -23", "integral = phase >> 23")
    a("M4 = R1")
    a("R0 = FEXT R0 BY 0:23", "fractional = (0x3F800000 | (phase & 0x7FFFFF)) - 1.0f")
    a("R0 = R0 OR R8")
    a("F0 = F0 - F8")
    a("R3 = DM(M4, I2)", "a = lut_sine[integral]")
    a("R4 = DM(M4, I3)", "b = lut_sine[integral + 1]")
    a("F4 = F4 - F3", "a + (b - a) * fractional")
    a("F4 = F4 * F0")
    a("F4 = F3 + F4")
    a(f"F0 = F4 * {amp}", f"pm = .. * amplitude[{j}]")
    a(f"R1 = DM({6 + j}, I4)")
    a(f"{amp} = {amp} + F1", f"amplitude[{j}] += amplitude_increment[{j}]")


def renderer(a: Asm, v: int) -> None:
    n, ms, add = VARIANTS[v]
    regs = FBREGS.get(v)
    a.label(f"_dxv_v{v}")
    if ms >= 0:
        a(f"R1 = DM({S_FBP}, I7)", "previous_0, previous_1 = fb_state")
        a("I0 = R1")
        if regs:
            a(f"{regs[1]} = DM({S_FB}, I7)", "fb_scale")
        a(f"R1 = DM({S_SIZE}, I7)")
        a("R12 = DM(0, I0)")
        if regs:
            a(f"{regs[0]} = DM(1, I0)")
        else:
            a("R0 = DM(1, I0)")
            a(f"DM({S_P1}, I7) = R0")
    else:
        a(f"R1 = DM({S_SIZE}, I7)")
    a(f"LCNTR = R1, DO _dxv_e{v} UNTIL LCE")
    if ms >= 0:
        if regs:
            a(f"F0 = F12 + F{regs[0][1:]}", "pm = (previous_0 + previous_1) * fb_scale")
            a(f"F0 = F0 * F{regs[1][1:]}")
        else:
            a(f"R1 = DM({S_P1}, I7)", "pm = (previous_0 + previous_1) * fb_scale")
            a("F0 = F12 + F1")
            a(f"R1 = DM({S_FB}, I7)")
            a("F0 = F0 * F1")
    elif ms == -2:
        a("R0 = DM(I0, M6)", "pm = *modulation++")
    else:
        a("R0 = 0", "pm = 0.0f")
    for j in range(n):
        sine_op(a, j)
        if j == ms:
            if regs:
                a(f"{regs[0]} = PASS R12", "previous_1 = previous_0")
            else:
                a(f"DM({S_P1}, I7) = R12", "previous_1 = previous_0")
            a("R12 = PASS R0", "previous_0 = pm")
    if add:
        a("R1 = DM(I1, M5)", "*out++ += pm")
        a("F1 = F1 + F0")
        a.label(f"_dxv_e{v}")
        a("DM(I1, M6) = R1")
    else:
        a.label(f"_dxv_e{v}")
        a("DM(I1, M6) = R0", "*out++ = pm")
    a(f"R1 = DM({S_VP}, I7)", "ops_phase[], ops_amplitude[] = phase[], amplitude[]")
    a("I4 = R1")
    if ms >= 0:
        a("DM(0, I0) = R12", "fb_state = previous_0, previous_1")
        if regs:
            a(f"DM(1, I0) = {regs[0]}")
        else:
            a(f"R0 = DM({S_P1}, I7)")
            a("DM(1, I0) = R0")
    else:
        a("R0 = 0", "(DAG gap)")
        a("R1 = 0")
    for j in range(n):
        a(f"DM({j}, I4) = {PH[j]}")
        a(f"DM({6 + j}, I4) = R{AMP[j][1:]}")
    a("JUMP _dxv_call")


