def env_set_kernel() -> str:
    a = Asm()
    dags = ["I0", "I1", "I2", "M4", "L0", "L1", "L2"]
    a.label("dx_env_set_kernel.")
    push(a, dags)
    for r in dags[4:]:
        a(f"{r} = 0")
    a("I0 = R4", "e")
    a("I1 = R8", "op")
    a("R0 = pl_dx_op_level.")
    a("I2 = R0")
    a(f"R5 = {K4B}")
    a("R6 = 0x3E000000", "0.125f")
    a(f"R7 = {HALF}")
    for i in range(4):
        a(f"R0 = DM({4 + i}, I1)", f"level[{i}]: pl_dx_op_level[env_level[{i}]]")
        a("M4 = R0")
        a("R2 = -2")
        a("R4 = 133")
        a("R8 = 1")
        a("R1 = DM(M4, I2)")
        a("R1 = R1 AND R2", "(level_scaled & ~1) + global_level - 133")
        a.iadd("R1 = R1 + R12")
        a.iadd("R1 = R1 - R4")
        a("R3 = R1 OR R5", "0.125f * (level_scaled < 1 ? 0.5f : itof_nonneg(level_scaled))")
        a("F3 = F3 - F5")
        a("COMP(R1, R8)")
        a("IF LT R3 = R7 OR R7")
        a("F3 = F6 * F3")
        a(f"DM({E_LEVEL + i}, I0) = R3")
    a("R0 = pl_dx_op_increment.")
    a("I2 = R0")
    for i in range(4):
        a(f"R0 = DM({i}, I1)", f"increment[{i}] = pl_dx_op_increment[env_rate[{i}]]")
        a("M4 = R0")
        a(f"R2 = DM({E_LEVEL + ((i + 3) & 3)}, I0)", "from")
        a(f"R3 = DM({E_LEVEL + i}, I0)", "to")
        a("R4 = 0")
        a("R1 = DM(M4, I2)")
        a("COMP(F2, F3)", "from == to")
        a(f"IF NE JUMP _dxe_ne{i}")
        a("R4 = 0x3F19999A", "increment *= 0.6f")
        a("F1 = F1 * F4")
        if i == 0:
            a(f"R4 = DM({4 + i}, I1)", "if (i == 0 && env_level[i] == 0) increment *= 20.0f")
            a("R8 = 0")
            a("COMP(R4, R8)")
            a(f"IF NE JUMP _dxe_st{i}")
            a("R4 = 0x41A00000")
            a("F1 = F1 * F4")
        a(f"JUMP _dxe_st{i}")
        a.label(f"_dxe_ne{i}")
        a("COMP(F2, F3)", "from < to: selcc's IF GE takes the else")
        a(f"IF GE JUMP _dxe_gt{i}")
        a("R4 = 0x40D66666", "from = maxf(6.7f, from), to = maxf(6.7f, to)")
        a("COMP(F4, F2)")
        a("IF GT R2 = R4 OR R4")
        a("COMP(F4, F3)")
        a("IF GT R3 = R4 OR R4")
        a("COMP(F2, F3)")
        a(f"IF NE JUMP _dxe_dv{i}")
        a(f"R1 = {ONE}", "increment = 1.0f")
        a(f"JUMP _dxe_st{i}")
        a.label(f"_dxe_dv{i}")
        a("F2 = F3 - F2", "increment *= 7.2f / (to - from)")
        a("R3 = 0x40E66666")
        a("CALL _dxe_div")
        a("F1 = F1 * F2")
        a(f"JUMP _dxe_st{i}")
        a.label(f"_dxe_gt{i}")
        a("F2 = F2 - F3", "increment *= 1.0f / (from - to)")
        a(f"R3 = {ONE}")
        a("CALL _dxe_div")
        a("F1 = F1 * F2")
        a.label(f"_dxe_st{i}")
        a("R4 = 0x3F6B3333", "increment * DX_ENV_SCALE")
        a("F1 = F1 * F4")
        a(f"DM({E_INC + i}, I0) = R1")
    a("R0 = 0", "(DAG gap)")
    a("R1 = 0")
    pop(a, dags)
    ret(a)
    a.label("_dxe_div")
    a("F4 = RECIPS F2", "F2 = F3 / F2 as selcc divides (uses R4, R6-R8)")
    a("R7 = 0x40000000")
    a("F6 = F2 * F4")
    a("F6 = F7 - F6")
    a("F4 = F4 * F6")
    a("F6 = F2 * F4")
    a("F6 = F7 - F6")
    a("F4 = F4 * F6")
    a("F7 = F3 * F4")
    a("F6 = F2 * F7")
    a("F6 = F3 - F6")
    a("F6 = F6 * F4")
    a("F2 = F7 + F6")
    a.rts()
    return "\n".join(a.lines) + "\n"


