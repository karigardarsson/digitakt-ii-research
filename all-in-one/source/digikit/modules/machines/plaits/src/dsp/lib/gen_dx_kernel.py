    a("R9 = DM(8, I4)")
    a("I4 = R1", "&k->frequency[i]")
    a(f"R1 = DM({S_SZB}, I7)")
    a(f"R2 = DM({S_TEMP}, I7)")
    a("R7 = FEXT R3 BY 16:8", "buffers[input_index]")
