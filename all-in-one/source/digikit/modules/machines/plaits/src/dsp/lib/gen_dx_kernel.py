class Asm:
    def __init__(self) -> None:
        self.lines: list[str] = []

    def __call__(self, text: str, comment: str = "") -> None:
        line = f"    {text};"
        line = f"{line:<56}// {comment}" if comment else line
        if "DM(M" in text:
            self.lines += ["    .NOCOMPRESS;", line, "    .COMPRESS;"]
        else:
            self.lines.append(line)

    def label(self, name: str) -> None:
        self.lines.append(f"{name}:")

    def iadd(self, text: str, comment: str = "") -> None:
        self.lines += ["    .NOCOMPRESS;", f"    {text};" + (f"  // {comment}" if comment else ""), "    .COMPRESS;"]

    def rts(self) -> None:
        self.lines += ["    .NOCOMPRESS;", "    RTS (DB);", "    .COMPRESS;", "    NOP;", "    NOP;"]


def itof(a: Asm, r: int, comment: str = "") -> None:
    """F{r} = itof_nonneg(R{r}) (R11 = 0x4B000000 = 8388608.0f)."""
    a(f"R{r} = R{r} OR R11", comment or "itof_nonneg: (0x4B000000 | i) as a float - 8388608.0f")
    a(f"F{r} = F{r} - F11")


def env_value_at(a: Asm) -> None:
    """_dxv_va: F5 = env_value_at(I1, R3 = stage, F2 = phase, F5 = start, reshape 1). Uses R1, R6, R7, M4, F2."""
    a.label("_dxv_va")
    a("R1 = 3")
    a.iadd("R6 = R3 + R1", "level[(stage + 3) & 3]")
    a("R6 = R6 AND R1")
    a(f"R1 = {E_LEVEL}")
    a.iadd("R6 = R6 + R1")
    a("M4 = R6")
    a.iadd("R7 = R3 + R1", "level[stage]")
    a("R1 = 0xC2C80000", "start == DX_PREVIOUS_LEVEL (-100.0f)")
    a("COMP(F5, F1)")
    a("R6 = DM(M4, I1)")
    a("M4 = R7")
    a("IF EQ R5 = R6 OR R6", "from")
    a("R1 = 0x40D66666", "6.7f")
    a("R6 = DM(M4, I1)", "to")
    a("COMP(F5, F6)", "if (reshape != 0 && from < to): selcc's IF GE skips")
    a("IF GE JUMP _dxv_va2")
    a(f"R7 = DM({S_RSH}, I7)")
    a("R7 = PASS R7")
    a("IF EQ JUMP _dxv_va2")
    a("COMP(F1, F5)", "from = maxf(6.7f, from)")
    a("IF GT R5 = R1 OR R1")
    a("COMP(F1, F6)", "to = maxf(6.7f, to)")
    a("IF GT R6 = R1 OR R1")
    a("R1 = 0x40200000", "phase *= (2.5f - phase) * 0.666667f")
    a("F1 = F1 - F2")
    a("R7 = 0x3F2AAAB0")
    a("F1 = F1 * F7")
    a("F2 = F2 * F1")
    a.label("_dxv_va2")
    a("F6 = F6 - F5", "phase * (to - from) + from")
    a("F6 = F2 * F6")
    a("F5 = F6 + F5")
    a.rts()


def env_render(a: Asm) -> None:
    """_dxv_env: F5 = env_render(I1, R14 = gate, F0 = rate, ad_scale, release_scale, reshape = slot S_RSH).
    Uses R1-R7, M4, F2."""
    a.label("_dxv_env")
    a(f"R3 = DM({E_STAGE}, I1)", "stage")
    a("R1 = 3")
    a("R2 = 0")
    a("COMP(R14, R2)", "gate")
    a("IF EQ JUMP _dxv_off")
    a("COMP(R3, R1)")
    a("IF NE JUMP _dxv_go")
    a("R4 = 0")
    a("JUMP _dxv_tr")
    a.label("_dxv_off")
    a("COMP(R3, R1)")
    a("IF EQ JUMP _dxv_go")
    a("R4 = 3")
    a.label("_dxv_tr")
    a(f"R2 = DM({E_PHASE}, I1)", "start = env_value_at(stage, phase, start)")
    a(f"R5 = DM({E_START}, I1)")
    a("CALL _dxv_va")
    a(f"DM({E_START}, I1) = R5")
    a(f"DM({E_STAGE}, I1) = R4")
    a("R3 = PASS R4")
    a("R2 = 0")
    a(f"DM({E_PHASE}, I1) = R2", "phase = 0.0f")
    a.label("_dxv_go")
    a("R1 = 3")
    a.iadd("R2 = R3 + R1", "increment[stage]")
    a("M4 = R2")
    a(f"R5 = DM({S_AD}, I7)")
    a(f"R6 = DM({S_RS}, I7)")
    a("COMP(R3, R1)", "stage == 3 ? release_scale : ad_scale")
    a("IF EQ R5 = R6 OR R6")
    a(f"R2 = DM({E_PHASE}, I1)")
    a("R1 = DM(M4, I1)")
    a("F1 = F1 * F0", "phase += increment[stage] * rate * scale")
    a("F1 = F1 * F5")
    a("F2 = F2 + F1")
    a(f"R5 = DM({E_START}, I1)")
    a(f"R1 = {ONE}")
    a("COMP(F2, F1)", "if (phase >= 1.0f): selcc's IF LT skips")
    a("IF LT JUMP _dxv_nw")
    a("R1 = 2")
    a("COMP(R3, R1)", "stage >= 2: selcc's IF LT advances")
    a("IF LT JUMP _dxv_adv")
    a(f"R2 = {ONE}", "phase = 1.0f")
    a("JUMP _dxv_st")
    a.label("_dxv_adv")
    a("R2 = 0", "phase = 0.0f, ++stage")
    a("R1 = 1")
    a.iadd("R3 = R3 + R1")
    a.label("_dxv_st")
    a("R5 = 0xC2C80000", "start = DX_PREVIOUS_LEVEL")
    a.label("_dxv_nw")
    a(f"DM({E_STAGE}, I1) = R3")
    a(f"DM({E_PHASE}, I1) = R2")
    a(f"DM({E_START}, I1) = R5")
    a("CALL _dxv_va", "env_value_at(stage, phase, start)")
    a.rts()


def pow2_fast_2(a: Asm) -> None:
    """_dxv_p2: R0 = pow2_fast_2(F0) (its bits). Uses R1-R4."""
    a.label("_dxv_p2")
    a("R1 = TRUNC F0", "x_integral = (int)x")
    a("R2 = 1")
    a.iadd("R3 = R1 - R2")
    a("R2 = 0")
    a("COMP(F0, F2)", "if (x < 0.0f) --x_integral: selcc's IF GE skips")
    a("IF LT R1 = R3 OR R3")
    a("R2 = R1 OR R11", "itof_signed(x_integral)")
    a("F2 = F2 - F11")
    a("R3 = -R1")
    a("R3 = R3 OR R11")
    a("F3 = F3 - F11")
    a("F3 = -F3")
    a("R4 = 0")
    a("COMP(R1, R4)")
    a("IF LT R2 = R3 OR R3")
    a("F0 = F0 - F2", "x -= itof_signed(x_integral)")
    a("R2 = 0x3EAFDF3B", "r = 1.0f + x * (0.6565f + x * 0.3435f)")
    a("F2 = F0 * F2")
    a("R3 = 0x3F281062")
    a("F2 = F3 + F2")
    a("F2 = F0 * F2")
    a(f"R3 = {ONE}")
    a("F2 = F3 + F2")
    a("R1 = LSHIFT R1 BY 23", "float_bits(r) + (x_integral << 23)")
    a.iadd("R0 = R2 + R1")
    a.rts()


def pow2_fast_1(a: Asm, r: int) -> None:
    """R{r} = pow2_fast_1(F{r}) (its bits): (int)(8388608.0f * (127.0f + x)). Uses R3."""
    a("R3 = 0x42FE0000", "pow2_fast_1: (int)(8388608.0f * (127.0f + x))")
    a(f"F{r} = F3 + F{r}")
    a(f"F{r} = F11 * F{r}")
    a(f"R{r} = TRUNC F{r}")


def prefix(a: Asm) -> None:
    """voice_render up to the operator loop: the scales, the pitch envelope, f0, the note-on, then the values of the
    operator loop. I2 = v, I4 = k, R9 = envelope_rate, R11 = 0x4B000000."""
    a.label("_dxv_pre")
    a(f"R0 = DM({V_PEC}, I2)", "ad_scale = pow2_fast_1((0.5f - envelope_control) * 8.0f)")
    a(f"R1 = {HALF}")
    a("F1 = F1 - F0")
    a("R2 = 0x41000000")
    a("F1 = F1 * F2")
    pow2_fast_1(a, 1)
    a(f"DM({S_AD}, I7) = R1")
    a("R1 = 0x3E99999A", "r_scale = pow2_fast_1(-absf(envelope_control - 0.3f) * 8.0f)")
    a("F1 = F0 - F1")
    a("F3 = -F1")
    a("R4 = 0")
    a("COMP(F1, F4)")
    a("IF LT R1 = R3 OR R3")
    a("F1 = -F1")
    a("F1 = F1 * F2")
    pow2_fast_1(a, 1)
    a(f"DM({S_RS}, I7) = R1")
    a(f"R14 = DM({V_PGATE}, I2)", "p_gate")
    a("R0 = 0")
    a(f"DM({S_RSH}, I7) = R0")
    a(f"R0 = {4 * V_PITCH_ENV}")
    a(f"R8 = DM({S_V}, I7)")
    a.iadd("R0 = R8 + R0")
    a("I1 = R0", "&pitch_env")
    a("R0 = PASS R9")
    a("CALL _dxv_env", "pitch_envelope = env_render(&pitch_env, gate, envelope_rate, .., 0)")
    a(f"R1 = DM({V_PPM}, I2)", "pitch_mod = pitch_envelope + p_pitch_mod")
    a("F5 = F5 + F1")
    a(f"R1 = DM({V_PNOTE}, I2)", "p_note - 9.0f + pitch_mod * 12.0f")
    a("R2 = 0x41100000")
    a("F1 = F1 - F2")
    a("R2 = 0x41400000")
    a("F5 = F5 * F2")
    a("F1 = F1 + F5")
    a(f"R2 = {ONE}", "semitones_to_ratio_safe: scale")
    a.label("_dxv_s1")
    a("R3 = 0x42F00000", "while (semitones > 120.0f)")
    a("COMP(F1, F3)")
    a("IF LE JUMP _dxv_s2")
    a("F1 = F1 - F3")
    a("R4 = 0x44800000")
    a("F2 = F2 * F4")
    a("JUMP _dxv_s1")
    a.label("_dxv_s2")
    a("R3 = 0xC2F00000", "while (semitones < -120.0f)")
    a("COMP(F1, F3)")
    a("IF GE JUMP _dxv_s3")
    a("R3 = 0x42F00000")
    a("F1 = F1 + F3")
    a("R4 = 0x3A800000")
    a("F2 = F2 * F4")
    a("JUMP _dxv_s2")
    a.label("_dxv_s3")
    a("R3 = 0x43000000", "SemitonesToRatio: pitch = semitones + 128.0f")
    a("F1 = F1 + F3")
    a("R3 = TRUNC F1")
    a("R4 = R3 OR R11")
    a("F4 = F4 - F11")
    a("F1 = F1 - F4", "pitch_fractional")
    a(f"R4 = DM({K_RHIGH}, I4)")
    a("R5 = LSHIFT R3 BY 2")
    a.iadd("R4 = R4 + R5")
    a("I3 = R4", "&lut_pitch_ratio_high[pitch_integral]")
    a("R5 = 0x43800000")
    a("F1 = F1 * F5")
    a("R1 = TRUNC F1")
    a("R5 = LSHIFT R1 BY 2")
    a(f"R4 = DM({K_RLOW}, I4)")
    a.iadd("R4 = R4 + R5")
    a("R3 = DM(0, I3)")
    a("I3 = R4", "&lut_pitch_ratio_low[(int)(pitch_fractional * 256.0f)]")
    a("R5 = 0", "(DAG gap)")
    a("R6 = 0")
    a("R7 = 0")
    a("R4 = DM(0, I3)")
    a("F3 = F3 * F4")
    a("F2 = F2 * F3", "scale * SemitonesToRatio(semitones)")
    a("R3 = 0x39962FC9", "f0 = DX_A0 * 0.25f * ..")
    a("F15 = F3 * F2")
