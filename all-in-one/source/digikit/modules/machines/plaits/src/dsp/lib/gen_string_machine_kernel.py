"""Generate lib/string_machine_sm.s: STRING MACHINE's mixdown filters and the Ensemble chorus (engines/string_machine.c,
lib/ensemble.c) as one SISD kernel, bit-identical in output to selcc's code of the C (-DPL_SM_C).

    python3 modules/machines/plaits/src/dsp/lib/gen_string_machine_kernel.py

The mixdown loop and ensemble_process run per sample in one loop (each stage owns its state; the ensemble reads the
mixdown's output of the same sample, as the C's second loop does). Every float operation is the C's, with the same
operands in the same order (commutative swaps only).

The chorus line is not cleared at init (ensemble_init in the DSP build sets fresh_ = 0 instead): every tap reads the
sample its own line (L at offset 0, R at offset 512 from the write pointer) wrote oi (resp. oi + 1) samples earlier,
and the other line never writes that word in between, so the C's cleared memory is seen exactly when fewer than oi
(oi + 1) samples have run since init; the kernel selects 0.0f for those words. From 370 samples on (oi + 1 <= 369) the
unchecked loop runs. tests/plaits/test_string_machine_kernel.py checks it against the C on the concrete core.
"""

from __future__ import annotations

from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE / "string_machine_sm.s"

F0_66, F0_33, F192 = "0x3F28F5C3", "0x3EA8F5C3", "0x43400000"
BIAS = "0x4B000000"
FRESH_FULL = 370

HEADER = """\
// machines/plaits: STRING MACHINE's mixdown filters and Ensemble chorus (engines/string_machine.c, lib/ensemble.c),
// hand-written SISD kernel. Generated by lib/gen_string_machine_kernel.py; do not edit by hand.
//
// sm_tail_kernel(float *svf, Ensemble *e, const float *k, float *out, float *aux, int size): svf = &svf_lp_[0]
//   (svf_lp_[0..1], svf_bp_[0..1]); k[0..5] = f_0, f_1, amount, dry_amount, a, b. Per sample: the mixdown (two
//   NaiveSvf low passes, the 0.66 / 0.33 cross mix) into out and aux, then the ensemble in place.
//   Bit-identical in output to selcc's code of the C (-DPL_SM_C); the chorus line is never cleared: reads of the C's
//   cleared memory give 0.0f (lib/gen_string_machine_kernel.py, fresh_).
//
// State on return: R0-R8, R12, I4 and the flags change; every other register is as on entry (R9-R11, R13-R15 saved
// above I7; I0, I1, I2, I3, M6, L0-L4 pushed through R0, M6 = 1 and L0-L4 = 0 set here). No SIMD.
// ABI: as the other kernels (lib/wavetable_sm.s). Assembled under .COMPRESS; integer additions in their 48-bit form.

.SECTION/PM seg_pmco;
.GLOBAL sm_tail_kernel.;
.EXTERN pl_lut_sine.;
.COMPRESS;
"""


class Asm:
    def __init__(self) -> None:
        self.lines: list[str] = []

    def __call__(self, text: str, comment: str = "") -> None:
        line = f"    {text};"
        if comment:
            line = f"{line:<56}// {comment}"
        self.lines.append(line)

    def label(self, name: str) -> None:
        self.lines.append(f"{name}:")

    def iadd(self, text: str, comment: str = "") -> None:
        self.lines.append("    .NOCOMPRESS;")
        self(text, comment)
        self.lines.append("    .COMPRESS;")

    def slot(self, reg: str, k: int, comment: str = "") -> None:
        self(f"{reg} = DM({k}, I7)", comment)

    def put(self, k: int, reg: str, comment: str = "") -> None:
        self(f"DM({k}, I7) = {reg}", comment)


DAGS = ["I0", "I1", "I2", "I3", "M6", "L0", "L1", "L2", "L3", "L4"]
SAVES = ["R9", "R10", "R11", "R13", "R14", "R15"]
(
    S_F0,
    S_F1,
    S_AMT,
    S_DRY,
    S_A,
    S_B,
    S_CNT,
    S_N,
    S_LP0,
    S_LP1,
    S_BP0,
    S_BP1,
    S_L,
    S_R,
    S_M1,
    S_M2,
    S_M3,
    S_WET,
) = range(7, 25)
FRAME = 24


def tap(a: Asm, base: int, mod: int, first: bool, checked: bool) -> None:
    """ENS_TAP(wet, base, mod + 192.0f): wet (slot S_WET) += (a + (b - a) * of) * 0.33f. Uses R0-R8."""
    a.slot("R0", mod)
    a(f"R1 = {F192}")
    a("F0 = F0 + F1", "o = mod + 192.0f")
    a("R2 = TRUNC F0", "oi = (int)o")
    a("R3 = R11 OR R2")
    a("F3 = F3 - F11")
    a("F0 = F0 - F3", "of = o - itof_nonneg(oi)")
    a.iadd("R4 = R15 + R2", "ix = (wp + oi + base) & ENS_MASK")
    if base:
        a(f"R5 = {base}")
        a.iadd("R4 = R4 + R5")
    a("R5 = 1023")
    a("R4 = R4 AND R5")
    a("R6 = 1")
    a.iadd("R6 = R4 + R6", "(ix + 1) & ENS_MASK")
    a("R6 = R6 AND R5")
    a("R4 = LSHIFT R4 BY 2")
    a("R6 = LSHIFT R6 BY 2")
    a.iadd("R4 = R4 + R14")
    a.iadd("R6 = R6 + R14")
    a("I4 = R4")
    a("I3 = R6")
    if checked:
        a.slot("R7", S_N, "fresh_ < oi (oi + 1): the C's cleared memory")
        a("R8 = 1")
        a.iadd("R8 = R2 + R8")
        a("R5 = 0")
    else:
        a("R5 = 0")
        a("R7 = 0", "(DAG gap)")
    a("R1 = DM(I4, M5)", "a = buf[ix]")
    a("R3 = DM(I3, M5)", "b = buf[(ix + 1) & ENS_MASK]")
    if checked:
        a("COMP(R7, R2)")
        a("IF LT R1 = R5 OR R5")
        a("COMP(R7, R8)")
        a("IF LT R3 = R5 OR R5")
    a("F3 = F3 - F1", "a + (b - a) * of")
    a("F3 = F3 * F0")
    a("F3 = F1 + F3")
    a(f"R1 = {F0_33}")
    a("F3 = F3 * F1", "* 0.33f")
    if first:
        a("R1 = 0", "wet = 0.0f")
    else:
        a.slot("R1", S_WET)
    a("F1 = F1 + F3", "wet += ..")
    a.put(S_WET, "R1")


def body(a: Asm, p: str, checked: bool) -> None:
    a.label(f"{p}_loop")
    # mixdown: two NaiveSvf low passes and the cross mix
    a("R0 = DM(I0, M5)", "out[i]")
    a("R1 = DM(I1, M5)", "aux[i]")
    a.slot("R2", S_BP0)
    a.slot("R3", S_BP1)
    a.slot("R4", S_LP0)
    a.slot("R5", S_LP1)
    a.slot("R6", S_F0)
    a.slot("R7", S_F1)
    a("F0 = F0 - F2", "notch_0 = out[i] - bp_0")
    a("F1 = F1 - F3", "notch_1 = aux[i] - bp_1")
    a("F8 = F6 * F2", "lp_0 += f_0 * bp_0")
    a("F4 = F4 + F8")
    a("F8 = F7 * F3", "lp_1 += f_1 * bp_1")
    a("F5 = F5 + F8")
    a("F0 = F0 - F4", "bp_0 += f_0 * (notch_0 - lp_0)")
    a("F0 = F6 * F0")
    a("F2 = F2 + F0")
    a("F1 = F1 - F5", "bp_1 += f_1 * (notch_1 - lp_1)")
    a("F1 = F7 * F1")
    a("F3 = F3 + F1")
    a.put(S_BP0, "R2")
    a.put(S_BP1, "R3")
    a.put(S_LP0, "R4")
    a.put(S_LP1, "R5")
    a(f"R6 = {F0_66}")
    a(f"R7 = {F0_33}")
    a("F0 = F6 * F4", "out[i] = 0.66f * l + 0.33f * r")
    a("F1 = F7 * F5")
    a("F0 = F0 + F1")
    a.put(S_L, "R0", "l (the ensemble's input)")
    a("F1 = F6 * F5", "aux[i] = 0.66f * r + 0.33f * l")
    a("F2 = F7 * F4")
    a("F1 = F1 + F2")
    a.put(S_R, "R1", "r")
    # the ensemble: write pointer, LFOs
    a("R2 = 1")
    a.iadd("R15 = R15 - R2", "--wp")
    a("R2 = 0")
    a("COMP(R15, R2)")
    a(f"IF GE JUMP {p}_w")
    a("R2 = 1024")
    a.iadd("R15 = R15 + R2")
    a.label(f"{p}_w")
    a("R2 = 67289")
    a.iadd("R13 = R13 + R2", "phase_1 += 67289u")
    a("R2 = 589980")
    a.iadd("R12 = R12 + R2", "phase_2 += 589980u")
    a("R8 = -23")

    def sine_at(dst: int, ph: int, add: str | None) -> None:
        if add is None:
            a(f"R{dst} = LSHIFT R{ph} BY R8", "sine[phase >> 23]")
        else:
            a(f"R{dst} = {add}")
            a.iadd(f"R{dst} = R{ph} + R{dst}")
            a(f"R{dst} = LSHIFT R{dst} BY R8")
        a(f"R{dst} = LSHIFT R{dst} BY 2")
        a.iadd(f"R{dst} = R{dst} + R10")

    sine_at(2, 13, None)
    sine_at(3, 13, "0x547AE147")
    sine_at(4, 13, "0xA8F5C28F")
    a("I4 = R2")
    a("I2 = R3")
    a("I3 = R4")
    sine_at(5, 12, None)
    sine_at(6, 12, "0x547AE147")
    sine_at(7, 12, "0xA8F5C28F")
    a("R2 = DM(I4, M5)", "slow_0")
    a("R3 = DM(I2, M5)", "slow_120")
    a("R4 = DM(I3, M5)", "slow_240")
    a("I4 = R5")
    a("I2 = R6")
    a("I3 = R7")
    a.slot("R0", S_A)
    a.slot("R1", S_B)
    a("F2 = F2 * F0", "slow * a")
    a("F3 = F3 * F0")
    a("F4 = F4 * F0")
    a("R5 = DM(I4, M5)", "fast_0")
    a("R6 = DM(I2, M5)", "fast_120")
    a("R7 = DM(I3, M5)", "fast_240")
    a("F5 = F5 * F1", "mod_1 = slow_0 * a + fast_0 * b")
    a("F2 = F2 + F5")
    a.put(S_M1, "R2")
    a("F6 = F6 * F1", "mod_2")
    a("F3 = F3 + F6")
    a.put(S_M2, "R3")
    a("F7 = F7 * F1", "mod_3")
    a("F4 = F4 + F7")
    a.put(S_M3, "R4")
    # buf[wp] = l; buf[(wp + 512) & ENS_MASK] = r
    a("R0 = LSHIFT R15 BY 2")
    a.iadd("R0 = R0 + R14")
    a("I4 = R0")
    a("R1 = 512")
    a.iadd("R1 = R15 + R1")
    a("R2 = 1023")
    a("R1 = R1 AND R2")
    a("R1 = LSHIFT R1 BY 2")
    a.iadd("R1 = R1 + R14")
    a("I3 = R1")
    a.slot("R2", S_L)
    a.slot("R3", S_R)
    a("R4 = 0", "(DAG gap)")
    a("DM(I4, M5) = R2")
    a("DM(I3, M5) = R3")
    # the left taps, then the right ones
    tap(a, 0, S_M1, True, checked)
    tap(a, 0, S_M2, False, checked)
    tap(a, 512, S_M3, False, checked)
    a.slot("R1", S_WET)
    a.slot("R2", S_AMT)
    a.slot("R3", S_L)
    a.slot("R4", S_DRY)
    a("F1 = F1 * F2", "*left = wet * amount + l * dry_amount")
    a("F3 = F3 * F4")
    a("F1 = F1 + F3")
    a("DM(I0, M6) = R1")
    tap(a, 512, S_M1, True, checked)
    tap(a, 512, S_M2, False, checked)
    tap(a, 0, S_M3, False, checked)
    a.slot("R1", S_WET)
    a.slot("R2", S_AMT)
    a.slot("R3", S_R)
    a.slot("R4", S_DRY)
    a("F1 = F1 * F2", "*right = wet * amount + r * dry_amount")
    a("F3 = F3 * F4")
    a("F1 = F1 + F3")
    a("DM(I1, M6) = R1")
    if checked:
        a.slot("R0", S_N)
        a("R1 = 1")
        a.iadd("R0 = R0 + R1", "fresh_ += 1")
        a.put(S_N, "R0")
    a.slot("R0", S_CNT)
    a("R1 = 1")
    a.iadd("R0 = R0 - R1")
    a.put(S_CNT, "R0")
    a(f"IF NE JUMP {p}_loop")
    a("JUMP _smk_end")


def kernel() -> str:
    a = Asm()
    a.label("sm_tail_kernel.")
    for r in DAGS:
        a(f"R0 = {r}")
        a("DM(I7, M7) = R0")
    a("M6 = 1")
    for r in DAGS[5:]:
        a(f"{r} = 0")
    a(f"I7=MODIFY (I7,-{FRAME})(NW)")
    for i, r in enumerate(SAVES):
        a.put(i + 1, r)
    a("I2 = R4", "svf: lp_0, lp_1, bp_0, bp_1")
    a("R9 = PASS R4", "(svf again at the end: I2 is a scratch DAG in the loop)")
    a("R14 = PASS R8", "e (buffer_ at word 0)")
    a("I4 = R12", "k")
    a("R0 = DM(1, I6)", "out")
    a("I0 = R0")
    a("R0 = DM(2, I6)", "aux")
    a("I1 = R0")
    for j, sl in enumerate((S_F0, S_F1, S_AMT, S_DRY, S_A, S_B)):
        a(f"R0 = DM({j}, I4)")
        a.put(sl, "R0")
    for j, sl in enumerate((S_LP0, S_LP1, S_BP0, S_BP1)):
        a(f"R0 = DM({j}, I2)")
        a.put(sl, "R0")
    a("I3 = R14")
    a("R15 = DM(1024, I3)", "wp = write_ptr_")
    a("R13 = DM(1025, I3)", "phase_1")
    a("R12 = DM(1026, I3)", "phase_2")
    a("R0 = DM(1027, I3)", "fresh_")
    a.put(S_N, "R0")
    a(f"R11 = {BIAS}")
    a("R10 = pl_lut_sine.")
    a("R0 = DM(3, I6)", "size")
    a.put(S_CNT, "R0")
    a("R1 = 0")
    a("COMP(R0, R1)")
    a("IF LE JUMP _smk_end")
    a.slot("R1", S_N)
    a(f"R2 = {FRESH_FULL}")
    a("COMP(R1, R2)")
    a("IF LT JUMP _smc_loop")
    body(a, "_smf", False)
    body(a, "_smc", True)
    a.label("_smk_end")
    a("I2 = R9")
    for j, sl in enumerate((S_LP0, S_LP1, S_BP0, S_BP1)):
        a.slot("R0", sl)
        a(f"DM({j}, I2) = R0")
    a("I3 = R14")
    a("DM(1024, I3) = R15")
    a("DM(1025, I3) = R13")
    a("DM(1026, I3) = R12")
    a.slot("R0", S_N)
    a("DM(1027, I3) = R0")
    for i, r in enumerate(SAVES):
        a.slot(r, i + 1)
    a(f"I7=MODIFY (I7,{FRAME})(NW)")
    for i, r in enumerate(reversed(DAGS)):
        a(f"{r} = DM({i + 1}, I7)")
    a("I12 = DM(M7, I6)")
    a("JUMP (M14, I12) (DB)")
    a("RFRAME")
    a("NOP")
    return "\n".join(a.lines) + "\n"


def main() -> None:
    OUT.write_text(HEADER + "\n" + kernel())
    print(OUT)


if __name__ == "__main__":
    main()
