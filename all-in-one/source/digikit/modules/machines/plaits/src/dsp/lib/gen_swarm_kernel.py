"""Generate lib/swarm_sm.s: SWARM's per-grain sample loop (engines/swarm.c: the AdditiveSawOscillator and the
FastSineOscillator of one grain, added into out and aux) as a SISD kernel, bit-identical to selcc's code of the C loop
(-DPL_SWARM_C).

    python3 modules/machines/plaits/src/dsp/lib/gen_swarm_kernel.py

Every float operation is the C's, with the same operands in the same order (commutative swaps only); the blep helpers
and selcc's division are written out. tests/plaits/test_swarm_kernel.py checks it against the C on the concrete core.
"""

from __future__ import annotations

from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE / "swarm_sm.s"
ONE, HALF, MHALF, TWO = "0x3F800000", "0x3F000000", "0xBF000000", "0x40000000"

HEADER = """\
// machines/plaits: SWARM's per-grain sample loop (engines/swarm.c), hand-written SISD kernel.
// Generated by lib/gen_swarm_kernel.py; do not edit by hand.
//
// swarm_grain_kernel(float *g, float *out, float *aux, int size): g[0..11] = fm_v, fm_i, gn_v, gn_i, ep_v, ep_i, am_v,
//   am_i, saw_phase, saw_next, sx, sy (the grain's interpolators and oscillator state as swarm_render holds them in
//   its locals); adds the grain's saw to out and its sine to aux and writes the values back to g (g[0, 2, 4, 6, 8..11]).
//   Bit-identical to selcc's code of the C loop (-DPL_SWARM_C) (tests/plaits/test_swarm_kernel.py).
//
// State on return: R0-R8, R12, I4 and the flags change; every other register is as on entry (R9-R11, R13-R15 saved
// above I7; I0, I1, M6, L0, L1, L4 pushed through R0, M6 = 1 and L0 = L1 = L4 = 0 set here). No SIMD.
// ABI: as the other kernels (lib/wavetable_sm.s). Assembled under .COMPRESS.

.SECTION/PM seg_pmco;
.GLOBAL swarm_grain_kernel.;
.COMPRESS;
"""

AMI, CNT = 7, 8
FRAME = 8


def kernel() -> str:
    L: list[str] = []

    def a(t: str, c: str = "") -> None:
        line = f"    {t};"
        L.append(f"{line:<56}// {c}" if c else line)

    def lab(n: str) -> None:
        L.append(f"{n}:")

    lab("swarm_grain_kernel.")
    dags = ["I0", "I1", "M6", "L0", "L1", "L4"]
    for r in dags:
        a(f"R0 = {r}")
        a("DM(I7, M7) = R0")
    a("M6 = 1")
    for r in ("L0", "L1", "L4"):
        a(f"{r} = 0")
    a(f"I7=MODIFY (I7,-{FRAME})(NW)")
    saves = ["R9", "R10", "R11", "R13", "R14", "R15"]
    for i, r in enumerate(saves):
        a(f"DM({i + 1}, I7) = {r}")
    a("I4 = R4", "g")
    a("I0 = R8", "out")
    a("I1 = R12", "aux")
    a("R0 = DM(1, I6)", "size")
    a(f"DM({CNT}, I7) = R0")
    regs = [
        "R15",
        "R14",
        "R13",
        "R12",
        "R11",
        "R10",
        "R9",
        "R8",
        "R7",
        "R6",
        "R5",
        "R4",
    ]
    names = [
        "fm_v",
        "fm_i",
        "gn_v",
        "gn_i",
        "ep_v",
        "ep_i",
        "am_v",
        "am_i",
        "saw_phase",
        "saw_next",
        "sx",
        "sy",
    ]
    for j, (r, n) in enumerate(zip(regs, names, strict=True)):
        a(f"{r} = DM({j}, I4)", n)
    a(f"DM({AMI}, I7) = R8", "am_i (R8 is a temporary in the loop)")
    a("R1 = 0")
    a("COMP(R0, R1)")
    a("IF LE JUMP _swg_done")
    lab("_swg_loop")
    a("R1 = PASS R6", "this_sample = saw_next")
    a("R6 = 0", "saw_next = 0.0f")
    a("F15 = F15 + F14", "fq = fm_v += fm_i")
    a("F7 = F7 + F15", "saw_phase += fq")
    a(f"R0 = {ONE}")
    a("COMP(F7, F0)", "saw_phase >= 1.0f")
    a("IF LT JUMP _swg_nr")
    a("F7 = F7 - F0", "saw_phase -= 1.0f")
    a(f"R3 = {TWO}")
    a("F0 = RECIPS F15", "t = saw_phase / fq (selcc division)")
    a("F8 = F15 * F0")
    a("F8 = F3 - F8")
    a("F0 = F0 * F8")
    a("F8 = F15 * F0")
    a("F8 = F3 - F8")
    a("F0 = F0 * F8")
    a("F3 = F7 * F0")
    a("F8 = F15 * F3")
    a("F8 = F7 - F8")
    a("F8 = F8 * F0")
    a("F2 = F3 + F8")
    a(f"R0 = {HALF}")
    a("F0 = F0 * F2", "this_sample -= ThisBlepSample(t)")
    a("F0 = F0 * F2")
    a("F1 = F1 - F0")
    a(f"R0 = {ONE}")
    a("F3 = F0 - F2", "saw_next -= NextBlepSample(t)")
    a(f"R0 = {MHALF}")
    a("F0 = F0 * F3")
    a("F0 = F0 * F3")
    a("F6 = F6 - F0")
    lab("_swg_nr")
    a("F6 = F6 + F7", "saw_next += saw_phase")
    a("F13 = F13 + F12", "gn_v += gn_i")
    a(f"R0 = {TWO}")
    a("F0 = F0 * F1", "out[n] += (2.0f * this_sample - 1.0f) * gn_v")
    a(f"R2 = {ONE}")
    a("F0 = F0 - F2")
    a("F0 = F0 * F13")
    a("R2 = DM(I0, M5)")
    a("F2 = F2 + F0")
    a("DM(I0, M6) = R2")
    a("F11 = F11 + F10", "e = ep_v += ep_i")
    a("F0 = F11 * F4", "sx += e * sy")
    a("F5 = F5 + F0")
    a("F0 = F11 * F5", "sy -= e * sx")
    a("F4 = F4 - F0")
    a(f"R0 = DM({AMI}, I7)")
    a("F9 = F9 + F0", "am_v += am_i")
    a("F0 = F9 * F5", "aux[n] += am_v * sx")
    a("R2 = DM(I1, M5)")
    a("F2 = F2 + F0")
    a("DM(I1, M6) = R2")
    a(f"R0 = DM({CNT}, I7)")
    a("R1 = 1")
    L.append("    .NOCOMPRESS;")
    a("R0 = R0 - R1")
    L.append("    .COMPRESS;")
    a(f"DM({CNT}, I7) = R0")
    a("IF NE JUMP _swg_loop")
    lab("_swg_done")
    for j in (0, 2, 4, 6, 8, 9, 10, 11):
        a(f"DM({j}, I4) = {regs[j]}", names[j])
    for i, r in enumerate(saves):
        a(f"{r} = DM({i + 1}, I7)")
    a(f"I7=MODIFY (I7,{FRAME})(NW)")
    for i, r in enumerate(reversed(dags)):
        a(f"{r} = DM({i + 1}, I7)")
    a("I12 = DM(M7, I6)")
    a("JUMP (M14, I12) (DB)")
    a("RFRAME")
    a("NOP")
    return "\n".join(L) + "\n"


def main() -> None:
    OUT.write_text(HEADER + "\n" + kernel())
    print(OUT)


if __name__ == "__main__":
    main()
