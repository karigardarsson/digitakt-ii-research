"""Generate lib/dust_sm.s: DUST's sample loops (engines/dust.c: the particle loop, the post filter and the diffuser) as
SISD kernels, bit-identical in output to selcc's code of the C (-DPL_DUST_C).

    python3 modules/machines/plaits/src/dsp/lib/gen_dust_kernel.py

Every float operation is the C's, with the same operands in the same order (commutative swaps only); rng_float (as
in lib/drums_sm.s), SemitonesToRatio, minf, pl_rsqrt, the delay memory's 16-bit packing (DUST_READ, DUST_WRITE with
selcc's comparisons: a NaN stores 32767 as selcc's code does) and selcc's division are written out.

The delay memory is not cleared at init (the 16 KB clear was the model-change block's spike): dust_init sets fresh_ =
0 instead, and the diffuser treats a word that the C would still read as zero as zero. Every read of the diffuser is
of the sample its own line wrote o - B samples earlier (o the read's offset from the write pointer, B the line's
base; the lines are disjoint and the write pointer moves by one per sample), and no other line writes that halfword
in between; so the read sees the C's cleared memory exactly when fewer than o - B samples have run since init. The
kernel counts the samples since init in fresh_ and selects zero for those reads; from 3,412 samples on (o - B is at
most 3,411) no read can see cleared memory and the unchecked loop runs. The output and every word the C would read
later are the C's; the halfwords not yet written hold whatever the memory held (tests/plaits/test_dust_kernel.py
compares them as such).
"""

