KP = {
    "DENS": 0,
    "GAIN": 1,
    "F0": 2,
    "SPREAD": 3,
    "Q": 4,
    "SQD": 5,
    "RES": 6,
    "SYNC": 7,
    "BIG": 8,
    "C65536": 9,
    "D32": 10,
    "TWO": 11,
    "Y32": 12,
}
P_SIZE, P_OUT, P_AUX, P_PCNT, P_SCNT, P_CAN, P_SAMPLE = range(7, 14)
P_FRAME = 13


def rng_float(a: Asm, dst: str) -> None:
    """dst = rng_float(&rng) with the word in R13 (lib/gen_drum_kernels.py rng_float, I4 = k). Uses R4-R8."""
    k = KP
    a("R4 = 1664525")
    a("R5 = 1013904223")
    a(f"R13 = R13 * R4 (SSI), R6 = DM({k['BIG']}, I4)", "rng_word")
    a("R13 = R13 + R5")
    a("R7 = FEXT R13 BY 16:16", "w >> 16")
    a("R8 = FEXT R13 BY 0:16", "w & 0xFFFF")
    a("R7 = R7 OR R6", "itof_nonneg")
    a("R8 = R8 OR R6")
    a(f"F7 = F7 - F6, R5 = DM({k['C65536']}, I4)")
    a("F8 = F8 - F6")
    a(f"F7 = F7 * F5, R5 = DM({k['Y32']}, I4)", "hi * 65536.0f")
    a(f"F7 = F7 + F8, R6 = DM({k['D32']}, I4)", "+ lo")
    a("F8 = F7 * F5", "/ 4294967296.0f: q")
    a("F4 = F6 * F8")
    a("F4 = F7 - F4")
    a("F4 = F4 * F5")
    a(f"{dst} = F8 + F4")


def particles_kernel() -> str:
    a = Asm()
    k = KP
    prologue(a, "dust_particles_kernel.", P_FRAME)
    a("I1 = R4", "s")
    a("I4 = R8", "k")
    a.put(P_OUT, "R12", "out")
    a("R0 = DM(1, I6)", "aux")
    a.put(P_AUX, "R0")
    a("R0 = DM(2, I6)", "size")
    a.put(P_SIZE, "R0")
    # k[Y32] = selcc's reciprocal of 2^32 after its two Newton steps
    a(f"R8 = DM({k['D32']}, I4)")
    a(f"R4 = DM({k['TWO']}, I4)")
    a("F9 = RECIPS F8")
    a("F10 = F8 * F9")
    a("F10 = F4 - F10")
    a("F9 = F9 * F10")
    a("F10 = F8 * F9")
    a("F10 = F4 - F10")
    a("F9 = F9 * F10")
    a(f"DM({k['Y32']}, I4) = R9")
    a("R13 = DM(45, I1)", "rng = s->rng_")
    a.slot("R0", P_SIZE)
    a("R1 = 0")
    a("COMP(R0, R1)")
    a("IF LE JUMP _dpk_zd")
    a("I0 = R12", "out[n] = 0.0f; aux[n] = 0.0f")
    a.slot("R2", P_AUX)
    a("I3 = R2")
    a("LCNTR = R0, DO _dpk_clr UNTIL LCE")
    a("DM(I0, M6) = R1")
    a.label("_dpk_clr")
    a("DM(I3, M6) = R1")
    a.label("_dpk_zd")
    a("I2 = I1", "pt = the first particle")
    a("R0 = 6")
    a.put(P_PCNT, "R0")
    a.label("_dpk_part")
    rng_float(a, "F3")
    a("R9 = DM(0, I2)", "pre_gain = pt->pre_gain_")
    a("R12 = DM(1, I2)", "g")
    a("R11 = DM(2, I2)", "r")
    a("R10 = DM(3, I2)", "h")
    a("R15 = DM(4, I2)", "state_1")
    a("R14 = DM(5, I2)", "state_2")
    a("R0 = 1")
    a.put(P_CAN, "R0", "can_randomize_frequency = 1")
    a(f"R0 = DM({k['SYNC']}, I4)")
    a("R1 = 0")
    a("COMP(R0, R1)", "if (sync) u = density")
    a("IF EQ JUMP _dpk_ns")
    a(f"R3 = DM({k['DENS']}, I4)")
    a.label("_dpk_ns")
    a.slot("R0", P_OUT)
    a("I0 = R0")
    a.slot("R0", P_AUX)
    a("I3 = R0")
    a.slot("R0", P_SIZE)
    a.put(P_SCNT, "R0")
    a("R1 = 0")
    a("COMP(R0, R1)")
    a("IF LE JUMP _dpk_pend")
    a.label("_dpk_loop")
    a("R0 = 0", "sample = 0.0f")
    a(f"R1 = DM({k['DENS']}, I4)")
    a("COMP(F3, F1)", "u <= density")
    a("IF GT JUMP _dpk_imp")
    a(f"R2 = DM({k['GAIN']}, I4)")
    a("F0 = F3 * F2", "sample = u * gain")
    a.slot("R1", P_CAN)
    a("R2 = 0")
    a("COMP(R1, R2)")
    a("IF EQ JUMP _dpk_imp")
    a.put(P_SAMPLE, "R0")
    rng_float(a, "F1")
    a(f"R2 = {TWO}")
    a("F1 = F2 * F1", "v = 2.0f * rng_float(&rng) - 1.0f")
    a(f"R2 = {ONE}")
    a("F1 = F1 - F2")
    a(f"R2 = DM({k['SPREAD']}, I4)")
    a("F1 = F2 * F1", "SemitonesToRatio(spread * v)")
    a(f"R2 = {F128}")
    a("F1 = F1 + F2", "pitch = semitones + 128.0f")
    a("R2 = TRUNC F1", "pitch_integral")
    a(f"R4 = {BIAS}")
    a("R5 = R4 OR R2")
    a("F5 = F5 - F4")
    a("F1 = F1 - F5", "pitch_fractional")
    a("R2 = LSHIFT R2 BY 2")
    a("R4 = pl_lut_pitch_ratio_high.")
    a.iadd("R2 = R2 + R4")
    a("I5 = R2")
    a(f"R4 = {F256}")
    a("F1 = F1 * F4")
    a("R5 = TRUNC F1", "(int)(pitch_fractional * 256.0f)")
    a("R5 = LSHIFT R5 BY 2")
    a("R2 = DM(I5, M5)", "lut_pitch_ratio_high[pitch_integral]")
    a("R4 = pl_lut_pitch_ratio_low.")
    a.iadd("R5 = R5 + R4")
    a("I5 = R5")
    a(f"R6 = DM({k['F0']}, I4)")
    a(f"R7 = {F0_25}")
    a(f"R8 = DM({k['Q']}, I4)")
    a(f"R0 = {HALF}")
    a("R5 = DM(I5, M5)", "lut_pitch_ratio_low[..]")
    a("F2 = F2 * F5", "ratio")
    a("F2 = F2 * F6", "f = minf(ratio * f0, 0.25f)")
    a("COMP(F2, F7)")
    a("IF GE R2 = R7 OR R7")
    # pre_gain = 0.5f * pl_rsqrt(q * f * sqrt_density)
    a("F1 = F8 * F2", "q * f * sqrt_density")
    a(f"R5 = DM({k['SQD']}, I4)")
    a("F1 = F1 * F5")
    a("F4 = F0 * F1", "pl_rsqrt: h = 0.5f * x")
    a("R5 = 0")
    a("COMP(F1, F5)", "x > 0.0f")
    a("IF GT JUMP _dpk_rs")
    a("R9 = 0")
    a("JUMP _dpk_rd")
    a.label("_dpk_rs")
    a("R5 = -1")
    a("R1 = ASHIFT R1 BY R5")
    a(f"R5 = {MAGIC}")
    a.iadd("R9 = R5 - R1")
    a(f"R0 = {F1_5}")
    for _ in range(3):
        a("F1 = F4 * F9", "y = y * (1.5f - h * y * y)")
        a("F1 = F1 * F9")
        a("F1 = F0 - F1")
        a("F9 = F9 * F1")
    a.label("_dpk_rd")
    a(f"R0 = {HALF}")
    a("F9 = F0 * F9", "pre_gain = 0.5f * ..")
    # g = f * (pi + 11.583945274353027f * f * f); r = resonance_r; h = 1 / (1 + r g + g g)
    a(f"R0 = {A_SVF}")
    a("F0 = F0 * F2", "g = f * (M_PI_F + a * f * f)")
    a("F0 = F0 * F2")
    a(f"R1 = {PI}")
    a("F0 = F1 + F0")
    a("F12 = F2 * F0")
    a(f"R11 = DM({k['RES']}, I4)", "r = resonance_r")
    a("F0 = F11 * F12", "h = 1.0f / (1.0f + r * g + g * g)")
    a(f"R1 = {ONE}")
    a("F0 = F1 + F0")
    a("F2 = F12 * F12")
    a("F0 = F0 + F2")
    a(f"R10 = {TWO}")
    a.div("F10", "F1", "F0", "F2", "F5", "F10")
    a.slot("R0", P_SAMPLE, "the sample back")
    a("R1 = 0")
    a.put(P_CAN, "R1", "can_randomize_frequency = 0")
    a.label("_dpk_imp")
    a("R1 = DM(I3, M5)", "aux[n] += sample")
    a("F1 = F1 + F0")
    a("DM(I3, M6) = R1")
    a("F0 = F9 * F0", "in = pre_gain * sample")
    a("F1 = F11 * F15", "hp = (in - r s1 - g s1 - s2) * h")
    a("F1 = F0 - F1")
    a("F2 = F12 * F15")
    a("F1 = F1 - F2")
    a("F1 = F1 - F14")
    a("F1 = F1 * F10")
    a("F2 = F12 * F1", "bp = g hp + s1")
    a("F2 = F2 + F15")
    a("F15 = F12 * F1", "s1 = g hp + bp")
    a("F15 = F15 + F2")
    a("F0 = F12 * F2", "lp = g bp + s2")
    a("F0 = F0 + F14")
    a("F14 = F12 * F2", "s2 = g bp + lp")
    a("F14 = F14 + F0")
    a("R1 = DM(I0, M5)", "out[n] += bp")
    a("F1 = F1 + F2")
    a("DM(I0, M6) = R1")
    rng_float(a, "F3")
    a.slot("R0", P_SCNT)
    a("R1 = 1")
    a.iadd("R0 = R0 - R1")
    a.put(P_SCNT, "R0")
    a("IF NE JUMP _dpk_loop")
    a.label("_dpk_pend")
    a("DM(0, I2) = R9")
    a("DM(1, I2) = R12")
    a("DM(2, I2) = R11")
    a("DM(3, I2) = R10")
    a("DM(4, I2) = R15")
    a("DM(5, I2) = R14")
    a("I2=MODIFY (I2,6)(NW)", "the next particle")
    a.slot("R0", P_PCNT)
    a("R1 = 1")
    a.iadd("R0 = R0 - R1")
    a.put(P_PCNT, "R0")
    a("IF NE JUMP _dpk_part")
    a("DM(45, I1) = R13", "s->rng_ = rng")
    epilogue(a, P_FRAME)
    return "\n".join(a.lines) + "\n"


# ---- dust_tail_kernel -----------------------------------------------------------------------------------------------
T_AMT, T_RT, T_IN, T_LFO, T_CNT, T_N, T_LP, T_Y1, T_Y0, T_OI = range(7, 17)
T_FRAME = 16
FRESH_WORD = 4142


def read(a: Asm, dst: int, idx: str, checked: bool, thr: str | None) -> None:
    """F{dst} = DUST_READ(R{idx}) (idx = wp + offset, unmasked); in the checked loop, 0 when fresh_ < thr (thr an
    immediate or a register outside R0-R3). Uses R0-R3 (dst may be one of R4-R8)."""
    a(f"R0 = R{idx} AND R11", "DUST_READ: i = ix & 8191")
    a("R1 = -1")
    a("R2 = ASHIFT R0 BY R1", "i >> 1")
    a("R2 = LSHIFT R2 BY 2")
    a.iadd("R2 = R2 + R14")
    a("I4 = R2")
    a("R1 = 1")
    a("R0 = R0 AND R1", "i & 1")
    a("R1 = 0x80000000")
    a("R2 = DM(I4, M5)", "w")
    a.iadd(
        "R3 = R2 + R1",
        "(r ^ 0x8000) of either half as (half + 0x8000) mod 2^16: no XOR in stock code",
    )
    a.iadd("R2 = R2 + R10")
    a("R3 = FEXT R3 BY 16:16", "(w >> 16) ^ 0x8000")
    a("R2 = FEXT R2 BY 0:16", "(w & 0xFFFF) ^ 0x8000")
    a("R1 = 0")
    a("COMP(R0, R1)")
    a("IF NE R2 = R3 OR R3")
    a("R2 = R2 OR R9", "itof_nonneg")
    a("F2 = F2 - F9")
    a(f"R1 = {F32768}")
    a("F2 = F2 - F1", "- 32768.0f")
    a(f"R1 = {INV4096}")
    a(f"F{dst} = F2 * F1", "* 0.000244140625f")
    if checked:
        a.slot("R0", T_N, "fresh_ < o - B: the C's cleared memory")
        if thr is not None and thr.startswith("R"):
            a(f"COMP(R0, {thr})")
        else:
            a(f"R1 = {thr}")
            a("COMP(R0, R1)")
        a("R1 = 0")
        a(f"IF LT R{dst} = R1 OR R1")


def write(a: Asm, idx: str, val: str) -> None:
    """DUST_WRITE(R{idx}, F{val}); uses R0-R7 (idx, val outside them, or val consumed first)."""
    a(f"R4 = {F4096}")
    a(f"F4 = F{val} * F4", "DUST_WRITE: x = value * 4096.0f")
    a(f"R5 = {F32767}")
    a("COMP(F4, F5)", "x > 32767.0f (a NaN too, as selcc compares): 32767")
    a("IF GT R4 = R5 OR R5")
    a(f"R5 = {FM32768}")
    a("COMP(F4, F5)", "x < -32768.0f: -32768")
    a("IF LT R4 = R5 OR R5")
    a("R4 = TRUNC F4", "(int) toward zero, both signs")
    a("R5 = 0xFFFF")
    a("R4 = R4 AND R5", "r = n & 0xFFFF")
    a(f"R0 = R{idx} AND R11", "i = ix & 8191")
    a("R1 = -1")
    a("R2 = ASHIFT R0 BY R1")
    a("R2 = LSHIFT R2 BY 2")
    a.iadd("R2 = R2 + R14")
    a("I4 = R2")
    a("R1 = 1")
    a("R0 = R0 AND R1", "i & 1")
    a("R6 = LSHIFT R4 BY 16")
    a("R7 = 0xFFFF0000")
    a("R2 = DM(I4, M5)", "w")
    a("R3 = R2 AND R5", "odd: (w & 0xFFFF) | (r << 16)")
    a("R3 = R3 OR R6")
    a("R2 = R2 AND R7", "even: (w & 0xFFFF0000) | r")
    a("R2 = R2 OR R4")
    a("R1 = 0")
    a("COMP(R0, R1)")
    a("IF NE R2 = R3 OR R3")
    a("DM(I4, M5) = R2")


def at(a: Asm, reg: int, ofs: int) -> None:
    """R{reg} = wp + ofs."""
    a(f"R{reg} = {ofs}")
    a.iadd(f"R{reg} = R15 + R{reg}")


def read_tail(a: Asm, tail: int, scale: str, checked: bool, thr: int) -> None:
    at(a, 8, tail)
    read(a, 4, "8", checked, str(thr))
    a("R12 = PASS R4", "prev = r")
    a(f"R1 = {scale}")
    a("F4 = F1 * F4", "acc += r * scale")
    a("F13 = F13 + F4")


def allpass(a: Asm, base: int, scale: str) -> None:
    at(a, 8, base)
    write(a, "8", "13")
    a(f"R1 = {scale}")
    a("F13 = F13 * F1", "acc *= scale")
    a("F13 = F13 + F12", "acc += previous_read")


def interpolate(
    a: Asm, base: int, offset: str, amp: str, scale: str, checked: bool
) -> None:
    """DUST_INTERPOLATE: two taps at wp + oi + base (+ 1), the fraction between; acc += x * scale (scale "slot":
    rt from its slot). In the checked loop the taps read zero while fresh_ < oi (resp. oi + 1)."""
    a.slot("R1", T_LFO)
    a(f"R0 = {amp}")
    a("F1 = F0 * F1", "o = offset + amplitude * lfo")
    a(f"R0 = {offset}")
    a("F1 = F0 + F1")
    a("R2 = TRUNC F1", "oi = (int)o")
    a("R6 = PASS R2")
    a("R3 = R9 OR R2")
    a("F3 = F3 - F9")
    a("F5 = F1 - F3", "of = o - itof_nonneg(oi)")
    a(f"R8 = {base}")
    a.iadd("R8 = R2 + R8")
    a.iadd("R8 = R15 + R8", "wp + oi + base")
    read(a, 4, "8", checked, "R6")
    a("R7 = PASS R4", "a")
    a("R1 = 1")
    a.iadd("R8 = R8 + R1")
    a.iadd("R6 = R6 + R1", "oi + 1")
    read(a, 4, "8", checked, "R6")
    a("F6 = F4 - F7", "x = a + (b - a) * of")
    a("F6 = F6 * F5")
    a("F6 = F7 + F6")
    a("R12 = PASS R6", "prev = x")
    if scale == "slot":
        a.slot("R1", T_RT)
    else:
        a(f"R1 = {scale}")
    a("F6 = F6 * F1", "acc += x * scale")
    a("F13 = F13 + F6")


def tail_body(a: Asm, p: str, checked: bool) -> None:
    a.label(f"{p}_loop")
    # post_filter_ (low pass)
    a("R0 = DM(I0, M5)", "post filter: x = out[n]")
    a("R1 = DM(39, I1)", "state_1_")
    a("R2 = DM(40, I1)", "state_2_")
    a("R3 = DM(37, I1)", "r_")
    a("R4 = DM(36, I1)", "g_")
    a("R5 = DM(38, I1)", "h_")
    a("F6 = F3 * F1", "hp = (x - r s1 - g s1 - s2) * h")
    a("F6 = F0 - F6")
    a("F7 = F4 * F1")
    a("F6 = F6 - F7")
    a("F6 = F6 - F2")
    a("F6 = F6 * F5")
    a("F7 = F4 * F6", "bp = g hp + s1")
    a("F7 = F7 + F1")
    a("F1 = F4 * F6", "s1 = g hp + bp")
    a("F1 = F1 + F7")
    a("F0 = F4 * F7", "lp = g bp + s2")
    a("F0 = F0 + F2")
    a("F2 = F4 * F7", "s2 = g bp + lp")
    a("F2 = F2 + F0")
    a("DM(39, I1) = R1")
    a("DM(40, I1) = R2")
    a.put(T_IN, "R0", "in = out[n] (the low pass)")
    # the write pointer and the LFO
    a("R1 = 1")
    a.iadd("R15 = R15 - R1", "--wp")
    a("R1 = 0")
    a("COMP(R15, R1)")
    a(f"IF GE JUMP {p}_w")
    a("R1 = 8192")
    a.iadd("R15 = R15 + R1")
    a.label(f"{p}_w")
    a("R1 = 31")
    a("R1 = R15 AND R1", "(wp & 31) == 0")
    a(f"IF NE JUMP {p}_l1")
    a.slot("R1", T_Y0)
    a.slot("R2", T_Y1)
    a(f"R3 = {F2LFO}")
    a("F3 = F3 * F1", "y0 = 1.99999869f * y0 - y1")
    a("F3 = F3 - F2")
    a.put(T_Y0, "R3")
    a.put(T_Y1, "R1", "y1 = t")
    a(f"JUMP {p}_l2")
    a.label(f"{p}_l1")
    a.slot("R1", T_Y1)
    a.label(f"{p}_l2")
    a(f"R2 = {HALF}")
    a("F1 = F1 + F2", "lfo = (t or y1) + 0.5f")
    a.put(T_LFO, "R1")
    a("R12 = 0", "prev = 0.0f")
    a.slot("R13", T_IN, "acc = in")
    read_tail(a, 125, F0_625, checked, 125)
    allpass(a, 0, FM0_625)
    read_tail(a, 306, F0_625, checked, 179)
    allpass(a, 127, FM0_625)
    read_tail(a, 576, F0_625, checked, 268)
    allpass(a, 308, FM0_625)
    interpolate(a, 578, "0x43C80000", "0x422C0000", F0_625, checked)
    allpass(a, 578, FM0_625)
    interpolate(a, 4688, "0x453FE000", "0x43AA0000", "slot", checked)
    a.slot("R1", T_LP)
    a("F2 = F13 - F1", "lp += 0.75f * (acc - lp)")
    a(f"R3 = {F0_75}")
    a("F2 = F3 * F2")
    a("F1 = F1 + F2")
    a.put(T_LP, "R1")
    a("R13 = PASS R1", "acc = lp")
    read_tail(a, 2675, FM0_625, checked, 1652)
    allpass(a, 1023, F0_625)
    read_tail(a, 4686, F0_625, checked, 2009)
    allpass(a, 2677, FM0_625)
    at(a, 8, 4688)
    write(a, "8", "13")
    a(f"R1 = {TWO}")
    a("F13 = F13 * F1", "acc *= 2.0f: wet")
    a.slot("R0", T_IN)
    a("F1 = F13 - F0", "out[n] = in + amount * (wet - in)")
    a.slot("R2", T_AMT)
    a("F1 = F2 * F1")
    a("F1 = F0 + F1")
    a("DM(I0, M6) = R1")
    if checked:
        a.slot("R0", T_N)
        a("R1 = 1")
        a.iadd("R0 = R0 + R1", "fresh_ += 1")
        a.put(T_N, "R0")
    a.slot("R0", T_CNT)
    a("R1 = 1")
    a.iadd("R0 = R0 - R1")
    a.put(T_CNT, "R0")
    a(f"IF NE JUMP {p}_loop")
    a("JUMP _dtk_end")


def tail_kernel() -> str:
    a = Asm()
    prologue(a, "dust_tail_kernel.", T_FRAME)
    a("I1 = R4", "s")
    a("I4 = R8", "k")
    a("I0 = R12", "out")
    a("R0 = DM(0, I4)", "amount")
    a.put(T_AMT, "R0")
    a("R0 = DM(1, I4)", "rt")
    a.put(T_RT, "R0")
    a("R0 = DM(1, I6)", "size")
    a.put(T_CNT, "R0")
    a(f"R1 = DM({FRESH_WORD}, I1)", "fresh_")
    a.put(T_N, "R1")
    a("R1 = DM(41, I1)")
    a.put(T_LP, "R1", "lp_decay_")
    a("R1 = DM(42, I1)")
    a.put(T_Y1, "R1", "lfo_y1_")
    a("R1 = DM(43, I1)")
    a.put(T_Y0, "R1", "lfo_y0_")
    a("R15 = DM(44, I1)", "wp = write_ptr_")
    a("R14 = I1", "buffer_ (word 46)")
    a("R1 = 184")
    a.iadd("R14 = R14 + R1")
    a("R11 = 0x1FFF", "DUST_MASK")
    a("R10 = 0x8000")
    a(f"R9 = {BIAS}")
    a("R1 = 0")
    a("COMP(R0, R1)")
    a("IF LE JUMP _dtk_end")
    a.slot("R1", T_N)
    a(f"R2 = {FRESH_FULL}")
    a("COMP(R1, R2)", "every read past the C's cleared memory: the plain loop")
    a("IF LT JUMP _dtc_loop")
    tail_body(a, "_dtf", False)
    tail_body(a, "_dtc", True)
    a.label("_dtk_end")
    a.slot("R1", T_LP)
    a("DM(41, I1) = R1")
    a.slot("R1", T_Y1)
    a("DM(42, I1) = R1")
    a.slot("R1", T_Y0)
    a("DM(43, I1) = R1")
    a("DM(44, I1) = R15")
    a.slot("R1", T_N)
    a(f"DM({FRESH_WORD}, I1) = R1")
    epilogue(a, T_FRAME)
    return "\n".join(a.lines) + "\n"


def clear_kernel() -> str:
    """dust_clear_kernel(unsigned int *b, int words): b[0..words) = 0, one store per word in a DO loop (dust_init's
    clear: the emulator treats memory never written as unknown, so the delay memory is cleared after all; the
    fresh_ selects above stay, exact either way)."""
    a = Asm()
    a.label("dust_clear_kernel.")
    for r in ("I0", "M6", "L0"):
        a(f"R0 = {r}")
        a("DM(I7, M7) = R0")
    a("M6 = 1")
    a("L0 = 0")
    a("I0 = R4")
    a("R0 = 0")
    a("COMP(R8, R0)")
    a("IF LE JUMP _dck_done")
    a("LCNTR = R8, DO _dck_e UNTIL LCE")
    a.label("_dck_e")
    a("DM(I0, M6) = R0")
    a.label("_dck_done")
    for i, r in enumerate(reversed(("I0", "M6", "L0"))):
        a(f"{r} = DM({i + 1}, I7)")
    a("I12 = DM(M7, I6)")
    a("JUMP (M14, I12) (DB)")
    a("RFRAME")
    a("NOP")
    return "\n".join(a.lines) + "\n"


def main() -> None:
    OUT.write_text(HEADER + "\n" + particles_kernel() + "\n" + tail_kernel() + "\n" + clear_kernel())
    print(OUT)


if __name__ == "__main__":
    main()
