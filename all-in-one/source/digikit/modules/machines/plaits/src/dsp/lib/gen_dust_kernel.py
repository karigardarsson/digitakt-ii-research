HEADER = """\
// machines/plaits: DUST's sample loops (engines/dust.c), hand-written SISD kernels.
// Generated by lib/gen_dust_kernel.py; do not edit by hand.
//
// dust_particles_kernel(Dust *s, float *k, float *out, float *aux, int size): out and aux cleared, then the six
//   particles (each: its impulse train, a new random frequency at its first impulse, its band-pass filter) added in.
//   k[0..7] = density, gain, f0, spread, q, sqrt_density, resonance_r, sync (an int); k[8] = 2^23 (bits 0x4B000000),
//   k[9] = 65536.0f, k[10] = 4294967296.0f, k[11] = 2.0f; k[12] is written (selcc's reciprocal of 2^32).
// dust_tail_kernel(Dust *s, const float *k, float *out, int size): the post filter (low pass, its g_, r_, h_ set by
//   the C) and the diffuser, per sample; k[0] = amount, k[1] = rt.
// Bit-identical in output to selcc's code of the C (-DPL_DUST_C) (tests/plaits/test_dust_kernel.py); the delay
// memory is never cleared: reads of the C's cleared memory give zero (lib/gen_dust_kernel.py, fresh_).
//
// State on return: R0-R8, R12, I4 and the flags change; every other register is as on entry (R9-R11, R13-R15 saved
// above I7; I0, I1, I2, I3, I5, M6, L0-L5 pushed through R0, M6 = 1 and L0-L5 = 0 set here). No SIMD.
// ABI: as the other kernels (lib/wavetable_sm.s). Assembled under .COMPRESS; integer additions in their 48-bit form.

.SECTION/PM seg_pmco;
.GLOBAL dust_particles_kernel.;
.GLOBAL dust_tail_kernel.;
.GLOBAL dust_clear_kernel.;
.EXTERN pl_lut_pitch_ratio_high.;
.EXTERN pl_lut_pitch_ratio_low.;
.COMPRESS;
"""


class Asm:
    def __init__(self) -> None:
        self.lines: list[str] = []
        self.n = 0

    def __call__(self, text: str, comment: str = "") -> None:
        line = f"    {text};"
        if comment:
            line = f"{line:<56}// {comment}"
        self.lines.append(line)

    def label(self, name: str) -> None:
        self.lines.append(f"{name}:")

    def uniq(self, p: str) -> str:
        self.n += 1
        return f"{p}{self.n}"

    def iadd(self, text: str, comment: str = "") -> None:
        """An integer addition or subtraction in its 48-bit form (the compressed form is not in stock code)."""
        self.lines.append("    .NOCOMPRESS;")
        self(text, comment)
        self.lines.append("    .COMPRESS;")

    def div(
        self, res: str, n: str, d: str, y: str, t: str, w: str, comment: str = ""
    ) -> None:
        """res = n / d as selcc divides; w holds 2.0 on entry. res may be w."""
        self(f"{y} = RECIPS {d}")
        self(f"{t} = {d} * {y}", comment or "selcc division")
        self(f"{t} = {w} - {t}")
        self(f"{y} = {y} * {t}")
        self(f"{t} = {d} * {y}")
        self(f"{t} = {w} - {t}")
        self(f"{y} = {y} * {t}")
        self(f"{w} = {n} * {y}")
        self(f"{t} = {d} * {w}")
        self(f"{t} = {n} - {t}")
        self(f"{t} = {t} * {y}")
        self(f"{res} = {w} + {t}")

    def slot(self, reg: str, k: int, comment: str = "") -> None:
        self(f"{reg} = DM({k}, I7)", comment)

    def put(self, k: int, reg: str, comment: str = "") -> None:
        self(f"DM({k}, I7) = {reg}", comment)


DAGS = ["I0", "I1", "I2", "I3", "I5", "M6", "L0", "L1", "L2", "L3", "L4", "L5"]
SAVES = ["R9", "R10", "R11", "R13", "R14", "R15"]


def prologue(a: Asm, name: str, frame: int) -> None:
    a.label(name)
    for r in DAGS:
        a(f"R0 = {r}")
        a("DM(I7, M7) = R0")
    a("M6 = 1")
    for r in DAGS[6:]:
        a(f"{r} = 0")
    a(f"I7=MODIFY (I7,-{frame})(NW)")
    for i, r in enumerate(SAVES):
        a.put(i + 1, r)


def epilogue(a: Asm, frame: int) -> None:
    for i, r in enumerate(SAVES):
        a.slot(r, i + 1)
    a(f"I7=MODIFY (I7,{frame})(NW)")
    for i, r in enumerate(reversed(DAGS)):
        a(f"{r} = DM({i + 1}, I7)")
    a("I12 = DM(M7, I6)")
    a("JUMP (M14, I12) (DB)")
    a("RFRAME")
    a("NOP")


