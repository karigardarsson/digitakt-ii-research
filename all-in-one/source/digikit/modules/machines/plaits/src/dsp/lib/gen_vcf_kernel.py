"""Generate lib/vcf_sm.s: VCF-VA's filter loop (engines/vcf.c, vcf_render's block loop: the two SVF stages with tan_fast,
their set_f_q divisions, the SoftClips and the stage-2 crossfade) as a SISD kernel, bit-identical to selcc's code of
the C loop (-DPL_VCF_C). (The two oscillators run on PHASE-DIST's pd_osc_kernel, see engines/vcf.c.)

    python3 modules/machines/plaits/src/dsp/lib/gen_vcf_kernel.py

Every float operation is the C's, with the same operands in the same order (commutative swaps only); tan_fast,
SoftClip (selects with selcc's conditions: a NaN gives 1.0f, as its code does), SoftLimit, minf and selcc's division are
written out. tests/plaits/test_vcf_kernel.py checks it against the C on the concrete core.
"""

from __future__ import annotations

from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE / "vcf_sm.s"
C = {
    "one": "0x3F800000",
    "half": "0x3F000000",
    "q": "0x3E800000",
    "two": "0x40000000",
    "a": "0x4121BA8F",
    "b": "0x425F2649",
    "pi": "0x40490FDB",
    "0.025": "0x3CCCCCCD",
    "27": "0x41D80000",
    "9": "0x41100000",
    "3": "0x40400000",
    "-3": "0xC0400000",
    "-1": "0xBF800000",
}

HEADER = """\
// machines/plaits: VCF-VA's filter loop (engines/vcf.c, vcf_render), hand-written SISD kernel.
// Generated by lib/gen_vcf_kernel.py; do not edit by hand.
//
// vcf_filter_kernel(Vcf *s, const float *k, float *out, float *aux, int size): k[0..4] = the increments of
//   previous_cutoff_, previous_stage2_gain_, previous_q_, previous_gain_, previous_sub_gain_; out holds the main
//   oscillator, aux the sub oscillator; out and aux receive the filter's outputs; the filter state and the last
//   sample's g_, r_, h_ go back to s->svf_ (size >= 1; the C stores uninitialised locals for size 0, the engine always
//   renders 16). Bit-identical to selcc's code of the C loop (-DPL_VCF_C) (tests/plaits/test_vcf_kernel.py).
//
// State on return: R0-R8, R12, I4 and the flags change; every other register is as on entry (R9-R11, R13-R15 saved
// above I7; I0, I1, I2, M6, L0, L1, L2, L4 pushed through R0, M6 = 1 and L0 = L1 = L2 = L4 = 0 set here). No SIMD.
// ABI: as the other kernels (lib/wavetable_sm.s). Assembled under .COMPRESS; integer additions in their 48-bit form.

.SECTION/PM seg_pmco;
.GLOBAL vcf_filter_kernel.;
.COMPRESS;
"""
DAGS = ["I0", "I1", "I2", "M6", "L0", "L1", "L2", "L4"]
SAVES = ["R9", "R10", "R11", "R13", "R14", "R15"]
K = (7, 8, 9, 10, 11)
CNT, G, R0S, H0, R1S, H1, GI, ST2, HP = range(12, 21)
FRAME = 20


def kernel() -> str:
    L: list[str] = []

    def a(t: str, c: str = "") -> None:
        line = f"    {t};"
        L.append(f"{line:<56}// {c}" if c else line)

    def lab(n: str) -> None:
        L.append(f"{n}:")

    def k(r: str, n: str) -> None:
        a(f"{r} = {C[n]}", n)

    def slot(r: str, s: int, c: str = "") -> None:
        a(f"{r} = DM({s}, I7)", c)

    def put(s: int, r: str, c: str = "") -> None:
        a(f"DM({s}, I7) = {r}", c)

    def div(res: str, n: str, d: str, y: str, t: str, w: str, c: str = "") -> None:
        a(f"{y} = RECIPS {d}")
        a(f"{t} = {d} * {y}", c or "selcc division")
        a(f"{t} = {w} - {t}")
        a(f"{y} = {y} * {t}")
        a(f"{t} = {d} * {y}")
        a(f"{t} = {w} - {t}")
        a(f"{y} = {y} * {t}")
        a(f"{w} = {n} * {y}")
        a(f"{t} = {d} * {w}")
        a(f"{t} = {n} - {t}")
        a(f"{t} = {t} * {y}")
        a(f"{res} = {w} + {t}")

    def softclip(x: int) -> None:
        """F{x} = SoftClip(F{x}); uses R0-R6."""
        a(
            f"F1 = F{x} * F{x}",
            "SoftLimit: x * (27.0f + x * x) / (27.0f + 9.0f * x * x)",
        )
        k("R2", "27")
        a("F1 = F2 + F1")
        a(f"F1 = F{x} * F1")
        k("R3", "9")
        a(f"F3 = F3 * F{x}")
        a(f"F3 = F3 * F{x}")
        a("F3 = F2 + F3")
        k("R6", "two")
        div("F6", "F1", "F3", "F4", "F5", "F6")
        k("R2", "3")
        a(f"COMP(F{x}, F2)", "x > 3.0f (a NaN too, as selcc compares): 1.0f")
        k("R2", "one")
        a("IF GT R6 = R2 OR R2")
        k("R2", "-3")
        a(f"COMP(F{x}, F2)", "x < -3.0f: -1.0f")
        k("R2", "-1")
        a("IF LT R6 = R2 OR R2")
        a(f"R{x} = PASS R6")

    def stage(x: str, s1: int, s2: int, g: str, r: str, h: str) -> None:
        """hp (F7) = (x - r s1 - g s1 - s2) h; bp (F8) = g hp + s1; s1 = g hp + bp; lp (F0) = g bp + s2; s2 = g bp + lp.
        g, r, h in R4, R5, R6 (loaded by the caller); uses R0-R8."""
        a(f"F7 = {r} * F{s1}", "hp = (in - r s1 - g s1 - s2) * h")
        a(f"F7 = {x} - F7")
        a(f"F8 = {g} * F{s1}")
        a("F7 = F7 - F8")
        a(f"F7 = F7 - F{s2}")
        a(f"F7 = F7 * {h}")
        a(f"F8 = {g} * F7", "bp = g hp + s1")
        a(f"F8 = F8 + F{s1}")
        a(f"F{s1} = {g} * F7", "s1 = g hp + bp")
        a(f"F{s1} = F{s1} + F8")
        a(f"F0 = {g} * F8", "lp = g bp + s2")
        a(f"F0 = F0 + F{s2}")
        a(f"F{s2} = {g} * F8", "s2 = g bp + lp")
        a(f"F{s2} = F{s2} + F0")

    lab("vcf_filter_kernel.")
    for r in DAGS:
        a(f"R0 = {r}")
        a("DM(I7, M7) = R0")
    a("M6 = 1")
    for r in DAGS[4:]:
        a(f"{r} = 0")
    a(f"I7=MODIFY (I7,-{FRAME})(NW)")
    for i, r in enumerate(SAVES):
        put(i + 1, r)
    a("I2 = R4", "s")
    a("I4 = R8", "k")
    a("I0 = R12", "out")
    a("R0 = DM(1, I6)", "aux")
    a("I1 = R0")
    for j, sl in enumerate(K):
        a(f"R0 = DM({j}, I4)")
        put(sl, "R0")
    a("R0 = DM(2, I6)", "size")
    put(CNT, "R0")
    a("R15 = DM(6, I2)", "a1 = state_1_[0]")
    a("R14 = DM(8, I2)", "a2 = state_2_[0]")
    a("R13 = DM(7, I2)", "b1 = state_1_[1]")
    a("R12 = DM(9, I2)", "b2 = state_2_[1]")
    a("R1 = 0")
    a("COMP(R0, R1)")
    a("IF LE JUMP _vfk_end")
    lab("_vfk_loop")
    a("R0 = DM(24, I2)")
    slot("R1", K[0])
    a("F0 = F0 + F1", "c = minf(cutoff_modulation.Next(), 0.25f)")
    a("DM(24, I2) = R0")
    k("R1", "q")
    a("COMP(F0, F1)")
    a("IF GE R0 = R1 OR R1")
    a("R9 = DM(26, I2)")
    slot("R1", K[2])
    a("F9 = F9 + F1", "qi = q_modulation.Next()")
    a("DM(26, I2) = R9")
    a("R1 = DM(25, I2)")
    slot("R2", K[1])
    a("F1 = F1 + F2", "st2 = stage2_gain_modulation.Next()")
    a("DM(25, I2) = R1")
    put(ST2, "R1")
    a("F1 = F0 * F0", "g = tan_fast(c): f * (pi + f2 * (a + b * f2))")
    k("R2", "b")
    a("F2 = F2 * F1")
    k("R3", "a")
    a("F2 = F3 + F2")
    a("F2 = F1 * F2")
    k("R3", "pi")
    a("F2 = F3 + F2")
    a("F10 = F0 * F2")
    put(G, "R10")
    k("R1", "half")
    a("F1 = F1 + F9", "r0 = 1.0f / (0.5f + qi)")
    k("R2", "one")
    k("R6", "two")
    div("F6", "F2", "F1", "F4", "F5", "F6")
    put(R0S, "R6")
    a("F1 = F6 * F10", "h0 = 1.0f / (1.0f + r0 * g0 + g0 * g0)")
    a("F1 = F2 + F1")
    a("F3 = F10 * F10")
    a("F1 = F1 + F3")
    k("R6", "two")
    div("F6", "F2", "F1", "F4", "F5", "F6")
    put(H0, "R6")
    k("R1", "0.025")
    a("F1 = F1 * F9", "r1 = 1.0f / (0.5f + 0.025f * qi)")
    k("R3", "half")
    a("F1 = F3 + F1")
    k("R6", "two")
    div("F6", "F2", "F1", "F4", "F5", "F6")
    put(R1S, "R6")
    a("F1 = F6 * F10", "h1 = 1.0f / (1.0f + r1 * g1 + g1 * g1)")
    a("F1 = F2 + F1")
    a("F3 = F10 * F10")
    a("F1 = F1 + F3")
    k("R6", "two")
    div("F6", "F2", "F1", "F4", "F5", "F6")
    put(H1, "R6")
    a("R11 = DM(27, I2)")
    slot("R1", K[3])
    a("F11 = F11 + F1", "gi = gain_modulation.Next()")
    a("DM(27, I2) = R11")
    put(GI, "R11")
    a("R1 = DM(28, I2)")
    slot("R2", K[4])
    a("F1 = F1 + F2", "sub_gain_modulation.Next()")
    a("DM(28, I2) = R1")
    a("R0 = DM(I1, M5)", "input = SoftClip((out[i] + aux[i] * sub_gain) * gi)")
    a("F0 = F0 * F1")
    a("R1 = DM(I0, M5)")
    a("F9 = F1 + F0")
    a("F9 = F9 * F11")
    softclip(9)
    slot("R4", G)
    slot("R5", R0S)
    slot("R6", H0)
    stage("F9", 15, 14, "F4", "F5", "F6")
    put(HP, "R7")
    slot("R11", GI)
    a("F9 = F0 * F11", "lp = SoftClip(lp * gi)")
    softclip(9)
    slot("R4", G)
    slot("R5", R1S)
    slot("R6", H1)
    stage("F9", 13, 12, "F4", "F5", "F6")
    softclip(0)
    a("F0 = F0 - F9", "lp += st2 * (SoftClip(lp2) - lp)")
    slot("R1", ST2)
    a("F0 = F1 * F0")
    a("F9 = F9 + F0")
    a("DM(I0, M6) = R9", "out[i] = lp")
    slot("R9", HP)
    slot("R11", GI)
    a("F9 = F9 * F11", "aux[i] = SoftClip(hp * gi)")
    softclip(9)
    a("DM(I1, M6) = R9")
    slot("R0", CNT)
    a("R1 = 1")
    L.append("    .NOCOMPRESS;")
    a("R0 = R0 - R1")
    L.append("    .COMPRESS;")
    put(CNT, "R0")
    a("IF NE JUMP _vfk_loop")
    slot("R0", G)
    a("DM(0, I2) = R0", "g_[0], g_[1]")
    a("DM(1, I2) = R0")
    slot("R0", R0S)
    a("DM(2, I2) = R0", "r_[0]")
    slot("R0", R1S)
    a("DM(3, I2) = R0", "r_[1]")
    slot("R0", H0)
    a("DM(4, I2) = R0", "h_[0]")
    slot("R0", H1)
    a("DM(5, I2) = R0", "h_[1]")
    a("DM(6, I2) = R15")
    a("DM(8, I2) = R14")
    a("DM(7, I2) = R13")
    a("DM(9, I2) = R12")
    lab("_vfk_end")
    for i, r in enumerate(SAVES):
        slot(r, i + 1)
    a(f"I7=MODIFY (I7,{FRAME})(NW)")
    for i, r in enumerate(reversed(DAGS)):
        a(f"{r} = DM({i + 1}, I7)")
    a("I12 = DM(M7, I6)")
    a("JUMP (M14, I12) (DB)")
    a("RFRAME")
    a("NOP")
    return "\n".join(L) + "\n"


def main() -> None:
    OUT.write_text(HEADER + "\n" + kernel())
    print(OUT)


if __name__ == "__main__":
    main()
