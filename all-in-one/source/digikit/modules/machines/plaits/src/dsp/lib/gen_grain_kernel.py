def hp_kernel() -> str:
    a = Asm()
    a.label("grain_hp_kernel.")
    dags = ["I0", "I1", "M6", "L0", "L1", "L4"]
    for r in dags:
        a(f"R0 = {r}")
        a("DM(I7, M7) = R0")
    a("M6 = 1")
    for r in ("L0", "L1", "L4"):
        a(f"{r} = 0")
    a("I4 = R4", "f")
    a("I0 = R8", "x")
    a("I1 = R12", "y")
    a("R5 = DM(0, I4)", "g_")
    a("R6 = DM(1, I4)", "gi_")
    a("R7 = DM(2, I4)", "state_")
    a("R8 = DM(1, I6)", "size")
    a("R0 = 0")
    a("COMP(R8, R0)")
    a("IF LE JUMP _ghp_done")
    a("COMP(R12, R0)")
    a("IF EQ JUMP _ghp_plain")
    a("LCNTR = R8, DO _ghp_e0 UNTIL LCE")
    a("R0 = DM(I0, M5)", "in = x[i] + y[i]")
    a("R1 = DM(I1, M6)")
    a("F0 = F0 + F1")
    a("F1 = F5 * F0", "lp = (g_ * in + state_) * gi_")
    a("F1 = F1 + F7")
    a("F1 = F1 * F6")
    a("F2 = F0 - F1", "state_ = g_ * (in - lp) + lp")
    a("F3 = F5 * F2")
    a("F7 = F3 + F1")
    a.label("_ghp_e0")
    a("DM(I0, M6) = R2", "in - lp")
    a("JUMP _ghp_done")
    a.label("_ghp_plain")
    a("LCNTR = R8, DO _ghp_e1 UNTIL LCE")
    a("R0 = DM(I0, M5)", "in = x[i]")
    a("F1 = F5 * F0", "lp = (g_ * in + state_) * gi_")
    a("F1 = F1 + F7")
    a("F1 = F1 * F6")
    a("F2 = F0 - F1", "state_ = g_ * (in - lp) + lp")
    a("F3 = F5 * F2")
    a("F7 = F3 + F1")
    a.label("_ghp_e1")
    a("DM(I0, M6) = R2", "in - lp")
    a.label("_ghp_done")
    a("DM(2, I4) = R7")
    for i, r in enumerate(reversed(dags)):
        a(f"{r} = DM({i + 1}, I7)")
    a("I12 = DM(M7, I6)")
    a("JUMP (M14, I12) (DB)")
    a("RFRAME")
    a("NOP")
    return "\n".join(a.lines) + "\n"


