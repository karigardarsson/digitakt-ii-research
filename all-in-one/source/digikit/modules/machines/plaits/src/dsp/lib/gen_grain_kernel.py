"""Generate lib/grain_sm.s: FORMANT's sample loops (engines/grain.c: grainlet_render, z_render and the two DC
blockers) as SISD kernels, bit-identical to selcc's code of the C (-DPL_GRAIN_C).

    python3 modules/machines/plaits/src/dsp/lib/gen_grain_kernel.py

Every float operation is the C's, with the same operands in the same order (commutative swaps only); Sine
(InterpolateWrap over 512 points with itof_nonneg written out), the blep helpers, grainlet_carrier, grainlet, z_value,
one_pole_high_pass and selcc's division (RECIPS, two Newton steps on the divisor, one correction) are written out;
comparisons are selcc's (COMP of the C's left and right operand, the condition or its complement).
tests/plaits/test_grain_kernel.py checks them against the C on the concrete core.
"""

from __future__ import annotations

from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE / "grain_sm.s"

ONE, HALF, MHALF, TWO, QUARTER = (
    "0x3F800000",
    "0x3F000000",
    "0xBF000000",
    "0x40000000",
    "0x3E800000",
)
THREE, FIFTEEN, F14_5, F0_75 = "0x40400000", "0x41700000", "0x41680000", "0x3F400000"
F0_001, F0_499, F1_5 = "0x3A83126F", "0x3EFF7CEE", "0x3FC00000"
F0_333, F0_666, F0_7495, F0_33 = "0x3EAA7EFA", "0x3F2A7EFA", "0x3F3FDF3B", "0x3EA8F5C3"
F512 = "0x44000000"
BIAS = "0x4B000000"  # itof_nonneg's 2^23 (as a float: 8388608.0f)

HEADER = """\
// machines/plaits: FORMANT's sample loops (engines/grain.c), hand-written SISD kernels.
// Generated by lib/gen_grain_kernel.py; do not edit by hand.
//
// grainlet_kernel(Grainlet *s, const float *k, float *out, int size): grainlet_render's sample loop. s = the grainlet
//   (carrier_phase_, formant_phase_, next_sample_, then the four interpolators' values carrier_frequency_,
//   formant_frequency_, carrier_shape_, carrier_bleed_); k[0..3] = the interpolators' increments. Writes `size`
//   samples to out and the state back (the values are the interpolators' commits).
// z_kernel(ZOsc *s, const float *k, float *out, int size): z_render's sample loop, the same contract (carrier_phase_,
//   discontinuity_phase_, formant_phase_, next_sample_, then carrier_frequency_, formant_frequency_, carrier_shape_,
//   mode_; k[0..3] their increments).
// grain_hp_kernel(OnePole *f, float *x, const float *y, int size): x[i] = one_pole_high_pass(f, x[i] + y[i]) (y
//   non-null) or one_pole_high_pass(f, x[i]) (y null).
// All bit-identical to selcc's code of the C (-DPL_GRAIN_C): the same operations with the same operands in the same
// order (tests/plaits/test_grain_kernel.py).
//
// State on return: R0-R8, R12, I4 and the flags change; every other register is as on entry (R9-R11, R13-R15 saved
// above I7; I0, I1, M6, L0, L1, L4 pushed through R0, M6 = 1 and L0 = L1 = L4 = 0 set here). No SIMD.
// Registers in the oscillator loops: R15 = itof_nonneg's bias 0x4B000000 (as a float 2^23), R14 = pl_lut_sine, R9 = 1.0f,
// I1 = s, I0 = out; the phases and samples in R10-R13; per-sample values in frame slots above I7.
//
// ABI: as the other kernels (lib/wavetable_sm.s): relies on M5 = 0 and M7 = -1, sets M6 = 1 itself; DAG registers
// are pushed through R0 and restored by loads through I7. Assembled under .COMPRESS (the assembler leaves the
// instructions of a DO loop in their 48-bit forms, as the PRM requires for a loop's last 11): smaller hot code.

.SECTION/PM seg_pmco;
.GLOBAL grainlet_kernel.;
.GLOBAL z_kernel.;
.GLOBAL grain_hp_kernel.;
.EXTERN pl_lut_sine.;
.COMPRESS;
"""


class Asm:
    def __init__(self) -> None:
        self.lines: list[str] = []

    def __call__(self, text: str, comment: str = "") -> None:
        line = f"    {text};"
        if comment:
            line = f"{line:<56}// {comment}"
        self.lines.append(line)

    def label(self, name: str) -> None:
        self.lines.append(f"{name}:")

    def div(
        self, res: str, n: str, d: str, y: str, t: str, w: str, comment: str = ""
    ) -> None:
        """res = n / d as selcc divides; w holds 2.0 on entry. res may be w."""
        self(f"{y} = RECIPS {d}")
        self(f"{t} = {d} * {y}", comment or "selcc division")
        self(f"{t} = {w} - {t}")
        self(f"{y} = {y} * {t}")
        self(f"{t} = {d} * {y}")
        self(f"{t} = {w} - {t}")
        self(f"{y} = {y} * {t}")
        self(f"{w} = {n} * {y}")
        self(f"{t} = {d} * {w}")
        self(f"{t} = {n} - {t}")
        self(f"{t} = {t} * {y}")
        self(f"{res} = {w} + {t}")

    def slot(self, reg: str, k: int, comment: str = "") -> None:
        self(f"{reg} = DM({k}, I7)", comment)

    def put(self, k: int, reg: str, comment: str = "") -> None:
        self(f"DM({k}, I7) = {reg}", comment)

    def sine(self, dst: int, x: int, t1: int, t2: int, t3: int) -> None:
        """F{dst} = Sine(F{x}) = InterpolateWrap(lut_sine, x, 512) for x >= 0; uses R{t1..t3} (x is kept unless it is
        one of them; dst may be x or t1). R15 = the bias, R14 = lut_sine."""
        self(f"R{t1} = TRUNC F{x}", "Sine: index -= itof_nonneg((int)index)")
        self(f"R{t1} = R15 OR R{t1}")
        self(f"F{t1} = F{t1} - F15")
        self(f"F{t1} = F{x} - F{t1}")
        self(f"R{t2} = {F512}")
        self(f"F{t1} = F{t1} * F{t2}", "index *= 512.0f")
        self(f"R{t2} = TRUNC F{t1}", "index_integral")
        self(f"R{t3} = R15 OR R{t2}")
        self(f"R{t2} = LSHIFT R{t2} BY 2")
        self.lines.append("    .NOCOMPRESS;")
        self(
            f"R{t2} = R{t2} + R14",
            "(48-bit: the compressed integer add is not in stock code)",
        )
        self.lines.append("    .COMPRESS;")
        self(f"I4 = R{t2}")
        self(f"F{t3} = F{t3} - F15")
        self(f"F{t3} = F{t1} - F{t3}", "index_fractional")
        self(f"R{t1} = DM(I4, M5)", "a")
        self(f"R{t2} = DM(1, I4)", "b")
        self(f"F{t2} = F{t2} - F{t1}", "a + (b - a) * index_fractional")
        self(f"F{t2} = F{t2} * F{t3}")
        self(f"F{dst} = F{t1} + F{t2}")


# ---- grainlet_kernel ------------------------------------------------------------------------------------------------
# Frame slots above I7 (after the register saves at 1..6).
G_KCF, G_KFF, G_KSH, G_KBL, G_CNT, G_F0, G_F1, G_RT, G_BEFORE, G_CP, G_SH, G_BL = range(
    7, 19
)
G_FRAME = 18


def carrier(a: Asm, p: str, cp: int, sh: int) -> None:
    """F0 = grainlet_carrier(F{cp}, F{sh}); uses R0-R8 (cp and sh may be among them; both are lost)."""
    a(f"R2 = {THREE}")
    a(f"F2 = F{sh} * F2", "shape *= 3.0f")
    a("R3 = TRUNC F2", "shape_integral")
    a("R4 = R15 OR R3")
    a("F4 = F4 - F15")
    a("F4 = F2 - F4", "shape_fractional")
    a("F4 = F9 - F4", "t = 1.0f - shape_fractional")
    a("R5 = 0")
    a("COMP(R3, R5)")
    a(f"IF NE JUMP {p}_c1")
    # shape_integral == 0: phase = phase * (1.0f + t * t * t * 15.0f), clipped at 1.0f, + 0.75f
    a("F5 = F4 * F4")
    a("F5 = F5 * F4")
    a(f"R6 = {FIFTEEN}")
    a("F5 = F5 * F6")
    a("F5 = F9 + F5")
    a(f"F0 = F{cp} * F5")
    a("COMP(F0, F9)", "phase >= 1.0f: phase = 1.0f")
    a("IF GE R0 = R9 OR R9")
    a(f"R1 = {F0_75}")
    a("F0 = F0 + F1", "phase += 0.75f")
    a(f"JUMP {p}_cs")
    a.label(f"{p}_c1")
    a("R5 = 1")
    a("COMP(R3, R5)")
    a(f"IF NE JUMP {p}_c2")
    # shape_integral == 1: the breakpoint
    a(f"R5 = {F0_499}")
    a("F5 = F5 * F4", "0.001f + 0.499f * t * t * t")
    a("F5 = F5 * F4")
    a("F5 = F5 * F4")
    a(f"R6 = {F0_001}")
    a("F5 = F6 + F5", "breakpoint")
    a(f"COMP(F{cp}, F5)", "phase < breakpoint")
    a(f"IF GE JUMP {p}_c1b")
    a(f"R6 = {HALF}")
    a(f"R7 = {TWO}")
    a.div("F7", "F6", "F5", "F1", "F2", "F7", "0.5f / breakpoint")
    a(f"F0 = F{cp} * F7", "phase *= ..")
    a(f"JUMP {p}_c1e")
    a.label(f"{p}_c1b")
    a(f"F6 = F{cp} - F5", "0.5f + (phase - breakpoint) * 0.5f / (1.0f - breakpoint)")
    a(f"R1 = {HALF}")
    a("F6 = F6 * F1")
    a("F8 = F9 - F5")
    a(f"R7 = {TWO}")
    a.div("F7", "F6", "F8", "F2", "F3", "F7")
    a("F0 = F1 + F7")
    a.label(f"{p}_c1e")
    a(f"R1 = {F0_75}")
    a("F0 = F0 + F1", "phase += 0.75f")
    a(f"JUMP {p}_cs")
    a.label(f"{p}_c2")
    # otherwise: t = 1.0f - t; phase = 0.25f + phase * (0.5f + t * t * t * 14.5f), clipped at 0.75f
    a("F4 = F9 - F4")
    a("F5 = F4 * F4")
    a("F5 = F5 * F4")
    a(f"R6 = {F14_5}")
    a("F5 = F5 * F6")
    a(f"R6 = {HALF}")
    a("F5 = F6 + F5")
    a(f"F5 = F{cp} * F5")
    a(f"R6 = {QUARTER}")
    a("F0 = F6 + F5")
    a(f"R1 = {F0_75}")
    a("COMP(F0, F1)", "phase >= 0.75f: phase = 0.75f")
    a("IF GE R0 = R1 OR R1")
    a.label(f"{p}_cs")
    a.sine(0, 0, 1, 2, 3)
    a("F0 = F0 + F9", "(Sine(phase) + 1.0f) * 0.25f")
    a(f"R1 = {QUARTER}")
    a("F0 = F0 * F1")


def grainlet(a: Asm, p: str, cp: int, fp: int, sh: int, bl: int) -> None:
    """F0 = grainlet(F{cp}, F{fp}, F{sh}, F{bl}). cp, fp, sh, bl are frame slots (ints >= 100 mean slot - 100) or
    registers outside R0-R8 that survive; uses R0-R8."""

    def get(reg: int, src: int) -> None:
        if src >= 100:
            a.slot(f"R{reg}", src - 100)
        elif src != reg:
            a(f"R{reg} = PASS R{src}")

    get(0, cp)
    get(1, sh)
    carrier(a, p, 0, 1)
    a.put(G_CP, "R0", "carrier")
    get(4, fp)
    a.sine(4, 4, 1, 2, 3)
    get(5, bl)
    a("F4 = F4 + F5", "carrier * (formant + bleed) / (1.0f + bleed)")
    a.slot("R0", G_CP)
    a("F4 = F0 * F4")
    a("F5 = F9 + F5")
    a(f"R0 = {TWO}")
    a.div("F0", "F4", "F5", "F1", "F2", "F0")


def grainlet_kernel() -> str:
    a = Asm()
    a.label("grainlet_kernel.")
    dags = ["I0", "I1", "M6", "L0", "L1", "L4"]
    for r in dags:
        a(f"R0 = {r}")
        a("DM(I7, M7) = R0")
    a("M6 = 1")
    for r in ("L0", "L1", "L4"):
        a(f"{r} = 0")
    a(f"I7=MODIFY (I7,-{G_FRAME})(NW)")
    saves = ["R9", "R10", "R11", "R13", "R14", "R15"]
    for i, r in enumerate(saves):
        a.put(i + 1, r)
    a("I1 = R4", "s")
    a("I4 = R8", "k")
    a("I0 = R12", "out")
    for j, sl in enumerate((G_KCF, G_KFF, G_KSH, G_KBL)):
        a(f"R0 = DM({j}, I4)")
        a.put(sl, "R0")
    a("R0 = DM(1, I6)", "size")
    a.put(G_CNT, "R0")
    a(f"R15 = {BIAS}")
    a("R14 = pl_lut_sine.")
    a(f"R9 = {ONE}")
    a("R11 = DM(0, I1)", "carrier_phase_")
    a("R10 = DM(1, I1)", "formant_phase_")
    a("R13 = DM(2, I1)", "next_sample_")
    a("R1 = 0")
    a("COMP(R0, R1)")
    a("IF LE JUMP _grk_done")

    a.label("_grk_loop")
    a("R12 = PASS R13", "this_sample = next_sample")
    a("R13 = 0", "next_sample = 0.0f")
    a("R0 = DM(3, I1)")
    a.slot("R1", G_KCF)
    a("F0 = F0 + F1", "f0 = carrier_frequency_modulation.Next()")
    a("DM(3, I1) = R0")
    a.put(G_F0, "R0")
    a("R2 = DM(4, I1)")
    a.slot("R1", G_KFF)
    a("F2 = F2 + F1", "f1")
    a("DM(4, I1) = R2")
    a.put(G_F1, "R2")
    a("F11 = F11 + F0", "carrier_phase_ += f0")
    a("COMP(F11, F9)", "reset = carrier_phase_ >= 1.0f")
    a("IF LT JUMP _grk_nr")
    a("F11 = F11 - F9", "carrier_phase_ -= 1.0f")
    a(f"R4 = {TWO}")
    a.div("F4", "F11", "F0", "F1", "F3", "F4", "reset_time = carrier_phase_ / f0")
    a.put(G_RT, "R4")
    # before = grainlet(1.0f, formant_phase_ + (1 - reset_time) f1, subsample(shape, 1 - rt), subsample(bleed, 1 - rt))
    a("F5 = F9 - F4", "1.0f - reset_time")
    a.slot("R2", G_F1)
    a("F6 = F5 * F2")
    a("F6 = F10 + F6", "formant_phase_ + (1.0f - reset_time) * f1")
    a.put(G_BEFORE, "R6")
    a("R1 = DM(5, I1)")
    a.slot("R2", G_KSH)
    a("F2 = F2 * F5", "subsample(&carrier_shape_modulation, 1.0f - reset_time)")
    a("F1 = F1 + F2")
    a.put(G_SH, "R1")
    a("R1 = DM(6, I1)")
    a.slot("R2", G_KBL)
    a("F2 = F2 * F5", "subsample(&carrier_bleed_modulation, 1.0f - reset_time)")
    a("F1 = F1 + F2")
    a.put(G_BL, "R1")
    a("R0 = PASS R9", "carrier phase 1.0f")
    a.put(G_CP, "R0")
    grainlet(a, "_grb", 100 + G_CP, 100 + G_BEFORE, 100 + G_SH, 100 + G_BL)
    a.put(G_BEFORE, "R0", "before")
    # after = grainlet(0.0f, 0.0f, subsample(shape, 1.0f), subsample(bleed, 1.0f))
    a("R1 = DM(5, I1)")
    a.slot("R2", G_KSH)
    a("F2 = F2 * F9")
    a("F1 = F1 + F2")
    a.put(G_SH, "R1")
    a("R1 = DM(6, I1)")
    a.slot("R2", G_KBL)
    a("F2 = F2 * F9")
    a("F1 = F1 + F2")
    a.put(G_BL, "R1")
    a("R0 = 0")
    a.put(G_CP, "R0")
    a.put(G_F0, "R0", "(f0 is not needed again: the formant phase 0.0f)")
    grainlet(a, "_gra", 100 + G_CP, 100 + G_F0, 100 + G_SH, 100 + G_BL)
    a.slot("R1", G_BEFORE)
    a("F0 = F0 - F1", "discontinuity = after - before")
    a.slot("R2", G_RT)
    a(f"R3 = {HALF}")
    a("F3 = F3 * F2", "ThisBlepSample(reset_time)")
    a("F3 = F3 * F2")
    a("F3 = F0 * F3")
    a("F12 = F12 + F3", "this_sample += discontinuity * ..")
    a("F4 = F9 - F2", "NextBlepSample(reset_time)")
    a(f"R3 = {MHALF}")
    a("F3 = F3 * F4")
    a("F3 = F3 * F4")
    a("F3 = F0 * F3")
    a("F13 = F13 + F3", "next_sample += discontinuity * ..")
    a.slot("R1", G_F1)
    a("F10 = F2 * F1", "formant_phase_ = reset_time * f1")
    a("JUMP _grk_ns")
    a.label("_grk_nr")
    a("F10 = F10 + F2", "formant_phase_ += f1")
    a("COMP(F10, F9)", "formant_phase_ >= 1.0f")
    a("IF LT JUMP _grk_ns")
    a("F10 = F10 - F9")
    a.label("_grk_ns")
    # next_sample += grainlet(carrier_phase_, formant_phase_, next(&shape), next(&bleed))
    a("R1 = DM(5, I1)")
    a.slot("R2", G_KSH)
    a("F1 = F1 + F2", "carrier_shape_modulation.Next()")
    a("DM(5, I1) = R1")
    a("R5 = DM(6, I1)")
    a.slot("R2", G_KBL)
    a("F5 = F5 + F2", "carrier_bleed_modulation.Next()")
    a("DM(6, I1) = R5")
    a.put(G_BL, "R5")
    a("R0 = PASS R11")
    carrier(a, "_grn", 0, 1)
    a.put(G_CP, "R0", "carrier")
    a("R4 = PASS R10")
    a.sine(4, 4, 1, 2, 3)
    a.slot("R5", G_BL)
    a("F4 = F4 + F5", "carrier * (formant + bleed) / (1.0f + bleed)")
    a.slot("R0", G_CP)
    a("F4 = F0 * F4")
    a("F5 = F9 + F5")
    a(f"R0 = {TWO}")
    a.div("F0", "F4", "F5", "F1", "F2", "F0")
    a("F13 = F13 + F0", "next_sample += ..")
    a("DM(I0, M6) = R12", "*out++ = this_sample")
    a.slot("R0", G_CNT)
    a("R1 = 1")
    a("R0 = R0 - R1")
    a.put(G_CNT, "R0")
    a("IF NE JUMP _grk_loop")
    a.label("_grk_done")
    a("DM(0, I1) = R11")
    a("DM(1, I1) = R10")
    a("DM(2, I1) = R13")
    for i, r in enumerate(saves):
        a.slot(r, i + 1)
    a(f"I7=MODIFY (I7,{G_FRAME})(NW)")
    for i, r in enumerate(reversed(dags)):
        a(f"{r} = DM({i + 1}, I7)")
    a("I12 = DM(M7, I6)")
    a("JUMP (M14, I12) (DB)")
    a("RFRAME")
    a("NOP")
    return "\n".join(a.lines) + "\n"


# ---- z_kernel -------------------------------------------------------------------------------------------------------
Z_KCF, Z_KFF, Z_KSH, Z_KMO, Z_CNT, Z_F0, Z_F1, Z_RT, Z_BEFORE = range(7, 16)
Z_C, Z_D, Z_F, Z_SH, Z_MO, Z_RAMP, Z_OFF, Z_DISC = range(16, 24)
Z_FRAME = 23


def z_value(a: Asm, p: str) -> None:
    """F0 = z_value(c, d, f, shape, mode) from the slots Z_C, Z_D, Z_F, Z_SH, Z_MO; uses R0-R8."""
    a.slot("R0", Z_D)
    a(f"R1 = {HALF}")
    a("F0 = F1 * F0", "ramp_down = 0.5f * (1.0f + Sine(0.5f * d + 0.25f))")
    a(f"R1 = {QUARTER}")
    a("F0 = F0 + F1")
    a.sine(0, 0, 1, 2, 3)
    a("F0 = F9 + F0")
    a(f"R1 = {HALF}")
    a("F0 = F1 * F0")
    a.put(Z_RAMP, "R0")
    a.slot("R1", Z_MO)
    a(f"R3 = {F0_333}")
    a("COMP(F1, F3)", "mode < 0.333f")
    a(f"IF GE JUMP {p}_m1")
    a.put(Z_OFF, "R9", "offset = 1.0f")
    a(f"R5 = {F1_5}")
    a("F6 = F1 * F5", "phase_shift = 0.25f + mode * 1.50f")
    a(f"R3 = {QUARTER}")
    a("F4 = F3 + F6")
    a(f"JUMP {p}_ps")
    a.label(f"{p}_m1")
    a(f"R5 = {F0_33}")
    a("F6 = F1 - F5", "phase_shift = 0.7495f - (mode - 0.33f) * 0.75f")
    a(f"R5 = {F0_75}")
    a("F6 = F6 * F5")
    a(f"R5 = {F0_7495}")
    a("F4 = F5 - F6")
    a(f"R3 = {F0_666}")
    a("COMP(F1, F3)", "mode < 0.666f")
    a(f"IF GE JUMP {p}_m2")
    a.put(Z_DISC, "R4", "(phase_shift)")
    a.sine(0, 4, 1, 2, 3)
    a("F0 = -F0", "offset = -Sine(phase_shift)")
    a.put(Z_OFF, "R0")
    a.slot("R4", Z_DISC)
    a(f"JUMP {p}_ps")
    a.label(f"{p}_m2")
    a(f"R0 = {F0_001}")
    a.put(Z_OFF, "R0", "offset = 0.001f")
    a.label(f"{p}_ps")
    a.slot("R0", Z_F)
    a("F0 = F0 + F4", "discontinuity = Sine(f + phase_shift)")
    a.sine(0, 0, 1, 2, 3)
    a.put(Z_DISC, "R0")
    a.slot("R1", Z_SH)
    a(f"R3 = {HALF}")
    a("COMP(F1, F3)", "shape < 0.5f")
    a(f"IF GE JUMP {p}_s2")
    a(f"R3 = {TWO}")
