"""Generate lib/va_sm.s: VA's variable saw sample loop (engines/va.c, saw_render) as a SISD kernel, bit-identical to
selcc's code of the C loop (-DPL_VA_C).

    python3 modules/machines/plaits/src/dsp/lib/gen_va_kernel.py

Every float operation is the C's, with the same operands in the same order (commutative swaps only); the blep helpers,
saw_naive and selcc's division are written out. The output's division by the constant 1 + kVariableSawNotchDepth
runs selcc's sequence with the divisor's reciprocal (RECIPS and two Newton steps, which depend on the divisor only)
computed once. tests/plaits/test_va_kernel.py checks it against the C on the concrete core.
"""

from __future__ import annotations

from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE / "va_sm.s"

# Frame slots above I7 (after the register saves at 1..6).
SU, SD, TRI, NA, PPW, CNT, Y, D = range(7, 15)
FRAME = 14
ONE, HALF, MHALF, TWO = "0x3F800000", "0x3F000000", "0xBF000000", "0x40000000"
DEPTH = "0x3E4CCCCD"  # kVariableSawNotchDepth = 0.2f
C0_1875, C1_5 = "0x3E400000", "0x3FC00000"

HEADER = """\
// machines/plaits: VA's variable saw sample loop (engines/va.c, saw_render), hand-written SISD kernel.
// Generated by lib/gen_va_kernel.py; do not edit by hand.
//
// saw_kernel(Saw *s, const float *k, float *out, int size):
//   s = the saw (phase_, next_sample_, previous_pw_, high_, then the three interpolators' values frequency_, pw_,
//   waveshape_); k[0..2] = the interpolators' increments. Writes `size` samples to out and the state back (the
//   values are the interpolators' commits), bit-identical to selcc's code of the C loop (-DPL_VA_C): the same
//   operations with the same operands in the same order (tests/plaits/test_va_kernel.py).
//
// State on return: R0-R8, R12, I4 and the flags change; every other register is as on entry (R9-R11, R13-R15 saved
// above I7; I0, I1, M6, L0, L1, L4 pushed through R0, M6 = 1 and L0 = L1 = L4 = 0 set here). No SIMD, no DO loop.
// Registers in the loop: R15 phase, R13 next_sample, R12 this_sample, R11 high_, R10 frequency, R9 pw; I1 = s,
// I4 = k, I0 = out; the other per-sample values live in frame slots above I7.
//
// ABI: as the other kernels (lib/wavetable_sm.s): relies on M5 = 0 and M7 = -1, sets M6 = 1 itself; DAG registers
// are pushed through R0 and restored by loads through I7. Assembled under .COMPRESS (the assembler leaves the
// instructions of a DO loop in their 48-bit forms, as the PRM requires for a loop's last 11): smaller hot code.

.SECTION/PM seg_pmco;
.GLOBAL saw_kernel.;
.COMPRESS;
"""


class Asm:
    def __init__(self) -> None:
        self.lines: list[str] = []

    def __call__(self, text: str, comment: str = "") -> None:
        line = f"    {text};"
        if comment:
            line = f"{line:<56}// {comment}"
        self.lines.append(line)

    def label(self, name: str) -> None:
        self.lines.append(f"{name}:")

    def raw(self, text: str) -> None:
        self.lines.append(text)

    def recips(self, y: str, d: str) -> None:
        self(f"{y} = RECIPS {d}")

    def div(
        self, res: str, n: str, d: str, y: str, t: str, w: str, comment: str = ""
    ) -> None:
        """res = n / d as selcc divides; w holds 2.0 on entry. res may be w."""
        self.recips(y, d)
        self(f"{t} = {d} * {y}", comment or "selcc division")
        self(f"{t} = {w} - {t}")
        self(f"{y} = {y} * {t}")
        self(f"{t} = {d} * {y}")
        self(f"{t} = {w} - {t}")
        self(f"{y} = {y} * {t}")
        self(f"{w} = {n} * {y}")
        self(f"{t} = {d} * {w}")
        self(f"{t} = {n} - {t}")
        self(f"{t} = {t} * {y}")
        self(f"{res} = {w} + {t}")

    def slot(self, reg: str, k: int, comment: str = "") -> None:
        self(f"{reg} = DM({k}, I7)", comment)

    def put(self, k: int, reg: str, comment: str = "") -> None:
        self(f"DM({k}, I7) = {reg}", comment)

    def nib(self, res: str, x: str) -> None:
        """res = NextIntegratedBlepSample(x); uses R0, R4, R5, R7, R8."""
        self(f"R0 = {HALF}")
        self(f"F4 = F0 * {x}", "t1")
        self("F5 = F4 * F4", "t2")
        self("F7 = F5 * F5", "t4")
        self(f"R8 = {C0_1875}")
        self("F4 = F8 - F4", "0.1875 - t1")
        self(f"R0 = {C1_5}")
        self("F5 = F0 * F5", "1.5 t2")
        self("F4 = F4 + F5")
        self(f"{res} = F4 - F7")

    def tstep(self) -> None:
        """F6 = (slope_up + slope_down) * frequency * triangle_amount."""
        self.slot("R6", SU)
        self.slot("R7", SD)
        self("F6 = F6 + F7", "triangle_step")
        self("F6 = F6 * F10")
        self.slot("R7", TRI)
        self("F6 = F6 * F7")

    def blep(self, scale: str, this_op: str, int_op: str) -> None:
        """this/next_sample (this_op)= scale * This/NextBlepSample(t), (int_op)= F6 * This/NextIntegratedBlepSample(t);
        t in F2 (kept), scale in F8 (lost)."""
        self(f"R0 = {HALF}")
        self("F0 = F0 * F2", "ThisBlepSample(t)")
        self("F0 = F0 * F2")
        self(f"F0 = {scale} * F0")
        self(f"F12 = F12 {this_op} F0")
        self(f"R1 = {ONE}")
        self("F3 = F1 - F2", "1 - t")
        self(f"R0 = {MHALF}")
        self("F0 = F0 * F3", "NextBlepSample(t)")
        self("F0 = F0 * F3")
        self(f"F0 = {scale} * F0")
        self(f"F13 = F13 {this_op} F0")
        self.nib("F1", "F3")
        self("F1 = F6 * F1", "ThisIntegratedBlepSample(t)")
        self(f"F12 = F12 {int_op} F1")
        self.nib("F1", "F2")
        self("F1 = F6 * F1", "NextIntegratedBlepSample(t)")
        self(f"F13 = F13 {int_op} F1")


def kernel() -> str:
    a = Asm()
    a.label("saw_kernel.")
    dags = ["I0", "I1", "M6", "L0", "L1", "L4"]
    for r in dags:
        a(f"R0 = {r}")
        a("DM(I7, M7) = R0")
    a("M6 = 1")
    for r in ("L0", "L1", "L4"):
        a(f"{r} = 0")
    a(f"I7=MODIFY (I7,-{FRAME})(NW)")
    saves = ["R9", "R10", "R11", "R13", "R14", "R15"]
    for i, r in enumerate(saves):
        a.put(i + 1, r)
    a("I1 = R4", "s")
    a("I4 = R8", "k")
    a("I0 = R12", "out")
    a("R0 = DM(1, I6)", "size")
    a.put(CNT, "R0")
    a("R15 = DM(0, I1)", "phase_")
    a("R13 = DM(1, I1)", "next_sample_")
    a("R2 = DM(2, I1)", "previous_pw_")
    a.put(PPW, "R2")
    a("R11 = DM(3, I1)", "high_")
    # d = 1.0f + kVariableSawNotchDepth and its reciprocal after selcc's two Newton steps
    a(f"R1 = {ONE}")
    a(f"R2 = {DEPTH}")
    a("F2 = F1 + F2", "1.0f + kVariableSawNotchDepth")
    a.put(D, "R2")
    a(f"R3 = {TWO}")
    a.recips("F4", "F2")
    a("F5 = F2 * F4")
    a("F5 = F3 - F5")
    a("F4 = F4 * F5")
    a("F5 = F2 * F4")
    a("F5 = F3 - F5")
    a("F4 = F4 * F5")
    a.put(Y, "R4")
    a("R1 = 0")
    a("COMP(R0, R1)")
    a("IF LE JUMP _swk_done")

    a.label("_swk_loop")
    a("R12 = PASS R13", "this_sample = next_sample")
    a("R13 = 0", "next_sample = 0.0f")
    a("R0 = DM(4, I1)")
    a("R1 = DM(0, I4)")
    a("F10 = F0 + F1", "frequency = fm.Next()")
    a("DM(4, I1) = R10")
    a("R0 = DM(5, I1)")
    a("R1 = DM(1, I4)")
    a("F9 = F0 + F1", "pw")
    a("DM(5, I1) = R9")
    a("R0 = DM(6, I1)")
    a("R1 = DM(2, I4)")
    a("F0 = F0 + F1", "waveshape = triangle_amount")
    a("DM(6, I1) = R0")
    a.put(TRI, "R0")
    a(f"R1 = {ONE}")
    a("F1 = F1 - F0", "notch_amount = 1.0f - waveshape")
    a.put(NA, "R1")
    # slope_up = 1 / pw and slope_down = 1 / (1 - pw), two selcc divisions interleaved
    a(f"R0 = {ONE}")
    a(f"R3 = {TWO}")
    a(f"R7 = {TWO}")
    a("F4 = F0 - F9", "1.0f - pw")
    a.recips("F1", "F9")
    a.recips("F5", "F4")
    a("F2 = F9 * F1", "slope_up, slope_down: selcc divisions")
    a("F6 = F4 * F5")
    a("F2 = F3 - F2")
    a("F6 = F7 - F6")
    a("F1 = F1 * F2")
    a("F5 = F5 * F6")
    a("F2 = F9 * F1")
    a("F6 = F4 * F5")
    a("F2 = F3 - F2")
    a("F6 = F7 - F6")
    a("F1 = F1 * F2")
    a("F5 = F5 * F6")
    a("F3 = F0 * F1")
    a("F7 = F0 * F5")
    a("F2 = F9 * F3")
    a("F6 = F4 * F7")
    a("F2 = F0 - F2")
    a("F6 = F0 - F6")
    a("F2 = F2 * F1")
    a("F6 = F6 * F5")
    a("F3 = F3 + F2")
    a("F7 = F7 + F6")
    a.put(SU, "R3", "slope_up")
    a.put(SD, "R7", "slope_down")
    a("F15 = F15 + F10", "phase_ += frequency")
    a("R2 = 0")
    a("COMP(R11, R2)", "!high_ && phase_ >= pw")
    a("IF NE JUMP _swk_else")
    a("COMP(F15, F9)")
    a("IF LT JUMP _swk_else")
    a.tstep()
    a(f"R1 = {DEPTH}")
    a(f"R0 = {ONE}")
    a("F1 = F1 + F0", "kVariableSawNotchDepth + 1.0f - pw")
    a("F1 = F1 - F9")
    a.slot("R0", NA)
    a("F8 = F1 * F0", "notch")
    a.slot("R0", PPW)
    a("F0 = F0 - F9", "previous_pw_ - pw + frequency")
    a("F0 = F0 + F10")
    a("F1 = F15 - F9", "phase_ - pw")
    a(f"R4 = {TWO}")
    a("R14 = PASS R8", "notch (the division uses R3-R5)")
    a.div("F2", "F1", "F0", "F3", "F5", "F4", "t")
    a("R8 = PASS R14")
    a.blep("F8", "+", "-")
    a("R11 = 1", "high_ = 1")
    a("JUMP _swk_naive")
    a.label("_swk_else")
    a(f"R0 = {ONE}")
    a("COMP(F15, F0)", "else if (phase_ >= 1.0f)")
    a("IF LT JUMP _swk_naive")
    a("F15 = F15 - F0")
    a.tstep()
    a(f"R1 = {DEPTH}")
    a(f"R0 = {ONE}")
    a("F1 = F1 + F0", "(kVariableSawNotchDepth + 1.0f) * notch_amount")
    a.slot("R0", NA)
    a("F14 = F1 * F0", "notch")
    a(f"R4 = {TWO}")
    a.div("F2", "F15", "F10", "F3", "F5", "F4", "t = phase_ / frequency")
    a("R8 = PASS R14")
    a.blep("F8", "-", "+")
    a("R11 = 0", "high_ = 0")
    a.label("_swk_naive")
    # saw_naive(phase_, pw, slope_up, slope_down, triangle_amount, notch_amount)
    a(f"R1 = {DEPTH}")
    a(f"R0 = {ONE}")
    a("F1 = F0 + F1", "1.0f + kVariableSawNotchDepth")
    a("COMP(F15, F9)", "notch_saw = phase < pw ? phase : ..")
    a("IF LT R1 = R15 OR R15")
    a.slot("R2", SU)
    a("F2 = F15 * F2", "phase * slope_up")
    a("F3 = F15 - F9")
    a.slot("R4", SD)
    a("F3 = F3 * F4")
    a("F3 = F0 - F3", "1.0f - (phase - pw) * slope_down")
    a("COMP(F15, F9)", "triangle = phase < pw ? ..")
    a("IF LT R3 = R2 OR R2")
    a.slot("R4", NA)
    a("F1 = F1 * F4", "notch_saw * notch_amount")
    a.slot("R4", TRI)
    a("F3 = F3 * F4", "triangle * triangle_amount")
    a("F1 = F1 + F3")
    a("F13 = F13 + F1", "next_sample += saw_naive(..)")
    a.put(PPW, "R9", "previous_pw_ = pw")
    a(f"R0 = {TWO}")
    a("F0 = F0 * F12", "(2.0f * this_sample - 1.0f) / (1.0f + kVariableSawNotchDepth)")
    a(f"R1 = {ONE}")
    a("F5 = F0 - F1", "n")
    a.slot("R4", Y)
    a.slot("R2", D)
    a("F0 = F5 * F4", "selcc division: w = n y")
    a("F1 = F2 * F0", "t = d w")
    a("F1 = F5 - F1", "t = n - t")
    a("F1 = F1 * F4", "t = t y")
    a("F0 = F0 + F1")
    a("DM(I0, M6) = R0")
    a.slot("R0", CNT)
    a("R1 = 1")
    a("R0 = R0 - R1")
    a.put(CNT, "R0")
    a("IF NE JUMP _swk_loop")
    a.label("_swk_done")
    a("DM(0, I1) = R15")
    a("DM(1, I1) = R13")
    a.slot("R0", PPW)
    a("DM(2, I1) = R0")
    a("DM(3, I1) = R11")
    for i, r in enumerate(saves):
        a.slot(r, i + 1)
    a(f"I7=MODIFY (I7,{FRAME})(NW)")
    for i, r in enumerate(reversed(dags)):
        a(f"{r} = DM({i + 1}, I7)")
    a("I12 = DM(M7, I6)")
    a("JUMP (M14, I12) (DB)")
    a("RFRAME")
    a("NOP")
    return HEADER + "\n" + "\n".join(a.lines) + "\n"


def main() -> None:
    OUT.write_text(kernel())
    print(OUT)


if __name__ == "__main__":
    main()
