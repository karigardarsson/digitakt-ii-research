"""Generate lib/terrain_sm.s: TERRAIN's sample loop (engines/terrain.c: terrain_render's loop over the samples, the two
oversampled path points, the two terrains of each and the AUX sine) as a SISD kernel, bit-identical to selcc's code
of the C (-DPL_TERRAIN_C).

    python3 modules/machines/plaits/src/dsp/lib/gen_terrain_kernel.py

Every float operation is the C's, with the same operands in the same order (commutative swaps only); terrain(),
terrain_sine (the negative-phase wrap with itof of a negative integer), Sine, squash, absf, terrain_lookup_wt with
interpolate_integrated_wave and selcc's division are written out (terrain() and terrain_sine as local subroutines,
CALL / RTS (DB)); comparisons are selcc's. tests/plaits/test_terrain_kernel.py checks it against the C on the concrete
core.
"""

from __future__ import annotations

from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE / "terrain_sm.s"

C = {
    "one": "0x3F800000",
    "half": "0x3F000000",
    "two": "0x40000000",
    "four": "0x40800000",
    "five": "0x40A00000",
    "q": "0x3E800000",
    "1.273": "0x3FA2F1AA",
    "1.571": "0x3FC91687",
    "0.637": "0x3F23126F",
    "0.57": "0x3F11EB85",
    "0.2": "0x3E4CCCCD",
    "0.159": "0x3E22D0E5",
    "2.387": "0x4018C49C",
    "0.350": "0x3EB33333",
    "6.366": "0x40CBB646",
    "0.170": "0x3E2E147B",
    "0.477": "0x3EF43958",
    "1.5": "0x3FC00000",
    "63": "0x427C0000",
    "128": "0x43000000",
    "130": "0x43020000",
    "1/1024": "0x3A800000",
    "512": "0x44000000",
    "bias": "0x4B000000",
}

HEADER = """\
// machines/plaits: TERRAIN's sample loop (engines/terrain.c, terrain_render), hand-written SISD kernel.
// Generated by lib/gen_terrain_kernel.py; do not edit by hand.
//
// terrain_kernel(Terrain *s, const float *k, float *out, float *aux, const float *path_x, const float *path_y, int size):
//   s = the engine (path_ 4 words, then the interpolators' values offset_, terrain_); k[0..1] = their increments;
//   path_x / path_y = the 2 size oversampled path points. Writes out and aux and the interpolators back,
//   bit-identical to selcc's code of the C loop (-DPL_TERRAIN_C) (tests/plaits/test_terrain_kernel.py).
//
// State on return: R0-R8, R12, I4 and the flags change; every other register is as on entry (R9-R11, R13-R15 saved
// above I7; I0, I1, I2, I3, I5, M6, L0-L5 pushed through R0, M6 = 1 and L0-L5 = 0 set here). No SIMD.
// ABI: as the other kernels (lib/wavetable_sm.s). Assembled under .COMPRESS; integer additions in their 48-bit form.
// Local subroutines: _tk_ter (F10 = x, F11 = y, R12 = terrain index -> F0; changes R0-R8, I4) and _tk_sin
// (F0 = phase -> F0 = terrain_sine(phase); changes R0-R3, I4). R15 = itof_nonneg's bias, R14 = pl_lut_sine,
// R13 = pl_wav_integrated_waves throughout.

.SECTION/PM seg_pmco;
.GLOBAL terrain_kernel.;
.EXTERN pl_lut_sine.;
.EXTERN pl_wav_integrated_waves.;
.COMPRESS;
"""

DAGS = ["I0", "I1", "I2", "I3", "I5", "M6", "L0", "L1", "L2", "L3", "L4", "L5"]
SAVES = ["R9", "R10", "R11", "R13", "R14", "R15"]
K0, K1, CNT, XO, M, ZI, ZF, OS, AS, Z0, Y = range(7, 18)
FRAME = 17


class Asm:
    def __init__(self) -> None:
        self.lines: list[str] = []

    def __call__(self, text: str, comment: str = "") -> None:
        line = f"    {text};"
        self.lines.append(f"{line:<56}// {comment}" if comment else line)

    def label(self, name: str) -> None:
        self.lines.append(f"{name}:")

    def iadd(self, text: str, comment: str = "") -> None:
        self.lines.append("    .NOCOMPRESS;")
        self(text, comment)
        self.lines.append("    .COMPRESS;")

    def k(self, reg: str, name: str) -> None:
        self(f"{reg} = {C[name]}", name)

    def div(
        self, res: str, n: str, d: str, y: str, t: str, w: str, comment: str = ""
    ) -> None:
        """res = n / d as selcc divides; w holds 2.0 on entry. res may be w."""
        self(f"{y} = RECIPS {d}")
        self(f"{t} = {d} * {y}", comment or "selcc division")
        self(f"{t} = {w} - {t}")
        self(f"{y} = {y} * {t}")
        self(f"{t} = {d} * {y}")
        self(f"{t} = {w} - {t}")
        self(f"{y} = {y} * {t}")
        self(f"{w} = {n} * {y}")
        self(f"{t} = {d} * {w}")
        self(f"{t} = {n} - {t}")
        self(f"{t} = {t} * {y}")
        self(f"{res} = {w} + {t}")

    def absf(self, dst: int, x: int, zero: int) -> None:
        """F{dst} = absf(F{x}) (x < 0 ? -x : x; selcc: COMP(x, 0); IF GE x); R{zero} holds 0."""
        self(f"F{dst} = -F{x}")
        self(f"COMP(F{x}, F{zero})")
        self(f"IF GE R{dst} = R{x} OR R{x}")

    def ret(self) -> None:
        self.lines.append("    .NOCOMPRESS;")
        self("RTS (DB)", "the stock return form is delayed")
        self.lines.append("    .COMPRESS;")
        self("NOP")
        self("NOP")


def sin_sub(a: Asm) -> None:
    """_tk_sin: F0 = terrain_sine(F0); uses R1-R3, I4."""
    a.label("_tk_sin")
    a("R1 = 0")
    a("COMP(F0, F1)", "phase < 0.0f: wrap by its integer part plus one")
    a("IF GE JUMP _tks_s")
    a("R1 = TRUNC F0", "(int)phase (<= 0)")
    a("R2 = 0")
    a("COMP(R1, R2)", "itof: i < 0 ? -itof_nonneg(-i) : itof_nonneg(i)")
    a("IF GE JUMP _tks_p")
    a("R1 = -R1")
    a("R1 = R15 OR R1")
    a("F1 = F1 - F15")
    a("F1 = -F1")
    a("JUMP _tks_d")
    a.label("_tks_p")
    a("R1 = R15 OR R1")
    a("F1 = F1 - F15")
    a.label("_tks_d")
    a("F0 = F0 - F1", "phase - itof((int)phase) + 1.0f")
    a.k("R1", "one")
    a("F0 = F0 + F1")
    a("COMP(F0, F1)", "phase >= 1.0f: phase -= 1.0f")
    a("IF LT JUMP _tks_s")
    a("F0 = F0 - F1")
    a.label("_tks_s")
    a("R1 = TRUNC F0", "Sine: index -= itof_nonneg((int)index)")
    a("R1 = R15 OR R1")
    a("F1 = F1 - F15")
    a("F1 = F0 - F1")
    a.k("R2", "512")
    a("F1 = F1 * F2", "index *= 512.0f")
    a("R2 = TRUNC F1", "index_integral")
    a("R3 = R15 OR R2")
    a("R2 = LSHIFT R2 BY 2")
    a.iadd("R2 = R2 + R14")
    a("I4 = R2")
    a("F3 = F3 - F15")
    a("F3 = F1 - F3", "index_fractional")
    a("R0 = DM(I4, M5)", "a")
    a("R2 = DM(1, I4)", "b")
    a("F2 = F2 - F0", "a + (b - a) * index_fractional")
    a("F2 = F2 * F3")
    a("F0 = F0 + F2")
    a.ret()


def iiw(a: Asm, dst: int, idx: int, t: int) -> None:
    """F{dst} = interpolate_integrated_wave(R{idx}, F{t}) = (b - a) + (c - b - b + a) * t; uses R0-R3 (idx kept)."""
    a(f"R0 = LSHIFT R{idx} BY 2")
    a.iadd("R0 = R0 + R13")
    a("I4 = R0")
    a("R0 = 0", "(DAG gap)")
    a("R1 = 0")
    a("R0 = DM(I4, M5)", "a")
    a("R1 = DM(1, I4)", "b")
    a("R2 = DM(2, I4)", "c")
    a("F3 = F1 - F0", "b - a")
    a("F2 = F2 - F1", "c - b - b + a")
    a("F2 = F2 - F1")
    a("F2 = F2 + F0")
    a(f"F2 = F2 * F{t}")
    a(f"F{dst} = F3 + F2")


def ter_sub(a: Asm) -> None:
    """_tk_ter: F0 = terrain(F10, F11, R12); uses R0-R8, I4 (calls _tk_sin)."""
    a.label("_tk_ter")
    for i, lab in enumerate(("_tkt0", "_tkt1", "_tkt2", "_tkt3", "_tkt4")):
        a(f"R0 = {i}")
        a("COMP(R12, R0)")
        a(f"IF EQ JUMP {lab}")
    a("R0 = 5")
    a("COMP(R12, R0)", "5..7: terrain_lookup_wt")
    a("IF LT JUMP _tkt_z")
    a("R0 = 7")
    a("COMP(R12, R0)")
    a("IF LE JUMP _tkt_wt")
    a.label("_tkt_z")
    a("R0 = 0", "return 0.0f")
    a.ret()
    # 0: (squash(terrain_sine(k + x * 1.273f), 2.0f) - terrain_sine(k + y * (x + 1.571f) * 0.637f)) * 0.57f
    a.label("_tkt0")
    a.k("R1", "1.273")
    a("F0 = F10 * F1")
    a.k("R1", "four")
    a("F0 = F1 + F0")
    a("CALL _tk_sin")
    a.k("R1", "two")
    a("F0 = F0 * F1", "squash: x *= a; x / (1.0f + absf(x))")
    a("R4 = 0")
    a.absf(5, 0, 4)
    a.k("R1", "one")
    a("F5 = F1 + F5")
    a.k("R7", "two")
    a.div("F4", "F0", "F5", "F6", "F8", "F7")
    a.k("R1", "1.571")
    a("F0 = F10 + F1")
    a("F0 = F11 * F0")
    a.k("R1", "0.637")
    a("F0 = F0 * F1")
    a.k("R1", "four")
    a("F0 = F1 + F0")
    a("CALL _tk_sin")
    a("F4 = F4 - F0")
    a.k("R1", "0.57")
    a("F0 = F4 * F1")
    a.ret()
    # 1 / 2: terrain_sine(k + terrain_sine(k + A) / (D + xy * xy) * 0.159f)
    for n, d in ((1, "0.2"), (2, "0.350")):
        a.label(f"_tkt{n}")
        a("F4 = F10 * F11", "xy = x * y")
        if n == 1:
            a("F0 = F10 + F11", "(x + y) * 0.637f")
            a.k("R1", "0.637")
            a("F0 = F0 * F1")
        else:
            a.k("R1", "2.387")
            a("F0 = F1 * F4", "2.387f * xy")
        a.k("R1", "four")
        a("F0 = F1 + F0")
        a("CALL _tk_sin")
        a("F5 = F4 * F4")
        a.k("R1", d)
        a("F5 = F1 + F5")
        a.k("R7", "two")
        a.div("F0", "F0", "F5", "F6", "F8", "F7")
        a.k("R1", "0.159")
        a("F0 = F0 * F1")
        a.k("R1", "four")
        a("F0 = F1 + F0")
        a("CALL _tk_sin")
        a.ret()
    # 3: terrain_sine(k + xy / (2.0f + absf(5.0f * xys)) * 6.366f)
    a.label("_tkt3")
    a("F4 = F10 * F11", "xy")
    a.k("R1", "q")
    a("F5 = F10 - F1", "xys = (x - 0.25f) * (y + 0.25f)")
    a("F6 = F11 + F1")
    a("F5 = F5 * F6")
    a.k("R1", "five")
    a("F5 = F1 * F5")
    a("R3 = 0")
    a.absf(6, 5, 3)
    a.k("R1", "two")
    a("F6 = F1 + F6")
    a.k("R7", "two")
    a.div("F0", "F4", "F6", "F5", "F8", "F7")
    a.k("R1", "6.366")
    a("F0 = F0 * F1")
    a.k("R1", "four")
    a("F0 = F1 + F0")
    a("CALL _tk_sin")
    a.ret()
    # 4: terrain_sine(0.159f / (0.170f + absf(y - 0.25f)) + 0.477f / (0.350f + absf((x + 0.5f) * (y + 1.5f))) + k)
    a.label("_tkt4")
    a("R3 = 0")
    a.k("R1", "q")
    a("F5 = F11 - F1")
    a.absf(6, 5, 3)
    a.k("R1", "0.170")
    a("F6 = F1 + F6")
    a.k("R2", "0.159")
    a.k("R7", "two")
    a.div("F4", "F2", "F6", "F5", "F8", "F7")
    a.k("R1", "half")
    a("F5 = F10 + F1")
    a.k("R1", "1.5")
    a("F6 = F11 + F1")
    a("F5 = F5 * F6")
    a("R3 = 0")
    a.absf(6, 5, 3)
    a.k("R1", "0.350")
    a("F6 = F1 + F6")
    a.k("R2", "0.477")
    a.k("R7", "two")
    a.div("F0", "F2", "F6", "F5", "F8", "F7")
    a("F0 = F4 + F0")
    a.k("R1", "four")
    a("F0 = F0 + F1")
    a("CALL _tk_sin")
    a.ret()
    # 5..7: terrain_lookup_wt(x, y, 2 - (index - 5))
    a.label("_tkt_wt")
    a.k("R1", "one")
    a("F4 = F11 + F1", "sample = (y + 1.0f) * 0.5f * 128.0f")
    a.k("R2", "half")
    a("F4 = F4 * F2")
    a.k("R3", "128")
    a("F4 = F4 * F3")
    a("F5 = F10 + F1", "wt = (x + 1.0f) * 0.5f * 63.0f")
    a("F5 = F5 * F2")
    a.k("R6", "63")
    a("F5 = F5 * F6")
    a("R0 = 0")
    a.label("_tkt_w1")
    a("COMP(F4, F0)", "while (sample < 0.0f) sample += 128.0f")
    a("IF GE JUMP _tkt_w2")
    a("F4 = F4 + F3")
    a("JUMP _tkt_w1")
    a.label("_tkt_w2")
    a.k("R1", "130")
    a.label("_tkt_w3")
    a("COMP(F4, F1)", "while (sample >= 130.0f) sample -= 128.0f")
    a("IF LT JUMP _tkt_w4")
    a("F4 = F4 - F3")
    a("JUMP _tkt_w3")
    a.label("_tkt_w4")
    a("COMP(F5, F0)", "if (wt < 0.0f) wt = 0.0f")
    a("IF LT R5 = R0 OR R0")
    a("COMP(F5, F6)", "if (wt > 63.0f) wt = 63.0f")
    a("IF GT R5 = R6 OR R6")
    a("R6 = TRUNC F4", "sample_integral")
    a("R7 = R15 OR R6")
    a("F7 = F7 - F15")
    a("F4 = F4 - F7", "sample_fractional")
    a("R7 = TRUNC F5", "wt_integral")
    a("R8 = R15 OR R7")
    a("F8 = F8 - F15")
    a("F5 = F5 - F8", "wt_fractional")
    a("R0 = 7")
    a.iadd("R0 = R0 - R12", "bank = 2 - (index - 5)")
    a("R1 = LSHIFT R0 BY 13", "bank * (64 * 132) = bank * 8192 + bank * 256")
    a("R0 = LSHIFT R0 BY 8")
    a.iadd("R1 = R1 + R0")
    a("R0 = LSHIFT R7 BY 7", "wt_integral * 132 = * 128 + * 4")
    a("R2 = LSHIFT R7 BY 2")
    a.iadd("R0 = R0 + R2")
    a.iadd("R1 = R1 + R0")
    a.iadd("R8 = R1 + R6", "base")
    iiw(a, 6, 8, 4)
    a("R0 = 63")
    a("COMP(R7, R0)", "wt_integral >= 63: xy1 = xy0")
    a("IF LT JUMP _tkt_w5")
    a("R0 = PASS R6")
    a("JUMP _tkt_w6")
    a.label("_tkt_w5")
    a("R0 = 132")
    a.iadd("R8 = R8 + R0")
    iiw(a, 0, 8, 4)
    a.label("_tkt_w6")
    a("F0 = F0 - F6", "(xy0 + (xy1 - xy0) * wt_fractional) * value_scale")
    a("F0 = F0 * F5")
    a("F0 = F6 + F0")
    a.k("R1", "1/1024")
    a("F0 = F0 * F1")
    a.ret()


def kernel() -> str:
    a = Asm()
    a.label("terrain_kernel.")
    for r in DAGS:
        a(f"R0 = {r}")
        a("DM(I7, M7) = R0")
    a("M6 = 1")
    for r in DAGS[6:]:
        a(f"{r} = 0")
    a(f"I7=MODIFY (I7,-{FRAME})(NW)")
    for i, r in enumerate(SAVES):
        a(f"DM({i + 1}, I7) = {r}")
    a("I5 = R4", "s")
    a("I4 = R8", "k")
    a("I0 = R12", "out")
    a("R0 = DM(0, I4)")
    a(f"DM({K0}, I7) = R0")
    a("R0 = DM(1, I4)")
    a(f"DM({K1}, I7) = R0")
    a("R0 = DM(1, I6)", "aux")
    a("I1 = R0")
    a("R0 = DM(2, I6)", "path_x")
    a("I2 = R0")
    a("R0 = DM(3, I6)", "path_y")
    a("I3 = R0")
    a("R0 = DM(4, I6)", "size")
    a(f"DM({CNT}, I7) = R0")
    a.k("R15", "bias")
    a("R14 = pl_lut_sine.")
    a("R13 = pl_wav_integrated_waves.")
    a("R1 = 0")
    a("COMP(R0, R1)")
    a("IF LE JUMP _tk_done")
    a.label("_tk_loop")
    a("R0 = DM(4, I5)")
    a(f"R1 = DM({K0}, I7)")
    a("F0 = F0 + F1", "x_offset = offset.Next()")
    a("DM(4, I5) = R0")
    a(f"DM({XO}, I7) = R0")
    a("R2 = DM(5, I5)")
    a(f"R1 = DM({K1}, I7)")
    a("F2 = F2 + F1", "zz = terrain_z.Next()")
    a("DM(5, I5) = R2")
    a("R3 = TRUNC F2", "zz_integral")
    a(f"DM({ZI}, I7) = R3")
    a("R4 = R15 OR R3")
    a("F4 = F4 - F15")
    a("F2 = F2 - F4", "zz_fractional")
    a(f"DM({ZF}, I7) = R2")
    a("R1 = 0")
    a(f"DM({OS}, I7) = R1", "out_s = 0.0f")
    a(f"DM({AS}, I7) = R1", "aux_s = 0.0f")
    for _j in range(2):
        a(f"R0 = DM({XO}, I7)")
        a("R1 = 0")
        a.absf(2, 0, 1)
        a.k("R1", "one")
        a("F2 = F1 - F2", "x = path_x[ij] * (1.0f - absf(x_offset)) + x_offset")
        a("R3 = DM(I2, M6)")
        a("F3 = F3 * F2")
        a("F10 = F3 + F0")
        a("R11 = DM(I3, M6)", "y = path_y[ij]")
        a(f"R12 = DM({ZI}, I7)")
        a("CALL _tk_ter", "z0 = terrain(x, y, zz_integral)")
        a(f"DM({Z0}, I7) = R0")
        a(f"R12 = DM({ZI}, I7)")
        a("R1 = 1")
        a.iadd("R12 = R12 + R1")
        a("CALL _tk_ter", "z1 = terrain(x, y, zz_integral + 1)")
        a(f"R1 = DM({Z0}, I7)")
        a("F0 = F0 - F1", "z = z0 + (z1 - z0) * zz_fractional")
        a(f"R2 = DM({ZF}, I7)")
        a("F0 = F0 * F2")
        a("F0 = F1 + F0")
        a(f"R1 = DM({OS}, I7)")
        a("F1 = F1 + F0", "out_s += z")
        a(f"DM({OS}, I7) = R1")
        a("F0 = F11 + F0", "aux_s += y + z")
        a(f"R1 = DM({AS}, I7)")
        a("F1 = F1 + F0")
        a(f"DM({AS}, I7) = R1")
    a(f"R0 = DM({OS}, I7)")
    a.k("R1", "half")
    a("F0 = F1 * F0", "out[i] = kScale * out_s")
    a("DM(I0, M6) = R0")
    a(f"R0 = DM({AS}, I7)")
    a.k("R1", "q")
    a("F0 = F1 * F0", "aux[i] = terrain_sine(1.0f + 0.5f * kScale * aux_s)")
    a.k("R1", "one")
    a("F0 = F1 + F0")
    a("CALL _tk_sin")
    a("DM(I1, M6) = R0")
    a(f"R0 = DM({CNT}, I7)")
    a("R1 = 1")
    a.iadd("R0 = R0 - R1")
    a(f"DM({CNT}, I7) = R0")
    a("IF NE JUMP _tk_loop")
    a.label("_tk_done")
    for i, r in enumerate(SAVES):
        a(f"{r} = DM({i + 1}, I7)")
    a(f"I7=MODIFY (I7,{FRAME})(NW)")
    for i, r in enumerate(reversed(DAGS)):
        a(f"{r} = DM({i + 1}, I7)")
    a("I12 = DM(M7, I6)")
    a("JUMP (M14, I12) (DB)")
    a("RFRAME")
    a("NOP")
    sin_sub(a)
    ter_sub(a)
    return "\n".join(a.lines) + "\n"


def main() -> None:
    OUT.write_text(HEADER + "\n" + kernel())
    print(OUT)


if __name__ == "__main__":
    main()
