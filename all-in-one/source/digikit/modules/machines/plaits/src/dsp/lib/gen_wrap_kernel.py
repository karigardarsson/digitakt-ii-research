"""Generate src/dsp/wrap_sm.s: the voice wrapper's per-block path (plaits.c: plaits_render at 48 kHz, render_engine and
render_sub) in assembly, bit-identical to selcc's code of the C (-DPL_WRAP_C).

    python3 modules/machines/plaits/src/dsp/lib/gen_wrap_kernel.py

It keeps selcc's calling convention: it is entered by CJUMP (from plaits_track), keeps its locals below I6 as selcc
does, calls the C engines, note_on (plaits_note_on_c) and plaits_stage_kernel by CJUMP with selcc's argument
registers and stack, and returns with selcc's return sequence. At 96 kHz it jumps to the C (plaits_render_c) on the
same frame. The knob conversions (unit) and the trigger follow selcc's operations and comparisons;
tests/plaits/test_wrap_kernel.py checks it against the C on the concrete core with recording engine stubs.
"""

from __future__ import annotations

from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE.parent / "wrap_sm.s"

ENGINES = [
    "va_render", "ws_render", "fm_render", "grain_render", "additive_render", "wavetable_render", "chord_render",
    "speech_render", "swarm_render", "noise_render", "dust_render", "string_engine_render", "modal_render",
    "kick_render", "snare_render", "hihat_render", "vcf_render", "phase_dist_render", "six_op_render",
    "six_op_render", "six_op_render", "terrain_render", "string_machine_render", "square_render", "six_op_render",
]
E = 16572  # sizeof(PlaitsEngine) (plaits.c checks it)
V_OUT, V_AUX, V_ACCENT, V_MODEL, V_ARMED, V_RELEASED = E, E + 64, E + 144, E + 148, E + 152, E + 156
F_PITCH, F_TUNE, F_HARM, F_TIMBRE, F_MORPH, F_MIX, F_ACTIVE, F_RELEASED = 0, 1, 3, 4, 5, 6, 8, 9
SUB = 16
# locals below I6 (words): saved registers -3..-8, Params p at -14 (note .. accent), k[4] at -18
P_AT, K_AT = 14, 18
SAVES = ["R9", "R10", "R11", "R13", "R14", "R15"]
FRAME = 17  # I7 = I6 - 2 on entry; locals down to -18

HEADER = """\
// machines/plaits: the voice wrapper's per-block path (plaits.c plaits_render, render_engine, render_sub) at 48 kHz.
// Generated by lib/gen_wrap_kernel.py; do not edit by hand.
//
// int plaits_render(PlaitsVoice *v, const PlaitsFrame *f, int trig, float *out, int n, int rate): as the C
//   (plaits_render_c, -DPL_WRAP_C), which runs instead at any rate but 48000. selcc's calling convention; R9-R11 and
//   R13-R15 saved below I6 and restored. Bit-identical to selcc's code of the C (tests/plaits/test_wrap_kernel.py).
// Assembled under .COMPRESS; integer additions in their 48-bit form.

.SECTION/PM seg_pmco;
.GLOBAL plaits_render.;
.EXTERN plaits_render_c.;
.EXTERN plaits_note_on_c.;
.EXTERN plaits_stage_kernel.;
.EXTERN plaits_out_gain.;
.EXTERN plaits_aux_gain.;
.EXTERN plaits_gain.;
"""


class Asm:
    def __init__(self) -> None:
        self.lines: list[str] = []
        self.n = 0

    def __call__(self, text: str, comment: str = "") -> None:
        line = f"    {text};"
        self.lines.append(f"{line:<56}// {comment}" if comment else line)

    def label(self, name: str) -> None:
        self.lines.append(f"{name}:")

    def iadd(self, text: str, comment: str = "") -> None:
        self.lines += ["    .NOCOMPRESS;", f"    {text};" + (f"  // {comment}" if comment else ""), "    .COMPRESS;"]

    def local_addr(self, r: str, k: int) -> None:
        """R = the address of the local at I6 - k words (selcc's form)."""
        self(f"I6=MODIFY (I6,-{k})(NW)")
        self(f"{r} = I6")
        self(f"I6=MODIFY (I6,{k})(NW)")

    def cjump(self, target: str, pushes: list[str]) -> None:
        """A selcc call: stack arguments pushed (last argument first), CJUMP, the arguments popped."""
        self.n += 1
        ret = f"_plw_c{self.n}"
        for r in pushes:
            self(f"DM(I7, M7) = {r}")
        self("R2 = I6")
        self.lines += ["    .NOCOMPRESS;"]
        self(f"CJUMP {target} (DB)")
        self("DM(I7, M7) = R2")
        self(f"DM(I7, M7) = {ret} - 1")
        self.lines += ["    .COMPRESS;"]
        self.label(ret)
        if pushes:
            self(f"I7=MODIFY (I7,{len(pushes)})(NW)")


def unit(a: Asm, r: int, off: int, comment: str) -> None:
    """F{r} = unit(f[off]): x = word * PL_INV_FULL; if (x < 0) x = 0; else if (x > 1) x = 1 (selcc's comparisons)."""
    a(f"R{r} = DM({off}, I4)", comment)
    a(f"F{r} = F{r} * F5")
    a(f"COMP(F{r}, F7)", "selcc: x >= 1 is tested only when x >= 0")
    a(f"IF GT R{r} = R7 OR R7")
    a(f"COMP(F{r}, F6)")
    a(f"IF LT R{r} = R6 OR R6")


def tree(a: Asm, lo: int, hi: int) -> None:
    """Dispatch on R14 = model in [lo, hi) as render_sub's tree (the leaves are the engines)."""
    if hi - lo == 1:
        a.label(f"_plw_m{lo}")
        a("R4 = PASS R9", "the engine: &v->engine")
        a.local_addr("R8", P_AT)
        a(f"R0 = {V_AUX}")
        a.iadd("R0 = R9 + R0")
        a(f"R1 = {SUB}")
        a(f"R12 = {V_OUT}")
        a.iadd("R12 = R9 + R12")
        a.cjump(f"{ENGINES[lo]}.", ["R1", "R0"])
        a("JUMP _plw_post")
        return
    mid = {(0, 25): 10, (0, 10): 5, (0, 5): 2, (0, 2): 1, (2, 5): 3, (3, 5): 4, (5, 10): 7, (5, 7): 6, (7, 10): 8,
           (8, 10): 9, (10, 25): 15, (10, 15): 12, (10, 12): 11, (12, 15): 13, (13, 15): 14, (15, 25): 21,
           (15, 21): 16, (16, 21): 17, (17, 21): 18, (18, 21): 19, (19, 21): 20, (21, 25): 22, (22, 25): 23,
           (23, 25): 24}[(lo, hi)]
    a(f"R0 = {mid}")
    a("COMP(R14, R0)")
    a(f"IF GE JUMP _plw_t{mid}_{hi}")
    tree(a, lo, mid)
    a.label(f"_plw_t{mid}_{hi}")
    tree(a, mid, hi)


def kernel() -> str:
    a = Asm()
    a.label("plaits_render.")
    a("R0 = DM(3, I6)", "rate")
    a("R1 = 48000")
    a("COMP(R0, R1)")
    a("IF NE JUMP plaits_render_c.", "any other rate: the C, on this frame")
    a(f"I7=MODIFY (I7,-{FRAME})(NW)")
    for i, r in enumerate(SAVES):
        a(f"DM(-{3 + i}, I6) = {r}")
    a("R9 = PASS R4", "v")
    a("R10 = PASS R8", "f")
    a("R11 = PASS R12", "trig")
    a("R13 = DM(1, I6)", "out (= dst at 48 kHz)")
    a("R0 = 0")
    a("COMP(R11, R0)")
    a("IF EQ JUMP _plw_on", "if (trig) note_on(v, f, rate)")
    a("R12 = 48000")
    a.cjump("plaits_note_on_c.", [])
    a("R4 = PASS R9")
    a("R8 = PASS R10")
    a.label("_plw_on")
    a(f"R0 = {V_ARMED}")
    a.iadd("R0 = R9 + R0")
    a("I4 = R0")
    a("R3 = 0")
    a("R1 = 0", "(DAG gap)")
    a("R0 = DM(0, I4)", "armed")
    a("COMP(R0, R3)")
    a("IF EQ JUMP _plw_zero")
    a("I4 = R10")
    a("R1 = 0", "(DAG gap)")
    a("R2 = 0")
    a(f"R0 = DM({F_ACTIVE}, I4)", "f->active")
    a("COMP(R0, R3)")
    a("IF EQ JUMP _plw_zero")
    a(f"R0 = {V_MODEL}")
    a.iadd("R0 = R9 + R0")
    a("I4 = R0")
    a("R1 = 24")
    a("R0 = 0", "(DAG gap)")
    a("R14 = DM(0, I4)", "model")
    a("COMP(R14, R0)", "PL_PORTED: 0 <= model <= 24")
    a("IF LT JUMP _plw_zero")
    a("COMP(R14, R1)")
    a("IF GT JUMP _plw_zero")
    # render_engine: the DX7 gate latch
    a(f"R0 = {V_RELEASED}")
    a.iadd("R0 = R9 + R0")
    a("I4 = R0")
    a("R0 = 0")
    a("R1 = 1")
    a("COMP(R11, R0)", "if (trig) v->released = 0")
    a("IF EQ JUMP _plw_r0")
    a("DM(0, I4) = R0")
    a.label("_plw_r0")
    a("I4 = R10")
    a("R0 = 0")
    a("R2 = 0")
    a(f"R3 = DM({F_RELEASED}, I4)", "if (f->released != 0) v->released = 1")
    a("COMP(R3, R0)")
    a("IF EQ JUMP _plw_r1")
    a(f"R0 = {V_RELEASED}")
    a.iadd("R0 = R9 + R0")
    a("I4 = R0")
    a("R0 = 0", "(DAG gap)")
    a("R2 = 0")
    a("R3 = 0")
    a("DM(0, I4) = R1")
    a("I4 = R10")
    a("R0 = 0", "(DAG gap)")
    a("R2 = 0")
    a("R3 = 0")
    a.label("_plw_r1")
    # Params
    a(f"R0 = DM({F_PITCH}, I4)", "p.note = f->pitch / 256 + (f->tune / 256 - 64)")
    a("R1 = 0x3B800000")
    a("F0 = F0 * F1")
    a(f"R2 = DM({F_TUNE}, I4)")
    a("F2 = F2 * F1")
    a("R1 = 0x42800000")
    a("F2 = F2 - F1")
    a("F0 = F0 + F2")
    a(f"DM(-{P_AT}, I6) = R0")
    a("R5 = 0x38010204", "PL_INV_FULL")
    a("R6 = 0")
    a("R7 = 0x3F800000")
    unit(a, 0, F_HARM, "p.harmonics")
    a(f"DM(-{P_AT - 1}, I6) = R0")
    unit(a, 0, F_TIMBRE, "p.timbre")
    a(f"DM(-{P_AT - 2}, I6) = R0")
    unit(a, 0, F_MORPH, "p.morph")
    a(f"DM(-{P_AT - 3}, I6) = R0")
    unit(a, 0, F_MIX, "mix = k[2]")
    a(f"DM(-{K_AT - 2}, I6) = R0")
    a(f"R0 = {V_ACCENT}")
    a.iadd("R0 = R9 + R0")
    a("I4 = R0")
    a("R1 = plaits_out_gain.")
    a("R2 = LSHIFT R14 BY 2")
    a.iadd("R1 = R1 + R2")
    a("R0 = DM(0, I4)", "p.accent = v->accent")
    a(f"DM(-{P_AT - 5}, I6) = R0")
    a("I4 = R1")
    a("R1 = plaits_aux_gain.")
    a.iadd("R1 = R1 + R2")
    a("R0 = DM(plaits_gain.)", "k[3]")
    a(f"DM(-{K_AT - 3}, I6) = R0")
    a("R0 = DM(0, I4)", "k[0] = plaits_out_gain[model]")
    a(f"DM(-{K_AT}, I6) = R0")
    a("I4 = R1")
    a("R15 = 0", "s")
    a("R0 = 0", "(DAG gap)")
    a("R0 = DM(0, I4)", "k[1] = plaits_aux_gain[model]")
    a(f"DM(-{K_AT - 1}, I6) = R0")
    # the sub-blocks
    a.label("_plw_sub")
    a("R0 = 0")
    a("R1 = 4", "p.trigger = (trig && s == 0) ? RISING_HIGH : HIGH")
    a("R2 = 5")
    a("COMP(R11, R0)")
    a("IF EQ JUMP _plw_t0")
    a("COMP(R15, R0)")
    a("IF EQ R1 = R2 OR R2")
    a.label("_plw_t0")
    a("R3 = 8")
    a("COMP(R14, R3)", "SWARM: TRIG_UNPATCHED")
    a("IF NE JUMP _plw_t1")
    a("R1 = 2")
    a("JUMP _plw_t3")
    a.label("_plw_t1")
    a("R3 = 18", "DX7 (18..20, 24): LOW after a note-off")
    a("COMP(R14, R3)")
    a("IF LT JUMP _plw_t2")
    a("R3 = 20")
    a("COMP(R14, R3)")
    a("IF LE JUMP _plw_dx")
    a.label("_plw_t2")
    a("R3 = 24")
    a("COMP(R14, R3)")
    a("IF NE JUMP _plw_t3")
    a.label("_plw_dx")
    a("R3 = 5")
    a("COMP(R1, R3)")
    a("IF EQ JUMP _plw_t3")
    a(f"R3 = {V_RELEASED}")
    a.iadd("R3 = R9 + R3")
    a("I4 = R3")
    a("R0 = 0", "(DAG gap)")
    a("R2 = 0")
    a("R3 = 0")
    a("R2 = DM(0, I4)")
    a("COMP(R2, R0)")
    a("IF NE R1 = R0 OR R0")
    a.label("_plw_t3")
    a(f"DM(-{P_AT - 4}, I6) = R1")
    tree(a, 0, 25)
    a.label("_plw_post")
    a(f"R4 = {V_OUT}", "plaits_stage_kernel(v->out, dst + s, k)")
    a.iadd("R4 = R9 + R4")
    a("R8 = LSHIFT R15 BY 2")
    a.iadd("R8 = R13 + R8")
    a.local_addr("R12", K_AT)
    a.cjump("plaits_stage_kernel.", [])
    a(f"R0 = {SUB}")
    a.iadd("R15 = R15 + R0")
    a("R0 = 32")
    a("COMP(R15, R0)")
    a("IF LT JUMP _plw_sub")
    a("R0 = 1", "return 1")
    a.label("_plw_ret")
    for i, r in enumerate(SAVES):
        a(f"{r} = DM(-{3 + i}, I6)")
    a("I12 = DM(M7, I6)")
    a("JUMP (M14, I12) (DB)")
    a("RFRAME")
    a("NOP")
    a.label("_plw_zero")
    a("R4 = DM(2, I6)", "zeros(out, n); return 0")
    a("I4 = R13")
    a("R0 = 0")
    a("COMP(R4, R0)")
    a("IF LE JUMP _plw_ret")
    a("LCNTR = R4, DO _plw_z UNTIL LCE")
    a("DM(I4, M5) = R0")
    a.label("_plw_z")
    a("I4=MODIFY (I4,1)(NW)")
    a("JUMP _plw_ret")
    return "\n".join(a.lines) + "\n"


def main() -> None:
    OUT.write_text(HEADER + "\n.COMPRESS;\n" + kernel())
    print(OUT)


if __name__ == "__main__":
    main()
