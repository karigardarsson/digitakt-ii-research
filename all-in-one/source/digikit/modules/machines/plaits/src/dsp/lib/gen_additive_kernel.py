"""Generate lib/additive_sm.s: ADDITIVE's harmonic oscillator sample loop (engines/additive.c, harmonic_render) as a
SISD kernel, bit-identical to selcc's code of the C loop (-DPL_ADD_C).

    python3 modules/machines/plaits/src/dsp/lib/gen_additive_kernel.py

Every float operation is the C's, with the same operands in the same order (commutative swaps only); the twelve
harmonics are unrolled (the Chebyshev recurrence alternates two registers), SineNoWrap and Sine (InterpolateWrap with
itof_nonneg) are written out, and the phase wrap is a compare and a conditional move.
tests/plaits/test_additive_kernel.py checks it against the C on the concrete core.
"""

from __future__ import annotations

from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE / "additive_sm.s"
N = 12
INC, KK, KM = (
    7,
    19,
    20,
)  # frame slots above I7: the twelve amplitude increments, k, k - 1
FRAME = 20
ONE, HALF, TWO, BIAS, F512, QUARTER = (
    "0x3F800000",
    "0x3F000000",
    "0x40000000",
    "0x4B000000",
    "0x44000000",
    "0x3E800000",
)

HEADER = """\
// machines/plaits: ADDITIVE's harmonic oscillator sample loop (engines/additive.c, harmonic_render), SISD kernel.
// Generated by lib/gen_additive_kernel.py; do not edit by hand.
//
// harmonic_kernel(Harmonic *s, const float *amplitudes, float *out, int size, int first_harmonic_index,
//                 const float *lut_sine, float frequency):
//   s = the oscillator (phase_, frequency_, amplitude_[12]: the interpolators' values); frequency already clamped to
//   0.5. The prologue computes the thirteen interpolators' increments as the C does (f = frequency *
//   itof_nonneg(first + i) clamped to 0.5, target amplitudes[i] * (1 - 2 f), (target - value) / itof_nonneg(size)),
//   running selcc's division with the divisor's reciprocal (RECIPS and two Newton steps, which depend on the divisor
//   only) computed once. Then writes (first index 1) or adds to (otherwise) `size` samples of out and writes the
//   state back (the values are the interpolators' commits), bit-identical to selcc's code of the C (-DPL_ADD_C;
//   tests/plaits/test_additive_kernel.py).
//
// State on return: R0-R8, R12, I4 and the flags change; every other register is as on entry (R9-R11, R13-R15 saved
// above I7; I0, I1, I5, M6, L0, L1, L4, L5 pushed through R0, M6 = 1 and L0 = L1 = L4 = L5 = 0 set here). No SIMD.
// Registers in the loop: R15 phase, R14 frequency value, R13 its increment, R12 two_x, R11 sum, R10 / R9 current /
// previous (alternating), R8 2 x current; I1 = s, I0 = out, I5 the table row; the amplitude increments, k and k - 1
// in frame slots above I7 (INC.., KK, KM).
//
// ABI: as the other kernels (lib/wavetable_sm.s): relies on M5 = 0 and M7 = -1, sets M6 = 1 itself; DAG registers
// are pushed through R0 and restored by loads through I7.

//
// amp_kernel(float *amplitudes, const int *harmonic_indices, int num_harmonics, float center, float slope,
//            float bumps, const float *lut_sine): amplitudes_update's two loops after its prologue (the C computes
//   center): per harmonic the gain (|d| slope, 1 - order made non-negative, squared, times 1 + Sine(0.25 + order
//   bumps), squared twice), ONE_POLE(amplitudes[j], gain, 0.001f) and the sum from 0.001f; then sum = 1.0f / sum by
//   selcc's division and amplitudes[j] *= sum. Changes R0-R8, R12, I4 and the flags; restores the rest (I1, I5, M4,
//   M6, L1, L4, L5 pushed through R0; R9-R11, R13-R15 saved above I7). amplitudes[j] through DM(M4, I1)
//   (pre-modify, the word index scaled by the byte-space access size as in the C ABI's DM(M7, I6)).

.SECTION/PM seg_pmco;
.GLOBAL harmonic_kernel.;
.GLOBAL amp_kernel.;
.COMPRESS;
"""


class Asm:
    def __init__(self) -> None:
        self.lines: list[str] = []

    def __call__(self, text: str, comment: str = "") -> None:
        line = f"    {text};"
        if comment:
            line = f"{line:<56}// {comment}"
        self.lines.append(line)

    def label(self, name: str) -> None:
        self.lines.append(f"{name}:")

    def raw(self, text: str) -> None:
        self.lines.append(text)


def phase(a: Asm) -> None:
    """fm.value += fm.increment; phase_ += fm.value; if (phase_ >= 1.0f) phase_ -= 1.0f."""
    a("F14 = F14 + F13", "fm.Next()")
    a("F15 = F15 + F14", "phase_ += fm.value")
    a(f"R0 = {ONE}")
    a("F1 = F15 - F0")
    a("COMP(F15, F0)", "phase_ >= 1.0f: phase_ -= 1.0f")
    a("IF GE R15 = R1 OR R1")


def sine_nowrap(a: Asm) -> None:
    """R12 = two_x = 2.0f * SineNoWrap(phase_) (Interpolate(lut_sine, phase_, 512))."""
    a(f"R0 = {F512}")
    a("F0 = F15 * F0", "index = phase_ * 512.0f")
    a("R1 = TRUNC F0", "index_integral")
    a(f"R2 = {BIAS}")
    a("R3 = R2 OR R1", "itof_nonneg")
    a("F3 = F3 - F2")
    a("F0 = F0 - F3", "index_fractional")
    a("R1 = LSHIFT R1 BY 2")
    a("R4 = DM(3, I6)", "lut_sine (the sixth argument)")
    a("R1 = R1 + R4")
    a("I5 = R1")
    a(f"R12 = {TWO}")
    a("R1 = DM(I5, M5)", "a")
    a("R3 = DM(1, I5)", "sine[index_integral + 1]")
    a("F3 = F3 - F1", "a + (b - a) * index_fractional")
    a("F3 = F3 * F0")
    a("F3 = F1 + F3")
    a("F12 = F12 * F3", "two_x = 2.0f * ..")


def sine_wrap(a: Asm, res: str, x: str) -> None:
    """res = Sine(x) = InterpolateWrap(lut_sine, x, 512); x is F0 or F5 and is destroyed; uses R1-R4."""
    a(f"R2 = {BIAS}")
    a(f"R1 = TRUNC {x}", "InterpolateWrap: index -= itof_nonneg((int)index)")
    a("R1 = R2 OR R1")
    a("F1 = F1 - F2")
    a(f"{x} = {x} - F1")
    a(f"R1 = {F512}")
    a(f"{x} = {x} * F1", "index *= 512.0f")
    a(f"R1 = TRUNC {x}", "index_integral")
    a("R3 = R2 OR R1")
    a("F3 = F3 - F2")
    a(f"F3 = {x} - F3", "index_fractional")
    a("R1 = LSHIFT R1 BY 2")
    a("R4 = DM(3, I6)")
    a("R1 = R1 + R4")
    a("I5 = R1")
    a("R1 = DM(I5, M5)")
    a("R4 = DM(1, I5)")
    a("F4 = F4 - F1")
    a("F4 = F4 * F3")
    a(f"{res} = F1 + F4")


def harmonics(a: Asm) -> None:
    """The twelve harmonics: v = value + increment (stored), sum += v * current, current = two_x * current - previous."""
    a("R11 = 0", "sum = 0.0f")
    c, p = "10", "9"
    for h in range(N):
        a(f"R0 = DM({2 + h}, I1)", f"harmonic {h}")
        a(f"R1 = DM({INC + h}, I7)")
        a(f"F8 = F12 * F{c}", "two_x * current")
        a("F0 = F0 + F1", "am[i].Next()")
        a(f"F{p} = F8 - F{p}", "- previous: the new current")
        a(f"F1 = F0 * F{c}", "v * current")
        a(f"DM({2 + h}, I1) = R0")
        a("F11 = F11 + F1", "sum += ..")
        c, p = p, c


def kernel() -> str:
    a = Asm()
    a.label("harmonic_kernel.")
    dags = ["I0", "I1", "I5", "M6", "L0", "L1", "L4", "L5"]
    for r in dags:
        a(f"R0 = {r}")
        a("DM(I7, M7) = R0")
    a("M6 = 1")
    for r in ("L0", "L1", "L4", "L5"):
        a(f"{r} = 0")
    saves = ["R9", "R10", "R11", "R13", "R14", "R15"]
    a(f"I7=MODIFY (I7,-{FRAME})(NW)")
    for i, r in enumerate(saves):
        a(f"DM({i + 1}, I7) = {r}")
    a("I1 = R4", "s")
    a("I4 = R8", "amplitudes")
    a("I0 = R12", "out")
    a("R15 = DM(0, I1)", "phase_")
    a("R14 = DM(1, I1)", "frequency_ (fm.value)")
    a("R8 = DM(1, I6)", "size")
    a("R0 = 0")
    a("COMP(R8, R0)")
    a("IF LE JUMP _hk_done")
    # the divisor itof_nonneg(size) and its reciprocal after selcc's two Newton steps
    a(f"R2 = {BIAS}")
    a("R9 = R2 OR R8", "d = itof_nonneg(size)")
    a("F9 = F9 - F2")
    a(f"R3 = {TWO}")
    a.raw(".COMPRESS;")
    a("F10 = RECIPS F9", "y")
    a.raw(".COMPRESS;")
    a("F0 = F9 * F10", "t = d y; t = 2 - t; y = y t (twice)")
    a("F0 = F3 - F0")
    a("F10 = F10 * F0")
    a("F0 = F9 * F10")
    a("F0 = F3 - F0")
    a("F10 = F10 * F0")
    a("R4 = DM(4, I6)", "frequency")
    a("R5 = DM(1, I1)")
    a("F5 = F4 - F5", "frequency - frequency_")
    a("F0 = F5 * F10", "selcc division: w = n y")
    a("F1 = F9 * F0", "t = d w")
    a("F1 = F5 - F1", "t = n - t")
    a("F1 = F1 * F10", "t = t y")
    a("F13 = F0 + F1", "fm.increment")
    a("R11 = DM(2, I6)", "first_harmonic_index")
    a("R0 = R2 OR R11", "k = itof_nonneg(first_harmonic_index)")
    a("F0 = F0 - F2")
    a(f"DM({KK}, I7) = R0")
    a(f"R1 = {ONE}")
    a("F0 = F0 - F1", "k - 1.0f")
    a(f"DM({KM}, I7) = R0")
    a(f"R12 = {HALF}")
    a("R6 = 1")
    for h in range(N):
        a("R0 = R2 OR R11", f"am[{h}]: f = frequency * itof_nonneg(first + {h})")
        a("F0 = F0 - F2")
        a("F0 = F4 * F0")
        a("COMP(F0, F12)", "f >= 0.5f: f = 0.5f")
        a("IF GE R0 = R12 OR R12")
        a("F0 = F0 * F3", "1.0f - f * 2.0f")
        a("F0 = F1 - F0")
        a(f"R5 = DM({h}, I4)", "amplitudes[i] * ..")
        a("F0 = F5 * F0")
        a(f"R5 = DM({2 + h}, I1)", "target - value")
        a("F5 = F0 - F5")
        a("F0 = F5 * F10", "selcc division: w = n y")
        a("F7 = F9 * F0", "t = d w")
        a("F7 = F5 - F7", "t = n - t")
        a("F7 = F7 * F10", "t = t y")
        a("F0 = F0 + F7")
        a(f"DM({INC + h}, I7) = R0")
        a("R11 = R11 + R6")
    a("R1 = DM(2, I6)", "first_harmonic_index")
    a("R2 = 1")
    a("COMP(R1, R2)")
    a("IF NE JUMP _hk_upper")
    a("LCNTR = R8, DO _hk_e1 UNTIL LCE")
    phase(a)
    sine_nowrap(a)
    a(f"R9 = {ONE}", "previous = 1.0f")
    a(f"R0 = {HALF}")
    a("F10 = F12 * F0", "current = two_x * 0.5f")
    harmonics(a)
    a.label("_hk_e1")
    a("DM(I0, M6) = R11", "*out++ = sum")
    a("JUMP _hk_done")
    a.label("_hk_upper")
    a("LCNTR = R8, DO _hk_e2 UNTIL LCE")
    phase(a)
    sine_nowrap(a)
    a(f"R0 = DM({KM}, I7)", "k - 1.0f")
    a("F0 = F15 * F0", "phase_ * (k - 1.0f)")
    a(f"R1 = {QUARTER}")
    a("F0 = F0 + F1", "+ 0.25f")
    sine_wrap(a, "F9", "F0")
    a(f"R5 = DM({KK}, I7)", "k")
    a("F5 = F15 * F5", "phase_ * k")
    sine_wrap(a, "F10", "F5")
    harmonics(a)
    a("R0 = DM(I0, M5)")
    a("F0 = F0 + F11", "*out++ += sum")
    a.label("_hk_e2")
    a("DM(I0, M6) = R0")
    a.label("_hk_done")
    a("DM(0, I1) = R15")
    a("DM(1, I1) = R14")
    for i, r in enumerate(saves):
        a(f"{r} = DM({i + 1}, I7)")
    a(f"I7=MODIFY (I7,{FRAME})(NW)")
    for i, r in enumerate(reversed(dags)):
        a(f"{r} = DM({i + 1}, I7)")
    a.raw(".COMPRESS;")
    a("I12 = DM(M7, I6)")
    a("JUMP (M14, I12) (DB)")
    a("RFRAME")
    a.raw(".COMPRESS;")
    return HEADER + "\n" + "\n".join(a.lines) + "\n"


def amp_kernel() -> str:
    a = Asm()
    a.label("amp_kernel.")
    dags = ["I1", "I5", "M4", "M6", "L1", "L4", "L5"]
    for r in dags:
        a(f"R0 = {r}")
        a("DM(I7, M7) = R0")
    a("M6 = 1")
    for r in ("L1", "L4", "L5"):
        a(f"{r} = 0")
    saves = ["R9", "R10", "R11", "R13", "R14", "R15"]
    a(f"I7=MODIFY (I7,-{len(saves) + 2})(NW)")
    for i, r in enumerate(saves):
        a(f"DM({i + 1}, I7) = {r}")
    a(f"DM({len(saves) + 1}, I7) = R8", "harmonic_indices")
    a(f"DM({len(saves) + 2}, I7) = R12", "num_harmonics")
    a("I1 = R4", "amplitudes")
    a("I4 = R8", "harmonic_indices")
    a("R15 = DM(1, I6)", "center")
    a("R14 = DM(2, I6)", "slope")
    a("R13 = DM(3, I6)", "bumps")
    a("R10 = DM(4, I6)", "lut_sine")
    a("R11 = 0x3A83126F", "sum = 0.001f")
    a("R9 = 0", "i")
    a("COMP(R12, R9)")
    a("IF LE JUMP _ak_done")
    a("R3 = PASS R12")
    a(f"R12 = {BIAS}")
    a("LCNTR = R3, DO _ak_e1 UNTIL LCE")
    a("R0 = DM(I4, M6)", "j = harmonic_indices[i]")
    a("M4 = R0")
    a("R0 = R12 OR R9", "d = itof_nonneg(i) - center")
    a("F0 = F0 - F12")
    a("F0 = F0 - F15")
    a("F1 = -F0")
    a("R2 = 0")
    a("COMP(F0, F2)", "(d < 0.0f ? -d : d)")
    a("IF LT R0 = R1 OR R1")
    a("F0 = F0 * F14", "order = .. * slope")
    a(f"R3 = {ONE}")
    a("F1 = F3 - F0", "gain = 1.0f - order")
    a("F4 = -F1")
    a("COMP(F1, F2)", "gain += gain < 0.0f ? -gain : gain")
    a("IF GE R4 = R1 OR R1")
    a("F1 = F1 + F4")
    a("F1 = F1 * F1", "gain *= gain")
    a("F6 = F0 * F13", "b = 0.25f + order * bumps")
    a(f"R7 = {QUARTER}")
    a("F6 = F7 + F6")
    a("R7 = TRUNC F6", "Sine(b): InterpolateWrap, index -= itof_nonneg((int)index)")
    a("R7 = R12 OR R7")
    a("F7 = F7 - F12")
    a("F6 = F6 - F7")
    a(f"R7 = {F512}")
    a("F6 = F6 * F7", "index *= 512.0f")
    a("R7 = TRUNC F6", "index_integral")
    a("R8 = R12 OR R7")
    a("R7 = LSHIFT R7 BY 2")
    a("R7 = R7 + R10")
    a("I5 = R7")
    a("F8 = F8 - F12")
    a("F8 = F6 - F8", "index_fractional")
    a("R0 = 1")
    a("R9 = R9 + R0", "++i")
    a("R2 = 0x3A83126F", "0.001f")
    a("R5 = DM(I5, M5)", "a")
    a("R6 = DM(1, I5)", "b")
    a("F6 = F6 - F5", "a + (b - a) * index_fractional")
    a("F6 = F6 * F8")
    a("F5 = F5 + F6")
    a("F5 = F3 + F5", "bump_factor = 1.0f + Sine(b)")
    a("F1 = F1 * F5", "gain *= bump_factor")
    a("F1 = F1 * F1", "gain *= gain")
    a("F1 = F1 * F1", "gain *= gain")
    a("R5 = DM(M4, I1)", "ONE_POLE(amplitudes[j], gain, 0.001f)")
    a("F6 = F1 - F5")
    a("F6 = F2 * F6")
    a("F5 = F5 + F6")
    a("DM(M4, I1) = R5")
    a.label("_ak_e1")
    a("F11 = F11 + F5", "sum += amplitudes[j]")
    a(f"R0 = {ONE}", "sum = 1.0f / sum (selcc division)")
    a(f"R4 = {TWO}")
    a("F1 = RECIPS F11")
    a("F2 = F11 * F1")
    a("F2 = F4 - F2")
    a("F1 = F1 * F2")
    a("F2 = F11 * F1")
    a("F2 = F4 - F2")
    a("F1 = F1 * F2")
    a("F4 = F0 * F1")
    a("F2 = F11 * F4")
    a("F2 = F0 - F2")
    a("F2 = F2 * F1")
    a("F11 = F4 + F2")
    a(f"R0 = DM({len(saves) + 1}, I7)")
    a("I4 = R0")
    a(f"R3 = DM({len(saves) + 2}, I7)")
    a("LCNTR = R3, DO _ak_e2 UNTIL LCE")
    a("R0 = DM(I4, M6)", "amplitudes[harmonic_indices[i]] *= sum")
    a("M4 = R0")
    a("R0 = DM(M4, I1)")
    a("F0 = F0 * F11")
    a.label("_ak_e2")
    a("DM(M4, I1) = R0")
    a.label("_ak_done")
    for i, r in enumerate(saves):
        a(f"{r} = DM({i + 1}, I7)")
    a(f"I7=MODIFY (I7,{len(saves) + 2})(NW)")
    for i, r in enumerate(reversed(dags)):
        a(f"{r} = DM({i + 1}, I7)")
    a("I12 = DM(M7, I6)")
    a("JUMP (M14, I12) (DB)")
    a("RFRAME")
    a("NOP")
    return "\n" + "\n".join(a.lines) + "\n"


def main() -> None:
    OUT.write_text(kernel() + amp_kernel())
    print(OUT)


if __name__ == "__main__":
    main()
