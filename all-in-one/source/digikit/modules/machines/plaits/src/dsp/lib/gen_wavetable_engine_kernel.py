"""Generate lib/wavetable_engine_sm.s: WAVETABLE's sample loop (engines/wavetable.c, wavetable_render: the three
smoothed coordinates, the eight Hermite wave reads, the trilinear mix, the differentiator and the AUX quantiser) as a
SISD kernel, bit-identical to selcc's code of the C loop (-DPL_WAVETABLE_C).

    python3 modules/machines/plaits/src/dsp/lib/gen_wavetable_engine_kernel.py

Every operation is the C's, with the same operands in the same order (commutative swaps only); minf, itof_nonneg,
itof_small, InterpolateWaveHermite and selcc's divisions (1 / (f * 131072) per sample; the AUX quantiser's division by
the constant 32.0f with its reciprocal's two Newton steps made once) are written out.
tests/plaits/test_wavetable_engine_kernel.py checks it against the C on the concrete core.
"""

from __future__ import annotations

from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE / "wavetable_engine_sm.s"
C = {
    "one": "0x3F800000",
    "half": "0x3F000000",
    "two": "0x40000000",
    "131072": "0x48000000",
    "0.95": "0x3F733333",
    "128": "0x43000000",
    "32": "0x42000000",
    "1.5x2^23": "0x4B400000",
    "bias": "0x4B000000",
}

HEADER = """\
// machines/plaits: WAVETABLE's sample loop (engines/wavetable.c, wavetable_render), hand-written SISD kernel.
// Generated by lib/gen_wavetable_engine_kernel.py; do not edit by hand.
//
// wavetable_engine_kernel(Wavetable *s, const float *k, float *out, float *aux, int size): k[0..3] = the increments of
//   previous_x_, previous_y_, previous_z_, previous_f0_; k[4] = lp_coefficient. Writes out and aux and the state
//   back (phase_, the three _lp_, the four interpolators, diff_out_), bit-identical to selcc's code of the C loop
//   (-DPL_WAVETABLE_C) (tests/plaits/test_wavetable_engine_kernel.py).
//
// State on return: R0-R8, R12, I4 and the flags change; every other register is as on entry (R9-R11, R13-R15 saved
// above I7; I0, I1, I2, M6, L0, L1, L2, L4 pushed through R0, M6 = 1 and L0 = L1 = L2 = L4 = 0 set here). No SIMD.
// ABI: as the other kernels (lib/wavetable_sm.s). Assembled under .COMPRESS; integer additions in their 48-bit form.

.SECTION/PM seg_pmco;
.GLOBAL wavetable_engine_kernel.;
.EXTERN pl_wav_integrated_waves.;
.EXTERN pl_wavetable_map.;
.COMPRESS;
"""
DAGS = ["I0", "I1", "I2", "M6", "L0", "L1", "L2", "L4"]
SAVES = ["R9", "R10", "R11", "R13", "R14", "R15"]
KX, KY, KZ, KF, LPC, CNT, Y32, GAIN, CUT, XF, YF, ZF, PI, X0, Y0, Z0, Z1, X1, Y1 = (
    range(7, 26)
)
V = {
    n: s
    for n, s in zip(
        ("000", "100", "010", "110", "001", "101", "011", "111"),
        range(26, 34),
        strict=False,
    )
}
FRAME = 33


def kernel() -> str:
    L: list[str] = []

    def a(t: str, c: str = "") -> None:
        line = f"    {t};"
        L.append(f"{line:<56}// {c}" if c else line)

    def lab(n: str) -> None:
        L.append(f"{n}:")

    def iadd(t: str, c: str = "") -> None:
        L.append("    .NOCOMPRESS;")
        a(t, c)
        L.append("    .COMPRESS;")

    def k(r: str, n: str) -> None:
        a(f"{r} = {C[n]}", n)

    def slot(r: str, s: int, c: str = "") -> None:
        a(f"{r} = DM({s}, I7)", c)

    def put(s: int, r: str, c: str = "") -> None:
        a(f"DM({s}, I7) = {r}", c)

    def read_wave(dst: str, xs: int, ys: int, zs: int) -> None:
        """slot dst = InterpolateWaveHermite(wave_map_[x + y * 8 + z * 64], p_integral, F12 = p_fractional); the
        coordinates from their slots; uses R0-R8."""
        slot("R0", xs)
        slot("R1", ys)
        slot("R2", zs)
        a("R1 = LSHIFT R1 BY 3", "index = x + y * 8 + z * 64")
        a("R2 = LSHIFT R2 BY 6")
        iadd("R0 = R0 + R1")
        iadd("R0 = R0 + R2")
        a("R0 = LSHIFT R0 BY 2")
        iadd("R0 = R0 + R14")
        a("I4 = R0")
        slot("R2", PI)
        a("R3 = 0", "(DAG gap)")
        a("R4 = 0")
        a("R1 = DM(I4, M5)", "wave_map_[index]")
        iadd("R1 = R1 + R2", "+ p_integral")
        a("R1 = LSHIFT R1 BY 2")
        iadd("R1 = R1 + R15")
        a("I4 = R1")
        k("R8", "half")
        a("R3 = 0", "(DAG gap)")
        a("R4 = 0")
        a("R4 = DM(I4, M5)", "xm1")
        a("R5 = DM(1, I4)", "x0")
        a("R6 = DM(2, I4)", "x1")
        a("R7 = DM(3, I4)", "x2")
        a("F0 = F6 - F4", "c = (x1 - xm1) * 0.5f")
        a("F0 = F0 * F8")
        a("F1 = F5 - F6", "v = x0 - x1")
        a("F2 = F0 + F1", "w = c + v")
        a("F3 = F7 - F5", "a = w + v + (x2 - x0) * 0.5f")
        a("F3 = F3 * F8")
        a("F4 = F2 + F1")
        a("F3 = F4 + F3")
        a("F2 = F2 + F3", "b_neg = w + a")
        a("F3 = F3 * F12", "(((a * pf) - b_neg) * pf + c) * pf + x0")
        a("F3 = F3 - F2")
        a("F3 = F3 * F12")
        a("F3 = F3 + F0")
        a("F3 = F3 * F12")
        a("F3 = F3 + F5")
        put(V[dst], "R3")

    def lerp(dst: int, lo: int, hi: int, frac: str) -> None:
        a(f"F{dst} = F{hi} - F{lo}")
        a(f"F{dst} = F{dst} * {frac}")
        a(f"F{dst} = F{lo} + F{dst}")

    lab("wavetable_engine_kernel.")
    for r in DAGS:
        a(f"R0 = {r}")
        a("DM(I7, M7) = R0")
    a("M6 = 1")
    for r in DAGS[4:]:
        a(f"{r} = 0")
    a(f"I7=MODIFY (I7,-{FRAME})(NW)")
    for i, r in enumerate(SAVES):
        put(i + 1, r)
    a("I2 = R4", "s")
    a("I4 = R8", "k")
    a("I0 = R12", "out")
    a("R0 = DM(1, I6)", "aux")
    a("I1 = R0")
    for j, sl in enumerate((KX, KY, KZ, KF, LPC)):
        a(f"R0 = DM({j}, I4)")
        put(sl, "R0")
    a("R0 = DM(2, I6)", "size")
    put(CNT, "R0")
    k("R1", "32")
    k("R2", "two")
    a("F3 = RECIPS F1", "selcc's reciprocal of 32.0f after its two Newton steps")
    a("F4 = F1 * F3")
    a("F4 = F2 - F4")
    a("F3 = F3 * F4")
    a("F4 = F1 * F3")
    a("F4 = F2 - F4")
    a("F3 = F3 * F4")
    put(Y32, "R3")
    a("R15 = pl_wav_integrated_waves.")
    a("R14 = pl_wavetable_map.")
    k("R13", "bias")
    a("R11 = DM(11, I2)", "d_lp")
    a("R10 = DM(12, I2)", "d_previous")
    a("R1 = 0")
    a("COMP(R0, R1)")
    a("IF LE JUMP _wek_done")
    lab("_wek_loop")
    a("R9 = DM(10, I2)")
    slot("R0", KF)
    a("F9 = F9 + F0", "f = f0_modulation.Next()")
    a("DM(10, I2) = R9")
    k("R1", "131072")
    a("F1 = F9 * F1", "gain = (1.0f / (f * 131072.0f)) * (0.95f - f)")
    k("R2", "one")
    k("R3", "two")
    a("F4 = RECIPS F1")
    a("F5 = F1 * F4")
    a("F5 = F3 - F5")
    a("F4 = F4 * F5")
    a("F5 = F1 * F4")
    a("F5 = F3 - F5")
    a("F4 = F4 * F5")
    a("F3 = F2 * F4")
    a("F5 = F1 * F3")
    a("F5 = F2 - F5")
    a("F5 = F5 * F4")
    a("F3 = F3 + F5")
    k("R1", "0.95")
    a("F1 = F1 - F9")
    a("F3 = F3 * F1")
    put(GAIN, "R3")
    k("R1", "128")
    a("F1 = F1 * F9", "cutoff = minf(128.0f * f, 1.0f)")
    a("COMP(F1, F2)")
    a("IF GE R1 = R2 OR R2")
    put(CUT, "R1")
    slot("R8", LPC)
    for word, inc_slot, lp_word, isl, fsl in (
        (7, KX, 4, X0, XF),
        (8, KY, 5, Y0, YF),
        (9, KZ, 6, Z0, ZF),
    ):
        a(f"R0 = DM({word}, I2)")
        slot("R1", inc_slot)
        a("F0 = F0 + F1", "the coordinate's Next()")
        a(f"DM({word}, I2) = R0")
        a(f"R1 = DM({lp_word}, I2)")
        a("F0 = F0 - F1", "ONE_POLE(_lp_, value, lp_coefficient)")
        a("F0 = F8 * F0")
        a("F1 = F1 + F0")
        a(f"DM({lp_word}, I2) = R1")
        a("R2 = TRUNC F1", "_integral = (int)_lp_")
        put(isl, "R2")
        a("R3 = R13 OR R2")
        a("F3 = F3 - F13")
        a("F1 = F1 - F3", "_fractional")
        put(fsl, "R1")
    a("R0 = DM(0, I2)")
    a("F0 = F0 + F9", "phase_ += f")
    k("R1", "one")
    a("COMP(F0, F1)", "phase_ >= 1.0f")
    a("IF LT JUMP _wek_ph")
    a("F0 = F0 - F1")
    lab("_wek_ph")
    a("DM(0, I2) = R0")
    k("R1", "128")
    a("F0 = F0 * F1", "ph = phase_ * 128.0f")
    a("R2 = TRUNC F0", "p_integral")
    put(PI, "R2")
    a("R3 = R13 OR R2")
    a("F3 = F3 - F13")
    a("F12 = F0 - F3", "p_fractional")
    # z0, z1 = z_integral, z_integral + 1, each folded at 4: 7 - z
    slot("R0", Z0)
    a("R1 = 1")
    iadd("R1 = R0 + R1", "z1 = z_integral + 1")
    a("R2 = 4")
    a("R3 = 7")
    a("COMP(R0, R2)", "z0 >= 4: z0 = 7 - z0")
    a("IF LT JUMP _wek_z0")
    iadd("R0 = R3 - R0")
    lab("_wek_z0")
    a("COMP(R1, R2)", "z1 >= 4: z1 = 7 - z1")
    a("IF LT JUMP _wek_z1")
    iadd("R1 = R3 - R1")
    lab("_wek_z1")
    put(Z0, "R0")
    put(Z1, "R1")
    slot("R0", X0)
    a("R1 = 1")
    iadd("R0 = R0 + R1", "x1 = x_integral + 1")
    put(X1, "R0")
    slot("R0", Y0)
    iadd("R0 = R0 + R1", "y1 = y_integral + 1")
    put(Y1, "R0")
    read_wave("000", X0, Y0, Z0)
    read_wave("100", X1, Y0, Z0)
    read_wave("010", X0, Y1, Z0)
    read_wave("110", X1, Y1, Z0)
    read_wave("001", X0, Y0, Z1)
    read_wave("101", X1, Y0, Z1)
    read_wave("011", X0, Y1, Z1)
    read_wave("111", X1, Y1, Z1)
    slot("R8", XF)
    for lo, hi, dst in (
        ("000", "100", "000"),
        ("010", "110", "010"),
        ("001", "101", "001"),
        ("011", "111", "011"),
    ):
        slot("R0", V[lo])
        slot("R1", V[hi])
        lerp(2, 0, 1, "F8")
        put(V[dst], "R2", f"xy{lo[1]}z{lo[2]}")
    slot("R8", YF)
    slot("R0", V["000"])
    slot("R1", V["010"])
    lerp(4, 0, 1, "F8")
    slot("R0", V["001"])
    slot("R1", V["011"])
    lerp(5, 0, 1, "F8")
    slot("R8", ZF)
    lerp(6, 4, 5, "F8")
    a("F0 = F6 - F10", "ONE_POLE(d_lp, mix - d_previous, cutoff)")
    a("F0 = F0 - F11")
    slot("R1", CUT)
    a("F0 = F1 * F0")
    a("F11 = F11 + F0")
    a("R10 = PASS R6", "d_previous = mix")
    slot("R1", GAIN)
    a("F0 = F11 * F1", "mix = d_lp * gain")
    a("DM(I0, M6) = R0")
    k("R1", "32")
    a("F2 = F0 * F1", "aux = itof_small((int)(mix * 32.0f)) / 32.0f")
    a("R2 = TRUNC F2")
    k("R3", "1.5x2^23")
    iadd("R2 = R3 + R2")
    a("F2 = F2 - F3")
    slot("R4", Y32)
    a("F5 = F2 * F4", "/ 32.0f: q")
    a("F6 = F1 * F5")
    a("F6 = F2 - F6")
    a("F6 = F6 * F4")
    a("F5 = F5 + F6")
    a("DM(I1, M6) = R5")
    slot("R0", CNT)
    a("R1 = 1")
    iadd("R0 = R0 - R1")
    put(CNT, "R0")
    a("IF NE JUMP _wek_loop")
    lab("_wek_done")
    a("DM(11, I2) = R11")
    a("DM(12, I2) = R10")
    for i, r in enumerate(SAVES):
        slot(r, i + 1)
    a(f"I7=MODIFY (I7,{FRAME})(NW)")
    for i, r in enumerate(reversed(DAGS)):
        a(f"{r} = DM({i + 1}, I7)")
    a("I12 = DM(M7, I6)")
    a("JUMP (M14, I12) (DB)")
    a("RFRAME")
    a("NOP")
    return "\n".join(L) + "\n"


def main() -> None:
    OUT.write_text(HEADER + "\n" + kernel())
    print(OUT)


if __name__ == "__main__":
    main()
