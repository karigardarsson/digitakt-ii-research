.SECTION/PM seg_pmco;
.GLOBAL _tf_render;
.EXTERN _di_frame_hw;
.EXTERN _di_trig;
.EXTERN _di_released;
.EXTERN _di_return_out;
.EXTERN fusion_render.;
.EXTERN _tf_level_tail;
.NOCOMPRESS;
.GLOBAL _tf_level_decode;
// Native unpack FUN_1c24e9: raw SRC field9 has just entered R8.
// It is stock SRC LEV, but type14 owns that saved field as RCVR/AUTO.
// Keep the wire/frame unchanged for _tf_render. Only the native gain consumer
// receives unity. Every other machine gets its original value byte-for-byte.
// M4 is the unpacker's track index (both stereo passes). Use the native stack
// and restore all scratch registers before replaying the exact displaced op.
_tf_level_decode:
    DM(I7, M7) = R0;
    DM(I7, M7) = R1;
    DM(I7, M7) = R2;
    R0 = I4;
    DM(I7, M7) = R0;
    R0 = M4;
    R1 = 0x4a;
    R0 = R0 + R1;
    CALL _di_frame_hw;
    R1 = 14;
    COMP(R0, R1);
    IF NE JUMP _tf_level_restore;
    R8 = 32512;
_tf_level_restore:
    MODIFY(I7, 4) (NW);
    R0 = DM(-3, I7);
    I4 = R0;
    R2 = DM(-2, I7);
    R1 = DM(-1, I7);
    R0 = DM(I7, M5);
    JUMP _tf_level_tail;

_tf_render:
    R8 = R0;
    R9 = R2;
    R10 = I2;
    I5 = _tf_frame;
    DM(14, I5) = R1;
    R0 = R9 + 1;
    CALL _di_frame_hw;
    F0 = FLOAT R0;
    DM(I5, M6) = R0;
    R11 = LSHIFT R9 BY 5;
    R1 = LSHIFT R9 BY 4;
    R11 = R11 + R1;
    R1 = 0x6d;
    R11 = R11 + R1;
    R0 = R11;
    CALL _di_frame_hw;
    F0 = FLOAT R0;
    DM(I5, M6) = R0;
    R0 = R11 + 1;
    CALL _di_frame_hw;
    F0 = FLOAT R0;
    DM(I5, M6) = R0;
    R1 = 2;
    R0 = R11 + R1;
    CALL _di_frame_hw;
    F0 = FLOAT R0;
    DM(I5, M6) = R0;
    R1 = 3;
    R0 = R11 + R1;
    CALL _di_frame_hw;
    DM(I5, M6) = R0;
    R1 = 6;
    R0 = R11 + R1;
    CALL _di_frame_hw;
    F0 = FLOAT R0;
    DM(I5, M6) = R0;
    R1 = 7;
    R0 = R11 + R1;
    CALL _di_frame_hw;
    F0 = FLOAT R0;
    DM(I5, M6) = R0;
    R1 = 8;
    R0 = R11 + R1;
    CALL _di_frame_hw;
    DM(I5, M6) = R0;
    R0 = R8;
    CALL _di_trig;
    DM(I5, M6) = R0;
    R0 = R8;
    CALL _di_released;
    DM(I5, M6) = R0;
    R0 = 0x15;
    CALL _di_frame_hw;
    R1 = -R9;
    R0 = LSHIFT R0 BY R1;
    R1 = 1;
    R0 = R0 AND R1;
    DM(I5, M6) = R0;
    R1 = 9;
    R0 = R11 + R1;
    CALL _di_frame_hw;
    F0 = FLOAT R0;
    DM(I5, M6) = R0;
    R1 = 4;
    R0 = R11 + R1;
    CALL _di_frame_hw;
    F0 = FLOAT R0;
    DM(I5, M6) = R0;
    R1 = 5;
    R0 = R11 + R1;
    CALL _di_frame_hw;
    F0 = FLOAT R0;
    DM(I5, M6) = R0;
    I3 = _tf_save;
    R0 = I6;
    DM(I3, M6) = R0;
    R0 = I7;
    DM(I3, M6) = R0;
    R0 = L6;
    DM(I3, M6) = R0;
    R0 = L7;
    DM(I3, M6) = R0;
    R0 = I13;
    DM(I3, M6) = R0;
    R0 = M12;
    DM(I3, M6) = R0;
    L6 = 0;
    L7 = 0;
    R0 = _tf_stack;
    R1 = 4092;
    R0 = R0 + R1;
    I7 = R0;
    R4 = R8;
    R8 = _tf_frame;
    R12 = R10;
    R2 = I6;
    CJUMP fusion_render. (DB);
    DM(I7, M7) = R2;
    DM(I7, M7) = _tf_back - 1;
_tf_back:
    I3 = _tf_save;
    R0 = DM(I3, M6);
    I6 = R0;
    R0 = DM(I3, M6);
    I7 = R0;
    R0 = DM(I3, M6);
    L6 = R0;
    R0 = DM(I3, M6);
    L7 = R0;
    R0 = DM(I3, M6);
    I13 = R0;
    R0 = DM(I3, M6);
    M12 = R0;
    JUMP _di_return_out;
.SECTION/DM seg_dmda;
