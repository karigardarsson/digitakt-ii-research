// Inline SDK entry, following the pinned Plaits interrupt-safe stack switch.
// Unlike Plaits, render BOTH sides independently: input samples may be stereo.
.SECTION/PM seg_pmco;
.GLOBAL _tw_render;
.GLOBAL tw_slot.;
.EXTERN _di_frame_hw;
.EXTERN _di_trig;
.EXTERN _di_released;
.EXTERN _di_return_out;
.EXTERN twinshot_render.;
.EXTERN _native_slot;
.NOCOMPRESS;

tw_slot.:
    R1 = R8;
    JUMP _native_slot;

_tw_render:
    R8 = R0;
    R9 = R2;
    R10 = I2;
    I5 = _tw_frame;
    R0 = R9 + 1;
    CALL _di_frame_hw;
    F0 = FLOAT R0;
    DM(I5, M6) = R0;
    R11 = LSHIFT R9 BY 5;
    R1 = LSHIFT R9 BY 4;
    R11 = R11 + R1;
    R1 = 0x6d;
    R11 = R11 + R1;
    R0 = R11;
    CALL _di_frame_hw;
    F0 = FLOAT R0;
    DM(I5, M6) = R0;
    R0 = R11 + 1;
    CALL _di_frame_hw;
    F0 = FLOAT R0;
    DM(I5, M6) = R0;
    R1 = 2;
    R0 = R11 + R1;
    CALL _di_frame_hw;
    F0 = FLOAT R0;
    DM(I5, M6) = R0;
    R1 = 3;
    R0 = R11 + R1;
    CALL _di_frame_hw;
    DM(I5, M6) = R0;
    R1 = 6;
    R0 = R11 + R1;
    CALL _di_frame_hw;
    F0 = FLOAT R0;
    DM(I5, M6) = R0;
    R1 = 7;
    R0 = R11 + R1;
    CALL _di_frame_hw;
    F0 = FLOAT R0;
    DM(I5, M6) = R0;
    R1 = 8;
    R0 = R11 + R1;
    CALL _di_frame_hw;
    DM(I5, M6) = R0;
    R0 = R8;
    CALL _di_trig;
    DM(I5, M6) = R0;
    R0 = R8;
    CALL _di_released;
    DM(I5, M6) = R0;
    R0 = 0x15;
    CALL _di_frame_hw;
    R1 = -R9;
    R0 = LSHIFT R0 BY R1;
    R1 = 1;
    R0 = R0 AND R1;
    DM(I5, M6) = R0;

    I3 = _tw_save;
    R0 = I6;
    DM(I3, M6) = R0;
    R0 = I7;
    DM(I3, M6) = R0;
    R0 = L6;
    DM(I3, M6) = R0;
    R0 = L7;
    DM(I3, M6) = R0;
    R0 = I13;
    DM(I3, M6) = R0;
    R0 = M12;
    DM(I3, M6) = R0;
    L6 = 0;
    L7 = 0;
    R0 = _tw_stack;
    R1 = 4092;
    R0 = R0 + R1;
    I7 = R0;
    R4 = R8;
    R8 = _tw_frame;
    R12 = R10;
    R2 = I6;
    CJUMP twinshot_render. (DB);
    DM(I7, M7) = R2;
    DM(I7, M7) = _tw_back - 1;
_tw_back:
    I3 = _tw_save;
    R0 = DM(I3, M6);
    I6 = R0;
    R0 = DM(I3, M6);
    I7 = R0;
    R0 = DM(I3, M6);
    L6 = R0;
    R0 = DM(I3, M6);
    L7 = R0;
    R0 = DM(I3, M6);
    I13 = R0;
    R0 = DM(I3, M6);
    M12 = R0;
    JUMP _di_return_out;

.SECTION/DM seg_dmda;
.PKDATA _tw_frame, 44;
.PKDATA _tw_save, 24;
.PKBSS _tw_stack, 4096;
// Explicit loaded zero data: no first-use reads of unspecified BSS contents.
.PKDATA tw_states., 39296;
.PKDATA tw_generations., 4100;
