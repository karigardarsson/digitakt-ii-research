#!/usr/bin/env python3
"""Helper bodies from tools/sharc_dev/sharc_core: for each form, a plain Rust function
that executes one instruction on the engine state with concrete values.

The same traced decision tree and effect programs as the IR lowering
(tools/sharc_dev/sharc_lowergen.py, tools/sharc_dev/sharc_lowergen_rs.py), printed differently:
register contents are `u32` locals, not kernel values and not V{b,m}; loads
and stores go through `Mem`; data-dependent branches are ordinary Rust. A
kernel calls the body for an instruction it cannot lower
(fast/helper.rs): the body returns 0 when the instruction completed and 1 when
it must be left to the interpreter (an unsupported leaf, a register that is
not fully known, memory that is not plain RAM); before returning 1 it has
written nothing but stores that the interpreter will repeat.

Per form two functions are generated:

- ``h_FORM(s, f) -> u32``: run the instruction (`f` the decoded fields, in the
  order of ``LABELS_FORM``);
- ``t_FORM(s, f, t) -> bool``: which registers the instruction reads and
  writes (`Touch`), false when the leaf for these fields is not supported.

    uv run python -m tools.sharc_dev.sharc_lowergen_helpers packages/emulator/sharc/src/fast/gen_helpers.rs FORM,...
"""

from __future__ import annotations

import sys

from tools.sharc_dev import sharc_lowergen as g
from tools.sharc_dev import sharc_lowergen_rs as r

HEADER = """//! Generated by tools/sharc_dev/sharc_lowergen_helpers.py from tools/sharc_dev/sharc_core: helper
//! bodies, one per instruction form, with concrete values (see that tool).
//! Do not edit.

#![allow(unused_variables, unused_mut, unused_assignments, unused_parens, clippy::all)]

use crate::fast::helper::{RegRead, Touch, hload, hpost, hstore_ok, rr};
use crate::rt::{Int, St, V};

macro_rules! rr {
    ($s:expr, $c:expr) => {
        match rr($s, $c as i128) {
            Some(x) => x,
            None => return 1,
        }
    };
}

macro_rules! rrt {
    ($s:expr, $c:expr) => {
        match rr($s, $c as i128) {
            Some(x) => x,
            None => return false,
        }
    };
}

pub const NF: usize = 16;

"""

OPS = {
    "add": "{a}.wrapping_add({b})",
    "sub": "{a}.wrapping_sub({b})",
    "mul": "{a}.wrapping_mul({b})",
    "and": "({a} & {b})",
    "or": "({a} | {b})",
    "xor": "({a} ^ {b})",
    "shl": "{a}.wrapping_shl({b})",
    "shru": "{a}.wrapping_shr({b})",
}


class HEmit(r.Emitter):
    def __init__(self, fv: dict, declared: set, touch: bool) -> None:
        super().__init__(fv, declared)
        self.touch = touch

    def let(self, vid: int, rhs: str, ind: int) -> None:
        if vid in self.declared:
            self.w(ind, "v%d = %s;" % (vid, rhs))
        else:
            self.w(ind, "let v%d: u32 = %s;" % (vid, rhs))

    def prog(self, prog: list, ind: int) -> None:
        fv = self.fv
        for it in prog:
            k = it[0]
            if k == "refuse":
                self.w(ind, "return %s;" % ("false" if self.touch else "1"))
            elif k == "def":
                vid, op = it[1], it[2]
                if self.touch:
                    if op == "rd":
                        self.w(ind, "t.rd((%s) as u32);" % r.rs_e(it[3], fv))
                    continue
                if op == "const":
                    self.let(vid, "(%s) as u32" % r.rs_e(it[3], fv), ind)
                elif op == "bin":
                    self.let(
                        vid, OPS[it[3]].format(a="v%d" % it[4], b="v%d" % it[5]), ind
                    )
                elif op == "not":
                    self.let(vid, "!v%d" % it[3], ind)
                elif op == "rd":
                    self.let(vid, "rr!(&*s, %s)" % r.rs_e(it[3], fv), ind)
                elif op == "load":
                    self.let(
                        vid,
                        "match hload(&*s, v%d, %s as u32, %s) { Some(x) => x, None => return 1 }"
                        % (it[3], r.rs_e(it[4], fv), "true" if it[5] else "false"),
                        ind,
                    )
                elif op == "postmod":
                    self.let(
                        vid,
                        "match hpost(&*s, (%s + 16) as u32, v%d, v%d, %s as i64) { Some(x) => x, None => return 1 }"
                        % (r.rs_e(it[3], fv), it[4], it[5], r.rs_e(it[6], fv)),
                        ind,
                    )
                else:
                    raise NotImplementedError(op)
            elif k == "wr":
                if self.touch:
                    self.w(ind, "t.wr((%s) as u32);" % r.rs_e(it[1], fv))
                else:
                    self.w(
                        ind,
                        "{ let c = (%s) as usize; if c >= 96 { return 1; } ws[nw] = (c as u8, v%d); nw += 1; }"
                        % (r.rs_e(it[1], fv), it[2]),
                    )
            elif k == "store":
                if not self.touch:
                    self.w(
                        ind,
                        "st[nst] = (v%d, v%d, %s as u8); nst += 1;"
                        % (it[1], it[2], r.rs_e(it[3], fv)),
                    )
            elif k in ("cond", "apply"):
                self.w(ind, "return %s;" % ("false" if self.touch else "1"))
            elif k == "br":
                self.w(ind, "if %s {" % r.rs_p(it[1], fv))
                self.prog(it[2], ind + 1)
                if it[3]:
                    self.w(ind, "} else {")
                    self.prog(it[3], ind + 1)
                self.w(ind, "}")
            elif k == "rbr":
                x = r.rs_e(it[1], fv)
                arms = it[2]
                for n, (ranges, sub) in enumerate(arms):
                    if n < len(arms) - 1:
                        conds = []
                        for lo, hi in ranges:
                            if lo is None:
                                conds.append("%s <= %di128" % (x, hi))
                            elif hi is None:
                                conds.append("%s >= %di128" % (x, lo))
                            elif lo == hi:
                                conds.append("%s == %di128" % (x, lo))
                            else:
                                conds.append(
                                    "(%s >= %di128 && %s <= %di128)" % (x, lo, x, hi)
                                )
                        self.w(
                            ind,
                            ("if " if n == 0 else "} else if ")
                            + " || ".join(conds)
                            + " {",
                        )
                    else:
                        self.w(ind, "} else {")
                    self.prog(sub, ind + 1)
                self.w(ind, "}")
            elif k == "match":
                labels = it[1]
                key = ", ".join(fv[label] for label in labels)
                self.w(ind, "match (%s%s) {" % (key, "," if len(labels) == 1 else ""))
                for valsets, sub in it[2]:
                    alts = []
                    for vals in valsets:
                        pat = ", ".join("%di128" % v for v in vals)
                        alts.append("(%s%s)" % (pat, "," if len(vals) == 1 else ""))
                    self.w(ind + 1, "%s => {" % " | ".join(alts))
                    self.prog(sub, ind + 2)
                    self.w(ind + 1, "}")
                self.w(ind + 1, "_ => unreachable!(),")
                self.w(ind, "}")
            else:
                raise NotImplementedError(k)


def form_fns(name: str, type_name: str) -> list[str]:
    leaves = g.trace_form(name, type_name)
    ids = r.Ids()
    prog = r.fold(r.build_tree(leaves), ids)
    used: set = set()
    r.fields_of_prog(prog, used)
    labels = sorted(used)
    fv = {label: "f%d" % i for i, label in enumerate(labels)}
    declared: set = set()
    r.inner_defs(prog, declared, True)
    out = [
        "pub const LABELS_%s: &[&str] = &[%s];"
        % (name.upper(), ", ".join(r.rs_str(x) for x in labels))
    ]
    r.HELPER_SYMS = "&*s"
    try:
        for touch in (False, True):
            r.HELPER_RR = "rrt" if touch else "rr"
            em = HEmit(fv, declared, touch)
            if touch:
                em.w(
                    0,
                    "pub fn t_%s<S: RegRead>(s: &S, f: &[i64; NF], t: &mut Touch) -> bool {"
                    % name,
                )
            else:
                em.w(0, "pub fn h_%s(s: &mut St, f: &[i64; NF]) -> u32 {" % name)
            for i, _ in enumerate(labels):
                em.w(1, "let f%d = f[%d] as i128;" % (i, i))
            for vid in sorted(declared):
                em.w(1, "let mut v%d: u32 = 0;" % vid)
            if not touch:
                em.w(1, "let mut ws: [(u8, u32); 8] = [(0, 0); 8];")
                em.w(1, "let mut nw = 0usize;")
                em.w(1, "let mut st: [(u32, u32, u8); 4] = [(0, 0, 0); 4];")
                em.w(1, "let mut nst = 0usize;")
            em.prog(prog, 1)
            if touch:
                em.w(1, "true")
            else:
                em.w(
                    1,
                    "for i in 0..nst { if !hstore_ok(s, st[i].0, st[i].1, st[i].2) { return 1; } }",
                )
                em.w(
                    1,
                    "for i in 0..nw { s.r[ws[i].0 as usize] = V::c(ws[i].1 as Int); }",
                )
                em.w(1, "0")
            em.w(0, "}")
            out.extend(em.lines)
    finally:
        r.HELPER_SYMS = None
    return out


def emit_file(names: list[str]) -> str:
    tab = r.type_names()
    out = [HEADER]
    out.append(
        "pub const FORMS: &[&str] = &[%s];\n" % ", ".join(r.rs_str(n) for n in names)
    )
    for n in names:
        out.extend(form_fns(n, tab[n]))
        out.append("")
    out.append("pub fn labels(id: usize) -> &'static [&'static str] {")
    out.append("    match id {")
    for i, n in enumerate(names):
        out.append("        %d => LABELS_%s," % (i, n.upper()))
    out.append("        _ => &[],")
    out.append("    }")
    out.append("}\n")
    out.append("pub fn run(id: usize, s: &mut St, f: &[i64; NF]) -> u32 {")
    out.append("    match id {")
    for i, n in enumerate(names):
        out.append("        %d => h_%s(s, f)," % (i, n))
    out.append("        _ => 1,")
    out.append("    }")
    out.append("}\n")
    out.append(
        "pub fn touch<S: RegRead>(id: usize, s: &S, f: &[i64; NF], t: &mut Touch) -> bool {"
    )
    out.append("    match id {")
    for i, n in enumerate(names):
        out.append("        %d => t_%s(s, f, t)," % (i, n))
    out.append("        _ => false,")
    out.append("    }")
    out.append("}")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    with open(sys.argv[1], "w") as fh:
        fh.write(emit_file(sys.argv[2].split(",")))
