"""Rust emitter for tools/sharc_dev/sharc_lowergen.py: decision trees of effect programs
-> `impl Lower` methods that lower one decoded instruction of a form.

The output holds no firmware: it is a function of tools/sharc_dev/sharc_core and of the
fixed intrinsic set. See docs/findings/18-dsp-performance.md.

Pipeline per form:

1. ``trace_form`` gives the leaves: a path of decisions on static symbols
   (fields, MODE1) and the effect list the handler recorded on that path.
2. Each leaf's effects become *items* over hash-consed value identities
   (pure values are numbered by what they compute, so two leaves that
   compute the same thing agree on the name), with common subexpressions
   and dead values removed.
3. The decision tree is folded into one program: for a decision, the
   programs of its branches share a common prefix and a common suffix; only
   the differing middle stays inside an ``if``/``match``. A form with k
   independent decisions is therefore linear in k, not exponential.
4. The program is printed as Rust over the primitives in gen_prims.rs.
"""

from __future__ import annotations

import json
import os
import re

from tools.sharc_dev import sharc_lowergen as g
from tools.sharc_dev.sharc_lowergen import Leaf, P

BIN_OPS = {
    "add": "Bin::Add",
    "sub": "Bin::Sub",
    "mul": "Bin::Mul",
    "and": "Bin::And",
    "or": "Bin::Or",
    "xor": "Bin::Xor",
    "shl": "Bin::Shl",
    "shru": "Bin::ShrU",
}

HEADER = """//! Generated by tools/sharc_dev/sharc_lowergen.py from tools/sharc_dev/sharc_core: one lowering
//! per instruction form, the decision tree of the core's handler over the
//! decoded fields and MODE1 with each leaf's effects in program order. Do not
//! edit. The primitives are in `gen_prims.rs`.

#![allow(unused_variables, unused_mut, unused_assignments, unused_parens, clippy::all)]

use super::*;

"""


def type_names() -> dict[str, str]:
    d = json.load(open(os.path.join(g.HERE, "sharcspec", "decode_table.json")))  # noqa: SIM115
    tab = {}
    for f in d["forms"]:
        n = re.sub(r"\s*\((\w+)\)", r"_\1", f["name"][4:])
        tab[n] = f["name"]
    return tab


def rs_str(s: str) -> str:
    return '"%s"' % s.replace("\\", "\\\\").replace('"', "'")


# While emitting a helper body: the Rust expression of the engine state `s`
# (or None for the lowering's own `self`). Helper bodies read MODE1, L and B
# from the state at run time.
HELPER_SYMS = None
HELPER_RR = "rr"


def rs_e(e: tuple, fv: dict) -> str:
    """Static expression E as Rust i128 code; FV maps field label -> variable."""
    k = e[0]
    if k == "c":
        return "%di128" % e[1]
    if k == "f":
        return fv[e[1]]
    if k == "v" and HELPER_SYMS is not None:
        if e[1][0] in "LB" and e[1][1:].isdigit():
            return "(%s!(%s, %d) as i128)" % (
                HELPER_RR,
                HELPER_SYMS,
                (48 if e[1][0] == "L" else 64) + int(e[1][1:]),
            )
        return "(%s!(%s, 114) as i128)" % (HELPER_RR, HELPER_SYMS)
    if (
        k == "&"
        and e[1] == ("v", "mode1")
        and e[2][0] == "c"
        and HELPER_SYMS is not None
    ):
        return "((%s!(%s, 114) as i128) & %d)" % (HELPER_RR, HELPER_SYMS, e[2][1])
    if k == "v":
        if e[1][0] in "LB" and e[1][1:].isdigit():
            return "(self.sv_lb(%d)? as i128)" % (
                (48 if e[1][0] == "L" else 64) + int(e[1][1:])
            )
        return {"mode1": "(self.m1(u32::MAX) as i128)"}[e[1]]
    if k == "~":
        return "(!%s)" % rs_e(e[1], fv)
    if k == "&" and e[1] == ("v", "mode1") and e[2][0] == "c":
        return "(self.m1(%#x) as i128)" % e[2][1]
    a, b = rs_e(e[1], fv), rs_e(e[2], fv)
    if k == "//":
        return "(%s).div_euclid(%s)" % (a, b)
    if k in ("<<", ">>"):
        return "((%s) %s (%s as u32))" % (a, k, b)
    return "(%s %s %s)" % (a, k, b)


def rs_p(p: P, fv: dict) -> str:
    return "(%s %s %s)" % (rs_e(p.a, fv), p.op, rs_e(p.b, fv))


# ---------------------------------------------------------------------------
# Decision tree
# ---------------------------------------------------------------------------


def build_tree(leaves, depth=0):
    """Group LEAVES (sharing the first DEPTH path entries) into a tree."""
    if len(leaves) == 1 and len(leaves[0].path) == depth:
        return ("leaf", leaves[0])
    assert all(len(lf.path) > depth for lf in leaves), "a path is a prefix of another"
    kind = leaves[0].path[depth][0]
    if kind == "d":
        p = leaves[0].path[depth][1]
        t = [lf for lf in leaves if lf.path[depth][2]]
        f = [lf for lf in leaves if not lf.path[depth][2]]
        assert t and f, (p, len(t), len(f))
        return ("if", p, build_tree(t, depth + 1), build_tree(f, depth + 1))
    labels = tuple(label for label, _ in leaves[0].path[depth][1])
    by: dict = {}
    for lf in leaves:
        assert tuple(label for label, _ in lf.path[depth][1]) == labels
        by.setdefault(tuple(v for _, v in lf.path[depth][1]), []).append(lf)
    return (
        "match",
        labels,
        [(vals, build_tree(grp, depth + 1)) for vals, grp in sorted(by.items())],
    )


# ---------------------------------------------------------------------------
# Leaf programs: items over hash-consed value identities
# ---------------------------------------------------------------------------


class Ids:
    """Hash-consing of value identities to small integers."""

    def __init__(self) -> None:
        self.table: dict = {}

    def of(self, key: tuple) -> int:
        if key not in self.table:
            self.table[key] = len(self.table)
        return self.table[key]


def leaf_items(lf: Leaf, ids: Ids) -> list:
    """The leaf as a list of items; values by identity, CSE and DCE applied."""
    if lf.refused:
        return [("refuse", lf.refused)]
    ident: dict = {}  # node -> vid
    defs: dict = {}  # vid -> def item
    items: list = []
    ordinal = 0
    consts: dict = {}
    for eff in lf.effects:
        kind = eff[0]
        if kind in ("plain", "advance"):
            continue
        if kind == "const":
            vid = ids.of(("const", eff[2]))
            ident[eff[1]] = vid
            if vid not in defs:
                defs[vid] = ("def", vid, "const", eff[2])
                items.append(defs[vid])
            consts[vid] = eff[2]
        elif kind == "bin":
            a, b = ident[eff[3]], ident[eff[4]]
            if eff[2] == "and":
                if consts.get(b) == ("c", 0xFFFFFFFF):
                    ident[eff[1]] = a
                    continue
                if consts.get(a) == ("c", 0xFFFFFFFF):
                    ident[eff[1]] = b
                    continue
            vid = ids.of(("bin", eff[2], a, b))
            ident[eff[1]] = vid
            if vid not in defs:
                defs[vid] = ("def", vid, "bin", eff[2], a, b)
                items.append(defs[vid])
        elif kind == "not":
            a = ident[eff[2]]
            vid = ids.of(("not", a))
            ident[eff[1]] = vid
            if vid not in defs:
                defs[vid] = ("def", vid, "not", a)
                items.append(defs[vid])
        elif kind == "rd":
            vid = ids.of(("rd", eff[2]))
            ident[eff[1]] = vid
            if vid not in defs:
                defs[vid] = ("def", vid, "rd", eff[2])
                items.append(defs[vid])
        elif kind == "load":
            ordinal += 1
            vid = ids.of(("load", ident[eff[2]], eff[3], eff[4], eff[5], ordinal))
            ident[eff[1]] = vid
            items.append(("def", vid, "load", ident[eff[2]], eff[3], eff[4]))
        elif kind == "postmod":
            ordinal += 1
            vid = ids.of(
                ("postmod", eff[2], ident[eff[3]], ident[eff[4]], eff[5], ordinal)
            )
            ident[eff[1]] = vid
            items.append(
                ("def", vid, "postmod", eff[2], ident[eff[3]], ident[eff[4]], eff[5])
            )
        elif kind == "circ":
            ordinal += 1
            vid = ids.of(
                ("circ", ident[eff[2]], eff[3], eff[4], ident[eff[5]], eff[6], ordinal)
            )
            ident[eff[1]] = vid
            items.append(
                (
                    "def",
                    vid,
                    "circ",
                    ident[eff[2]],
                    eff[3],
                    eff[4],
                    ident[eff[5]],
                    eff[6],
                )
            )
        elif kind == "plainmod":
            items.append(("plainmod", ident[eff[2]]))
        elif kind == "wr":
            v = ident[eff[3]]
            d = defs.get(v)
            if d is not None and d[2] == "rd" and d[3] == eff[2]:
                continue  # a register written back unchanged
            items.append(("wr", eff[2], v))
        elif kind == "store":
            items.append(("store", ident[eff[2]], ident[eff[4]], eff[3]))
        elif kind == "cond":
            items.append(("cond", eff[2], eff[3]))
        elif kind == "apply":
            items.append(("apply", eff[2], eff[3], eff[4]))
        else:
            raise NotImplementedError(kind)
    return dce_items(items)


SIDE = ("wr", "store", "cond", "apply", "plainmod")


def operands(it) -> list:
    if it[0] == "def":
        k = it[2]
        if k == "bin":
            return [it[4], it[5]]
        if k == "not":
            return [it[3]]
        if k == "load":
            return [it[3]]
        if k == "postmod":
            return [it[4], it[5]]
        if k == "circ":
            return [it[3], it[6]]
        return []
    if it[0] == "wr":
        return [it[2]]
    if it[0] == "store":
        return [it[1], it[2]]
    if it[0] == "plainmod":
        return [it[1]]
    return []


def dce_items(items: list) -> list:
    """Drop pure values nothing uses (loads and post-modifies are effects)."""
    used: set = set()
    keep = [False] * len(items)
    for i in range(len(items) - 1, -1, -1):
        it = items[i]
        impure = it[0] in SIDE or (
            it[0] == "def" and it[2] in ("load", "postmod", "circ")
        )
        if impure or (it[0] == "def" and it[1] in used):
            keep[i] = True
            used.update(operands(it))
    return [it for it, k in zip(items, keep, strict=False) if k]


# ---------------------------------------------------------------------------
# Folding the tree into one program
# ---------------------------------------------------------------------------


def _common(progs: list) -> tuple[int, int]:
    """Length of the common prefix and of the common suffix (disjoint)."""
    first = progs[0]
    n = min(len(p) for p in progs)
    i = 0
    while i < n and all(p[i] == first[i] for p in progs):
        i += 1
    j = 0
    while j < n - i and all(
        p[len(p) - 1 - j] == first[len(first) - 1 - j] for p in progs
    ):
        j += 1
    return i, j


def _range_chain(t):
    """A chain `if x <= c1 {A} else if x <= c2 {B} else ... {Z}` on one
    expression: ([(lo, hi, subtree)], expr) with the last arm open-ended."""
    arms = []
    e = None
    lo = None
    while t[0] == "if" and t[1].op in ("<=", "<") and t[1].b[0] == "c":
        if e is None:
            e = t[1].a
        elif t[1].a != e:
            break
        hi = t[1].b[1] - (1 if t[1].op == "<" else 0)
        arms.append((lo, hi, t[2]))
        lo = hi + 1
        t = t[3]
    if len(arms) < 2:
        return None
    arms.append((lo, None, t))
    return arms, e


def fold(t, ids: Ids) -> list:
    if t[0] == "leaf":
        return leaf_items(t[1], ids)
    chain = _range_chain(t) if t[0] == "if" else None
    if chain is not None:
        arms, e = chain
        groups: list = []  # [(ranges, prog)]
        for lo, hi, sub in arms:
            prog = fold(sub, ids)
            for grp in groups:
                if grp[1] == prog:
                    grp[0].append((lo, hi))
                    break
            else:
                groups.append(([(lo, hi)], prog))
        if len(groups) == 1:
            return groups[0][1]
        i, j = _common([p for _, p in groups])
        first = groups[0][1]
        arms_out = [(rs, p[i : len(p) - j]) for rs, p in groups]
        return first[:i] + [("rbr", e, arms_out)] + first[len(first) - j :]
    if t[0] == "if":
        a, b = fold(t[2], ids), fold(t[3], ids)
        if a == b:
            return a
        i, j = _common([a, b])
        return (
            a[:i]
            + [("br", t[1], a[i : len(a) - j], b[i : len(b) - j])]
            + a[len(a) - j :]
        )
    _, labels, arms = t
    progs = [(vals, fold(sub, ids)) for vals, sub in arms]
    groups: list = []  # [(list of vals, prog)]
    for vals, prog in progs:
        for grp in groups:
            if grp[1] == prog:
                grp[0].append(vals)
                break
        else:
            groups.append(([vals], prog))
    if len(groups) == 1:
        return groups[0][1]
    i, j = _common([p for _, p in groups])
    first = groups[0][1]
    arms_out = [(vs, p[i : len(p) - j]) for vs, p in groups]
    return first[:i] + [("match", labels, arms_out)] + first[len(first) - j :]


# ---------------------------------------------------------------------------
# Rust
# ---------------------------------------------------------------------------


def fields_of_prog(prog: list, out: set) -> None:
    def ex(e):
        g._fields_of(e, out)

    for it in prog:
        k = it[0]
        if k == "br":
            ex(it[1].a)
            ex(it[1].b)
            fields_of_prog(it[2], out)
            fields_of_prog(it[3], out)
        elif k == "rbr":
            ex(it[1])
            for _, p in it[2]:
                fields_of_prog(p, out)
        elif k == "match":
            for label in it[1]:
                out.add(label)
            for _, p in it[2]:
                fields_of_prog(p, out)
        elif k == "def":
            if it[2] == "const" or it[2] == "rd":
                ex(it[3])
            elif it[2] == "load":
                ex(it[4])
            elif it[2] == "postmod":
                ex(it[3])
                ex(it[6])
            elif it[2] == "circ":
                ex(it[4])
                ex(it[5])
        elif k == "wr":
            ex(it[1])
        elif k == "store":
            ex(it[3])
        elif k == "cond":
            ex(it[1])


def inner_defs(prog: list, out: set, top: bool) -> None:
    """Value ids defined inside a branch (declared before it)."""
    for it in prog:
        k = it[0]
        if k == "def" and not top:
            out.add(it[1])
        elif k == "br":
            inner_defs(it[2], out, False)
            inner_defs(it[3], out, False)
        elif k in ("match", "rbr"):
            for _, p in it[2]:
                inner_defs(p, out, False)


class Emitter:
    def __init__(self, fv: dict, declared: set) -> None:
        self.lines: list[str] = []
        self.fv = fv
        self.declared = declared  # vids declared up front (assigned, not let)

    def w(self, ind: int, s: str) -> None:
        self.lines.append("    " * ind + s)

    def let(self, vid: int, rhs: str, ind: int) -> None:
        if vid in self.declared:
            self.w(ind, "v%d = %s;" % (vid, rhs))
        else:
            self.w(ind, "let v%d = %s;" % (vid, rhs))

    def prog(self, prog: list, ind: int) -> None:
        fv = self.fv
        for it in prog:
            k = it[0]
            if k == "refuse":
                self.w(ind, "return refuse(%s);" % rs_str(it[1]))
            elif k == "def":
                vid, op = it[1], it[2]
                if op == "const":
                    self.let(vid, "self.ci(%s as u32)" % rs_e(it[3], fv), ind)
                elif op == "bin":
                    self.let(
                        vid,
                        "self.g_bin(%s, v%d, v%d)" % (BIN_OPS[it[3]], it[4], it[5]),
                        ind,
                    )
                elif op == "not":
                    self.let(vid, "self.un(Un::Not, v%d)" % it[3], ind)
                elif op == "rd":
                    self.let(vid, "self.g_rd(%s as u32)?" % rs_e(it[3], fv), ind)
                elif op == "load":
                    self.let(
                        vid,
                        "self.g_load(v%d, %s as u8, %s)?"
                        % (it[3], rs_e(it[4], fv), "true" if it[5] else "false"),
                        ind,
                    )
                elif op == "postmod":
                    self.let(
                        vid,
                        "self.g_postmod((%s + 16) as u32, v%d, v%d, %s as i64)?"
                        % (rs_e(it[3], fv), it[4], it[5], rs_e(it[6], fv)),
                        ind,
                    )
                elif op == "circ":
                    self.let(
                        vid,
                        "{ let b = %s as u32; let n = %s as i64; self.g_circ(v%d, v%d, b, n, %s)? }"
                        % (
                            rs_e(it[4], fv),
                            rs_e(it[5], fv),
                            it[3],
                            it[6],
                            "true" if it[7] else "false",
                        ),
                        ind,
                    )
                else:
                    raise NotImplementedError(op)
            elif k == "plainmod":
                self.w(ind, "self.g_plainmod(v%d)?;" % it[1])
            elif k == "wr":
                self.w(ind, "self.g_wr(%s as u32, v%d)?;" % (rs_e(it[1], fv), it[2]))
            elif k == "store":
                self.w(
                    ind,
                    "self.g_store(v%d, v%d, %s as u8)?;"
                    % (it[1], it[2], rs_e(it[3], fv)),
                )
            elif k == "cond":
                self.w(
                    ind,
                    "self.g_cond(%s as u32, %s)?;"
                    % (rs_e(it[1], fv), "true" if it[2] == "y" else "false"),
                )
            elif k == "apply":
                self.w(
                    ind,
                    "self.g_apply(d, %s, %s, %s)?;"
                    % (
                        rs_str(it[1]),
                        "true" if it[2] == "y" else "false",
                        "true" if it[3] else "false",
                    ),
                )
            elif k == "br":
                self.w(ind, "if %s {" % rs_p(it[1], fv))
                self.prog(it[2], ind + 1)
                if it[3]:
                    self.w(ind, "} else {")
                    self.prog(it[3], ind + 1)
                self.w(ind, "}")
            elif k == "rbr":
                x = rs_e(it[1], fv)
                arms = it[2]
                for n, (ranges, sub) in enumerate(arms):
                    if n < len(arms) - 1:
                        conds = []
                        for lo, hi in ranges:
                            if lo is None:
                                conds.append("%s <= %di128" % (x, hi))
                            elif hi is None:
                                conds.append("%s >= %di128" % (x, lo))
                            elif lo == hi:
                                conds.append("%s == %di128" % (x, lo))
                            else:
                                conds.append(
                                    "(%s >= %di128 && %s <= %di128)" % (x, lo, x, hi)
                                )
                        self.w(
                            ind,
                            ("if " if n == 0 else "} else if ")
                            + " || ".join(conds)
                            + " {",
                        )
                    else:
                        self.w(ind, "} else {")
                    self.prog(sub, ind + 1)
                self.w(ind, "}")
            elif k == "match":
                labels = it[1]
                key = ", ".join(fv[label] for label in labels)
                self.w(ind, "match (%s%s) {" % (key, "," if len(labels) == 1 else ""))
                for valsets, sub in it[2]:
                    alts = []
                    for vals in valsets:
                        pat = ", ".join("%di128" % v for v in vals)
                        alts.append("(%s%s)" % (pat, "," if len(vals) == 1 else ""))
                    self.w(ind + 1, "%s => {" % " | ".join(alts))
                    self.prog(sub, ind + 2)
                    self.w(ind + 1, "}")
                self.w(ind + 1, "_ => unreachable!(),")
                self.w(ind, "}")
            else:
                raise NotImplementedError(k)


def emit_form(name: str, type_name: str) -> list[str]:
    leaves = g.trace_form(name, type_name)
    ids = Ids()
    prog = fold(build_tree(leaves), ids)
    used: set = set()
    fields_of_prog(prog, used)
    labels = sorted(used)
    fv = {label: "f%d" % i for i, label in enumerate(labels)}
    declared: set = set()
    inner_defs(prog, declared, True)
    em = Emitter(fv, declared)
    em.w(1, "pub fn g_%s(&mut self, d: &Dec) -> LR<()> {" % name)
    em.w(2, "if !self.env.assume_nw32 {")
    em.w(3, 'return refuse("assume_nw32 off");')
    em.w(2, "}")
    for label in labels:
        em.w(
            2,
            "let %s = d.get(%s).ok_or(Refuse(%s.into()))? as i128;"
            % (fv[label], rs_str(label), rs_str("missing field " + label)),
        )
    for vid in sorted(declared):
        em.w(2, "let mut v%d: Val = 0;" % vid)
    em.prog(prog, 2)
    em.w(2, "Ok(())")
    em.w(1, "}")
    return em.lines


def emit_file(names: list[str]) -> str:
    tab = type_names()
    out = [HEADER]
    out.append(
        "pub const GENERATED: &[&str] = &[%s];\n" % ", ".join(rs_str(n) for n in names)
    )
    out.append("pub fn dispatch(l: &mut Lower, d: &Dec) -> LR<bool> {")
    out.append("    match d.form {")
    for n in names:
        out.append("        %s => l.g_%s(d).map(|_| true)," % (rs_str(n), n))
    out.append("        _ => Ok(false),")
    out.append("    }")
    out.append("}\n")
    out.append("impl Lower {")
    for n in names:
        out.extend(emit_form(n, tab[n]))
    out.append("}")
    return "\n".join(out) + "\n"


