#!/usr/bin/env python3
"""Random instruction encodings per form, for the generated-lowering fuzz test.

Writes packages/emulator/sharc/src/tests_gen_vectors.rs: for each form NAME, N words
built from tools/sharc_dev/sharcspec/decode_table.json (the fixed bits of the form, then
a random value in every field). Firmware-free. The Rust test
(packages/emulator/sharc/src/tests_gen.rs) runs each on the interpreter and on the fast
tier and compares the machine state.

    uv run python -m tools.sharc_dev.sharc_lowergen_vectors --out packages/emulator/sharc/src/tests_gen_vectors.rs 4a 3a ...
"""

from __future__ import annotations

import argparse
import json
import os
import random
import re

HERE = os.path.dirname(os.path.abspath(__file__))

# Compute fields (cu, opcode) the fast tier lowers: the fuzz picks these most
# of the time so that the transfer half of a 4a/3a is not always refused.
COMPUTE_MENU = [
    (0, 0x01),
    (0, 0x02),
    (0, 0x40),
    (0, 0x41),
    (0, 0x81),
    (0, 0x82),
    (0, 0x21),
]


def load() -> dict:
    d = json.load(open(os.path.join(HERE, "sharcspec", "decode_table.json")))  # noqa: SIM115
    out = {}
    for f in d["forms"]:
        out[re.sub(r"\s*\((\w+)\)", r"_\1", f["name"][4:])] = f
    return out


def pick(rng: random.Random, label: str, width: int, form: str) -> int:
    top = (1 << width) - 1
    stem = label.split("[")[0]
    if stem == "cond" and rng.random() < 0.75:
        return 0x1F if width == 5 else top
    if stem in ("l", "w", "x") and form.startswith(("3", "4")):
        return rng.choice([0, 1])
    if form in ("14a", "15a") and stem == "addr":
        # Inside the test engine's data block (0x25f000..) most of the time.
        base = 0x25F000 + 4 * rng.randint(0, 0x80)
        if form == "15a":
            base = 4 * rng.randint(0, 0x20)  # an offset from Ia
        if rng.random() < 0.8:
            return (base >> 16) if label.endswith("[31:16]") else (base & 0xFFFF)
    if stem in ("ureg", "dstureg", "dreg") and width == 7 and rng.random() < 0.25:
        # The system registers the lowering holds as plain words
        # (packages/emulator/sharc/src/fast/lower/sysops.rs `plain_sys`).
        return rng.choice([108, 109, 112, 113, 115, 116, 126, 127])
    if form == "18a":
        if stem == "sreg" and rng.random() < 0.8:
            return 2  # MODE1
        if label == "data[31:16]" and rng.random() < 0.8:
            return rng.choice([0x20, 0x20, 0x00, 0x30, 0x1000])
        if label == "data[15:0]" and rng.random() < 0.8:
            return 0
        if stem == "bop" and rng.random() < 0.8:
            return rng.choice([0, 1])
    return rng.randint(0, top)


def encode(f: dict, rng: random.Random, name: str) -> tuple[int, int]:
    word = int(f["value"], 16)
    labels = {x["label"]: x for x in f["fields"]}
    vals: dict[str, int] = {}
    for label, x in labels.items():
        width = x["hi"] - x["lo"] + 1
        v = pick(rng, label, width, name)
        vals[label] = v
    # A compute field (22:16 / 15:0): mostly empty or a lowered operation.
    if "compute[22:16]" in vals:
        r = rng.random()
        if r < 0.3:
            c = 0
        elif r < 0.8:
            cu, op = rng.choice(COMPUTE_MENU)
            c = (
                (cu << 20)
                | (op << 12)
                | (rng.randint(0, 15) << 8)
                | (rng.randint(0, 15) << 4)
                | rng.randint(0, 15)
            )
        else:
            c = rng.randint(0, (1 << 23) - 1)
        vals["compute[22:16]"] = c >> 16
        vals["compute[15:0]"] = c & 0xFFFF
    if name in ("19a", "19a_scaled") and "data[31:16]" in vals:
        # A small signed immediate: a large one is a refused circular modifier.
        d = rng.randint(-8, 8) & 0xFFFFFFFF
        vals["data[31:16]"], vals["data[15:0]"] = d >> 16, d & 0xFFFF
    for label, v in vals.items():
        x = labels[label]
        word |= v << x["lo"]
    return word, f["width"]


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("forms", nargs="+")
    ap.add_argument("--n", type=int, default=48)
    ap.add_argument("--seed", type=int, default=7)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    tab = load()
    lines = [
        "// Generated by tools/sharc_dev/sharc_lowergen_vectors.py. Random encodings per form",
        "// (form, parcels, first three short words of the instruction).",
        "pub const VECTORS: &[(&str, u8, [u16; 3])] = &[",
    ]
    for name in a.forms:
        f = tab[name]
        rng = random.Random("%s/%d" % (name, a.seed))
        for _ in range(a.n):
            word, width = encode(f, rng, name)
            parcels = width // 16
            ps = [(word >> 32) & 0xFFFF, (word >> 16) & 0xFFFF, word & 0xFFFF]
            lines.append(
                '    ("%s", %d, [%#06x, %#06x, %#06x]),' % (name, parcels, *ps)
            )
    lines.append("];")
    open(a.out, "w").write("\n".join(lines) + "\n")  # noqa: SIM115


if __name__ == "__main__":
    main()
